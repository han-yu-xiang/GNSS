runIds=strings(n,1);runs=zeros(n,1);wins=zeros(n,1);linked=zeros(n,1);mpcs=zeros(n,1);boundary=zeros(n,1);
for j=1:n,scene=scenes(j);r=string(stage2.scene_id)==scene;u=unique(string(stage2.run_id(r)),'stable');runIds(j)=strjoin(u,'|');runs(j)=numel(u);q=string(w.scene_id)==scene;wins(j)=sum(q);linked(j)=sum(q&w.cir_link_status=="CIR_PDP_VERIFIED");mpcs(j)=sum(doubleColumn(stage2.is_multipath(r))==1);boundary(j)=sum(q&w.pdp_peak_at_grid_boundary);end
