function summary = run_mainline_1023_gate_ef_audit(projectRoot, releaseRoot, cohortPath, stage2LedgerPath, alphaLedgerPath, stage2InputManifestPath, wp5ProvenancePath, outputDirectory, executionMode, selectedRunIds)
%RUN_MAINLINE_1023_GATE_EF_AUDIT Read-only full Mainline Gate E/F audit.
% CIR matrices are read in bounded blocks. Only outputDirectory is written.
% executionMode='preflight' runs the exact frozen identity/table checks and
% returns before opening any Stage0 or HDF5 scientific payload.
if nargin < 9 || strlength(string(executionMode)) == 0
    executionMode = "audit";
end
if nargin < 10
    selectedRunIds = strings(0, 1);
end
executionMode = lower(string(executionMode));
assert(ismember(executionMode, ["audit","preflight"]), ...
    'GNSS:SAGE:GateEModeInvalid', ...
    'executionMode must be audit or preflight.');
projectRoot = canonicalPath(projectRoot);
releaseRoot = canonicalPath(releaseRoot);
cohortPath = canonicalPath(cohortPath);
stage2LedgerPath = canonicalPath(stage2LedgerPath);
alphaLedgerPath = canonicalPath(alphaLedgerPath);
stage2InputManifestPath = canonicalPath(stage2InputManifestPath);
wp5ProvenancePath = canonicalPath(wp5ProvenancePath);
outputDirectory = canonicalPath(outputDirectory);
assert(isfolder(projectRoot) && isfolder(releaseRoot) && isfile(cohortPath) ...
    && isfile(stage2LedgerPath) && isfile(alphaLedgerPath) ...
    && isfile(stage2InputManifestPath) && isfile(wp5ProvenancePath), ...
    'GNSS:SAGE:GateFInputMissing', ...
    'A frozen input path is missing.');
assert(~isfolder(outputDirectory) && ~isfile(outputDirectory), ...
    'GNSS:SAGE:GateFOutputAlreadyExists', ...
    'Refusing to overwrite an existing result directory.');
[ok, message] = mkdir(outputDirectory);
assert(ok, 'GNSS:SAGE:GateFOutputCreateFailed', '%s', message);
diary(fullfile(outputDirectory, 'gate_e_f_execution.log'));

requestPath = fullfile(releaseRoot, 'release_request.json');
request = readJson(requestPath);
batchAudit = readJson(fullfile(releaseRoot, 'cir_batch_audit.json'));
completion = readJson(fullfile(releaseRoot, 'cir_batch_completion_receipt.json'));
cohort = readJson(cohortPath);
requestSha = sha256File(requestPath);
cohortSha = sha256File(cohortPath);
assert(string(request.release_id) == string(getFolderName(releaseRoot)) ...
    && lower(string(batchAudit.release_request_sha256)) == requestSha ...
    && lower(string(completion.request_sha256)) == requestSha ...
    && string(batchAudit.status) == "COMPLETE" ...
    && string(completion.status) == "PASS" && ~logical(request.resume) ...
    && ~logical(request.batch_policy.automatic_retry) ...
    && double(request.batch_policy.max_parallel_matlab) == 1, ...
    'GNSS:SAGE:GateEReleaseIdentityMismatch', ...
    'Release identity, final receipts, or serial/no-retry policy mismatch.');

frozenIds = string(request.frozen_cohort_run_ids(:));
cohortIds = fieldStrings(cohort.tasks, 'run_id');
newIds = fieldStrings(request.tasks, 'run_id');
skipIds = fieldStrings(request.skipped_existing_pass, 'run_id');
completedIds = fieldStrings(completion.tasks, 'run_id');
assert(numel(frozenIds) == 83 && numel(unique(frozenIds)) == 83 ...
    && isequal(cohortIds, frozenIds) && numel(newIds) == 43 ...
    && numel(skipIds) == 40 && numel(unique([newIds; skipIds])) == 83 ...
    && isequal(newIds, frozenIds(~ismember(frozenIds, skipIds))) ...
    && isequal(skipIds, frozenIds(~ismember(frozenIds, newIds))) ...
    && isequal(completedIds, newIds) && numel(batchAudit.completed_tasks) == 43 ...
    && strlength(string(batchAudit.stop_receipt_path)) == 0, ...
    'GNSS:SAGE:GateEPopulationMismatch', ...
    'Frozen, new, skipped, completion and audit identities disagree.');
skipTypes = fieldStrings(request.skipped_existing_pass, 'receipt_type');
assert(sum(skipTypes == "CIR_BATCH_PASS") == 37 ...
    && sum(skipTypes == "CIR_PILOT") == 2 ...
    && sum(skipTypes == "EXISTING_BASELINE_READBACK") == 1, ...
    'GNSS:SAGE:GateEPassPopulationMismatch', ...
    'The 37 inherited PASS and three pilot/baseline items do not match policy.');
selectedRunIds = string(selectedRunIds(:));
if isempty(selectedRunIds)
    runIndices = (1:83).';
else
    assert(numel(unique(selectedRunIds)) == numel(selectedRunIds) ...
        && all(ismember(selectedRunIds, frozenIds)), ...
        'GNSS:SAGE:GateERunSelectionInvalid', ...
        'Selected audit run IDs must be unique members of the frozen 83-run cohort.');
    runIndices = find(ismember(frozenIds, selectedRunIds));
    assert(numel(runIndices) == numel(selectedRunIds), ...
        'GNSS:SAGE:GateERunSelectionInvalid', ...
        'At least one selected run ID is not present in the frozen cohort.');
end

stage2 = readtable(stage2LedgerPath, 'Delimiter', ',', ...
    'ReadVariableNames', true, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
alpha = readtable(alphaLedgerPath, 'Delimiter', ',', ...
    'ReadVariableNames', true, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
stage2InputManifest = readtable(stage2InputManifestPath, ...
    'Delimiter', ',', 'ReadVariableNames', true, ...
    'TextType', 'string', 'VariableNamingRule', 'preserve');
inputManifestIds = string(stage2InputManifest.run_id(:));
wp5Provenance = readJson(wp5ProvenancePath);
stage2LedgerSha = sha256File(stage2LedgerPath);
alphaLedgerSha = sha256File(alphaLedgerPath);
inputManifestSha = sha256File(stage2InputManifestPath);
provenanceSha = sha256File(wp5ProvenancePath);
alphaLedgerOutputField = matlab.lang.makeValidName( ...
    'stage2_modeling_ledger_all_paths.csv');
assert(string(wp5Provenance.record_type) == ...
    "RETROSPECTIVE_SOURCE_SNAPSHOT_BINDING" ...
    && lower(string(wp5Provenance.frozen_input_sha256.cohort)) == cohortSha ...
    && lower(string(wp5Provenance.frozen_input_sha256.stage2_ledger)) == stage2LedgerSha ...
    && lower(string(wp5Provenance.frozen_input_sha256.input_manifest)) == inputManifestSha ...
    && isfield(wp5Provenance.output_sha256,alphaLedgerOutputField) ...
    && lower(string(wp5Provenance.output_sha256.(alphaLedgerOutputField))) == alphaLedgerSha, ...
    'GNSS:SAGE:GateEProvenancePinMismatch', ...
    'WP5 provenance does not pin the observed cohort, Stage2 ledger, input manifest and alpha ledger.');
stage2Key = pathKey(stage2.run_id, stage2.window_id, stage2.path_id);
alphaKey = pathKey(alpha.run_id, alpha.window_id, alpha.path_id);
assert(height(stage2) == 16761 && height(alpha) == 16761 ...
    && height(stage2InputManifest) == 83 ...
    && numel(unique(inputManifestIds)) == 83 ...
    && isequal(inputManifestIds, frozenIds) ...
    && all(string(stage2InputManifest.preflight_status) == "READY") ...
    && numel(unique(stage2Key)) == height(stage2) ...
    && numel(unique(alphaKey)) == height(alpha) ...
    && isequal(sort(stage2Key), sort(alphaKey)) ...
    && sum(doubleColumn(stage2.is_multipath) == 1) == 8914 ...
    && numel(unique(windowKey(stage2.run_id, stage2.window_id))) == 7847, ...
    'GNSS:SAGE:GateEStage2IdentityMismatch', ...
    'Stage2 ledger, WP5 alpha and frozen path/window counts disagree.');

if executionMode == "preflight"
    summary = struct('preflight_status','PASS', ...
        'release_id',char(request.release_id), ...
        'release_request_sha256',char(requestSha), ...
        'cohort_sha256',char(cohortSha), ...
        'stage2_ledger_sha256',char(stage2LedgerSha), ...
        'alpha_ledger_sha256',char(alphaLedgerSha), ...
        'stage2_input_manifest_sha256',char(inputManifestSha), ...
        'wp5_provenance_sha256',char(provenanceSha), ...
        'run_count',83,'new_release_task_count',43, ...
        'inherited_pass_count',37,'pilot_baseline_count',3, ...
        'stage2_path_count',height(stage2), ...
        'stage2_window_count',numel(unique(windowKey(stage2.run_id,stage2.window_id))), ...
        'stage2_mpc_count',sum(doubleColumn(stage2.is_multipath) == 1));
    writeJson(fullfile(outputDirectory,'gate_e_f_preflight.json'),summary);
    fprintf('GATE_EF_PREFLIGHT=PASS release=%s request_sha256=%s runs=%d new=%d inherited=%d pilots=%d stage2_paths=%d windows=%d mpc=%d\n', ...
        request.release_id,requestSha,summary.run_count, ...
        summary.new_release_task_count,summary.inherited_pass_count, ...
        summary.pilot_baseline_count,summary.stage2_path_count, ...
        summary.stage2_window_count,summary.stage2_mpc_count);
    diary off;
    return
end

runRecords = repmat(emptyRunRecord(), numel(runIndices), 1);
windowParts = cell(numel(runIndices), 1);
anomalies = table(strings(0,1), strings(0,1), strings(0,1), ...
    'VariableNames', {'run_id','category','detail'});
fprintf('GATE_EF_BEGIN_UTC=%s\n', utcNow());
for outputIndex = 1:numel(runIndices)
    k = runIndices(outputIndex);
    task = recordAt(cohort.tasks, k);
    runId = string(task.run_id);
    sceneId = string(task.scene_id);
    stage2Run = stage2(string(stage2.run_id) == runId, :);
    rec = emptyRunRecord();
    rec.run_id = runId;
    rec.scene_id = sceneId;
    rec.prn = string(task.prn);
    rec.channel = double(task.tracking_channel);
    rec.stage2_paths = height(stage2Run);
    rec.stage2_windows = numel(unique(doubleColumn(stage2Run.window_id)));
    rec.stage2_mpc = sum(doubleColumn(stage2Run.is_multipath) == 1);
    windowParts{k} = buildWindows(stage2Run, rec, []);
    fprintf('GATE_EF_RUN_START=%d/83 %s\n', k, runId);
    try
        manifestRow = find(inputManifestIds == runId, 1);
        assert(~isempty(manifestRow), 'GNSS:SAGE:GateEManifestRunMissing', ...
            'WP5 manifest missing %s.', runId);
        [src, rec] = auditRun(projectRoot, releaseRoot, request, ...
            completion, requestSha, cohortSha, task, stage2Run, ...
            stage2InputManifest, manifestRow, rec);
        stage0 = readtable(src.stage0_path, 'Delimiter', ',', ...
            'ReadVariableNames', true, 'TextType', 'string', ...
            'VariableNamingRule', 'preserve');
        assert(height(stage0) == double(src.metadata.stage0_window_count), ...
            'GNSS:SAGE:GateEStage0CountMismatch', ...
            'Stage0 source row count differs from the recorded baseline/production count.');
        h5 = audit_gnss_code_domain_cir_pdp(src.hdf5_path, stage0);
        assert(string(h5.amplitude_reference_status) == ...
            rec.amplitude_reference_status, ...
            'GNSS:SAGE:GateFAmplitudeReferenceMismatch', ...
            'HDF5 and JSON metadata amplitude reference status differ.');
        rec.stage0_windows = h5.window_count;
        rec.cir_snapshots = h5.snapshot_count;
        rec.pdp_windows = h5.window_count;
        rec.delay_bins = h5.delay_count;
        rec.pdp_max_abs_diff = h5.max_abs_pdp_difference;
        rec.pdp_max_rel_diff = h5.max_relative_pdp_difference;
        rec.pdp_absolute_tolerance = h5.pdp_absolute_tolerance;
        rec.pdp_relative_tolerance = h5.pdp_relative_tolerance;
        rec.pdp_status = "PASS";
        rec.gate_f = "PASS";
        windowParts{k} = buildWindows(stage2Run, rec, h5.window_features);
        fprintf('GATE_EF_RUN_DONE=%d/83 %s STAGE0=%d CIR=%dx%d STAGE2_WINDOWS=%d MPC=%d PDP_MAX_DIFF=%.17g E=%s\n', ...
            k, runId, rec.stage0_windows, rec.cir_snapshots, rec.delay_bins, ...
            rec.stage2_windows, rec.stage2_mpc, rec.pdp_max_abs_diff, rec.gate_e);
    catch ex
        rec.gate_e = "FAIL";
        rec.gate_f = "NOT_VERIFIED";
        rec.failure_id = string(ex.identifier);
        rec.failure = string(ex.message);
        anomalies = [anomalies; table(runId, string(ex.identifier), ...
            string(ex.message), 'VariableNames', anomalies.Properties.VariableNames)]; %#ok<AGROW>
        windowParts{k} = buildWindows(stage2Run, rec, []);
        fprintf('GATE_EF_RUN_FAIL=%d/83 %s %s %s\n', k, runId, ex.identifier, ex.message);
    end
    runRecords(outputIndex) = rec;
end

stage2WindowFeatures = vertcat(windowParts{:});
links = build_mainline_stage2_cir_gate_f_links(stage2, alpha, stage2WindowFeatures);
assert(height(links.stage2_window_features) == 7847 ...
    && height(links.stage2_mpc_linkage) == 8914 ...
    && links.counts.stage2_path_rows == 16761, ...
    'GNSS:SAGE:GateFLinkPopulationMismatch', ...
    'Stage2 identity-preserving join changed a frozen row count.');
inventory = struct2table(runRecords);
sceneSummary = summarizeScenes(stage2, links.stage2_window_features);
linked = sum(links.stage2_window_features.cir_link_status == "CIR_PDP_VERIFIED");
boundary = sum(links.stage2_window_features.pdp_peak_at_grid_boundary);
allE = all(ismember(inventory.gate_e, ["PASS","PASS_WITH_LIMITATIONS"]));
allF = all(inventory.gate_f == "PASS");
fullCohortAudit = numel(runIndices) == 83;
if fullCohortAudit
    auditScope = "FULL_83_RUN_COHORT";
else
    auditScope = "SELECTED_RUN_SUPPLEMENT";
end
if fullCohortAudit && allE && allF && linked == 7847 ...
        && links.counts.unmatched_stage2_windows == 0 ...
        && links.counts.alpha_missing_mpc_rows == 0 ...
        && links.counts.alpha_unavailable_path_rows == 0 ...
        && links.counts.relative_power_recomputed_mismatch_all_rows == 0
    gateE = "PASS";
    if any(inventory.hdf5_sha_status == "OBSERVED_UNPINNED_BASELINE")
        gateE = "PASS_WITH_LIMITATIONS";
    end
    gateF = "PASS_WITH_LIMITATIONS";
elseif fullCohortAudit
    gateE = "FAIL";
    gateF = "FAIL";
else
    gateE = "SUPPLEMENTAL_NOT_AGGREGATED";
    gateF = "SUPPLEMENTAL_NOT_AGGREGATED";
end
summary = struct('created_utc',utcNow(), ...
    'release_id',char(request.release_id), ...
    'release_request_sha256',requestSha,'cohort_sha256',cohortSha, ...
    'stage2_ledger_sha256',sha256File(stage2LedgerPath), ...
    'alpha_ledger_sha256',sha256File(alphaLedgerPath), ...
    'stage2_input_manifest_sha256',sha256File(stage2InputManifestPath), ...
    'wp5_provenance_path',wp5ProvenancePath, ...
    'wp5_provenance_sha256',provenanceSha, ...
    'gate_e_status',char(gateE),'gate_f_status',char(gateF), ...
    'run_count',numel(runIndices),'audit_scope',char(auditScope), ...
    'current_release_pass_count',43, ...
    'inherited_formal_pass_count',37,'pilot_baseline_count',3, ...
    'formal_pass_count',80,'stage2_path_count',16761, ...
    'stage2_window_count',7847,'stage2_mpc_count',8914, ...
    'stage2_direct_reference_count',7847, ...
    'cir_linked_stage2_windows',linked, ...
    'unmatched_stage2_windows',links.counts.unmatched_stage2_windows, ...
    'unmatched_mpc_alpha',links.counts.alpha_missing_mpc_rows, ...
    'alpha_missing_stage2_path_rows',links.counts.alpha_missing_path_rows, ...
    'alpha_unavailable_stage2_path_rows',links.counts.alpha_unavailable_path_rows, ...
    'relative_power_recomputed_pass',links.counts.relative_power_recomputed_pass, ...
    'relative_power_recomputed_mismatch',links.counts.relative_power_recomputed_mismatch, ...
    'relative_power_recomputed_pass_all_rows',links.counts.relative_power_recomputed_pass_all_rows, ...
    'relative_power_recomputed_mismatch_all_rows',links.counts.relative_power_recomputed_mismatch_all_rows, ...
    'direct_reference_relative_power_mismatch',links.counts.direct_reference_relative_power_mismatch, ...
    'pdp_boundary_peak_windows',boundary, ...
    'pdp_boundary_peak_fraction',boundary/max(linked,1), ...
    'max_pdp_abs_difference',maxFinite(inventory.pdp_max_abs_diff), ...
    'max_pdp_relative_difference',maxFinite(inventory.pdp_max_rel_diff), ...
    'pdp_recomputation_absolute_tolerance', ...
    maxFinite(inventory.pdp_absolute_tolerance), ...
    'pdp_recomputation_relative_tolerance', ...
    maxFinite(inventory.pdp_relative_tolerance), ...
    'alpha_math_checked_path_rows',links.counts.alpha_math_checked_paths, ...
    'alpha_extra_path_rows',links.counts.alpha_extra_rows, ...
    'mpc_count_distribution',mpcDistribution(links.stage2_window_features.stage2_mpc_count), ...
    'scientific_limitations',{{ ...
    'CIR is raw-IQ NAV/code/Doppler-wiped code-domain correlation using Stage0 tracking inputs; it is not reconstructed from SAGE alpha and is not calibrated independent channel truth.', ...
    'PDP is the arithmetic mean of 40 one-ms CIR snapshot powers, not coherent summation.', ...
    'Overlapping Stage0 windows share samples and are not independent.', ...
    'Reported PDP RMS width is a signed code-delay correlation width, not a validated physical multipath RMS delay spread.', ...
    'Boundary-bin PDP peaks are retained and reported without changing the frozen delay grid.', ...
    'WP5 alpha linkage verifies identity only; it does not prove cross-window phase coherence, absolute gain or reflector tracking.', ...
    'The one legacy baseline read-back predates cohort/Stage0/HDF5 SHA pins. Its Stage2 CSV and frozen SAGE identity are bound by the WP5 manifest; Stage0 rows are observed beside that source and checked against every HDF5 window; HDF5 SHA is observed but not historically receipt-pinned.'}});
writetable(inventory, fullfile(outputDirectory,'gate_e_run_inventory.csv'));
writetable(links.stage2_window_features, fullfile(outputDirectory,'stage2_cir_pdp_window_features.csv'));
writetable(links.stage2_mpc_linkage, fullfile(outputDirectory,'stage2_mpc_cir_alpha_linkage.csv'));
writetable(sceneSummary, fullfile(outputDirectory,'gate_f_scene_summary.csv'));
writetable(anomalies, fullfile(outputDirectory,'gate_e_f_anomalies.csv'));
writeJson(fullfile(outputDirectory,'gate_e_f_summary.json'),summary);
writeJson(fullfile(outputDirectory,'execution_manifest.json'), ...
    struct('request_path',requestPath,'request_sha256',requestSha, ...
    'cohort_path',cohortPath,'cohort_sha256',cohortSha, ...
    'stage2_ledger_path',stage2LedgerPath, ...
    'stage2_ledger_sha256',sha256File(stage2LedgerPath), ...
    'alpha_ledger_path',alphaLedgerPath, ...
    'alpha_ledger_sha256',sha256File(alphaLedgerPath), ...
    'stage2_input_manifest_path',stage2InputManifestPath, ...
    'stage2_input_manifest_sha256',sha256File(stage2InputManifestPath), ...
    'wp5_provenance_path',wp5ProvenancePath, ...
    'wp5_provenance_sha256',provenanceSha, ...
    'chunk_rows',64,'matlab_version',version));
fprintf('GATE_E_STATUS=%s\nGATE_F_STATUS=%s\n',gateE,gateF);
fprintf('GATE_EF_COUNTS audit_runs=%d formal=80 stage2paths=16761 windows=7847 mpc=8914 linked=%d unmatched=%d alphaMissing=%d boundary=%d/%d\n', ...
    numel(runIndices), ...
    linked,links.counts.unmatched_stage2_windows, ...
    links.counts.alpha_missing_mpc_rows,boundary,linked);
fprintf('GATE_EF_END_UTC=%s\n',utcNow());
diary off;
end

function [src,rec] = auditRun(projectRoot,releaseRoot,request,completion,requestSha,cohortSha,task,stage2Run,stage2InputManifest,manifestRow,rec)
runId=string(task.run_id);
[src,~]=getEvidence(projectRoot,releaseRoot,request,completion,requestSha,runId);
rec.receipt_type=src.receipt_type;
rec.receipt_path=string(src.receipt_path);
rec.receipt_status=src.receipt_status;
rec.receipt_sha_actual=sha256File(src.receipt_path);
assert(rec.receipt_sha_actual==src.receipt_sha_expected && src.receipt_status=="PASS" ...
    && src.receipt_run_id==runId && src.receipt_request_sha==src.source_request_sha_expected ...
    && src.source_request_sha_actual==src.source_request_sha_expected, ...
    'GNSS:SAGE:GateEReceiptMismatch','Receipt/source release mismatch for %s.',runId);
if src.current_release
    assert(src.receipt_request_sha==requestSha && startsWith(lower(string(src.hdf5_path)),lower(string([releaseRoot,filesep]))), ...
        'GNSS:SAGE:GateENamespaceMismatch','Current HDF5 is outside the release namespace.');
end
if src.identity_run_id~=""
    assert(src.identity_run_id==runId && src.identity_scene==string(task.scene_id) ...
        && src.identity_prn==string(task.prn) && src.identity_channel==double(task.tracking_channel), ...
        'GNSS:SAGE:GateEReceiptIdentityMismatch','Receipt identity mismatch.');
end
m=src.metadata;
legacyBaseline = src.receipt_type == "EXISTING_BASELINE_READBACK";
manifestRun = string(stage2InputManifest.run_id(manifestRow));
manifestScene = string(stage2InputManifest.scene_id(manifestRow));
manifestPrn = string(stage2InputManifest.prn(manifestRow));
manifestChannel = double(stage2InputManifest.tracking_channel(manifestRow));
manifestFrozenSageSha = lower(string(stage2InputManifest.frozen_sage_sha256(manifestRow)));
assert(string(m.run_id)==runId && string(m.scene_id)==string(task.scene_id) ...
    && string(m.prn)==string(task.prn) && double(m.tracking_channel)==double(task.tracking_channel) ...
    && manifestRun==runId && manifestScene==string(task.scene_id) ...
    && manifestPrn==string(task.prn) && manifestChannel==double(task.tracking_channel) ...
    && lower(string(m.frozen_sage_sha256))==manifestFrozenSageSha ...
    && (legacyBaseline || (isfield(m,'source_cohort_sha256') ...
        && lower(string(m.source_cohort_sha256))==cohortSha)) ...
    && string(m.amplitude_reference_status)=="UNKNOWN_RECEIVER_GAIN_OR_AGC" ...
    && contains(string(m.cir_definition),"One-ms coherent code-domain correlation") ...
    && contains(string(m.cir_definition),"per-snapshot complex-mean removal") ...
    && contains(string(m.cir_definition),"no per-snapshot RMS normalization") ...
    && contains(string(m.cir_definition),"correlation divided by sample count") ...
    && contains(string(m.pdp_definition),"arithmetic mean of the powers of its 40 one-ms CIR snapshots"), ...
    'GNSS:SAGE:GateEMetadataIdentityMismatch','Metadata identity/provenance mismatch.');
rec.hdf5_path=string(src.hdf5_path);
rec.hdf5_size_bytes=double(dir(src.hdf5_path).bytes);
rec.hdf5_sha_expected=src.hdf5_sha_expected;
rec.hdf5_sha_actual=sha256File(src.hdf5_path);
if src.hdf5_sha_expected~=""
    assert(rec.hdf5_sha_actual==src.hdf5_sha_expected, ...
        'GNSS:SAGE:GateEOutputShaMismatch','HDF5 SHA mismatch.');
    rec.hdf5_sha_status="PASS_RECEIPT_PINNED";
else
    rec.hdf5_sha_status="OBSERVED_UNPINNED_BASELINE";
end
rec.source_request_path=string(src.source_request_path);
rec.source_request_sha_expected=src.source_request_sha_expected;
rec.source_request_sha_actual=src.source_request_sha_actual;
rec.source_request_sha=src.receipt_request_sha;
if isfield(m,'source_cohort_sha256')
    rec.source_cohort_sha256=lower(string(m.source_cohort_sha256));
else
    rec.source_cohort_sha256="UNPINNED_LEGACY_BASELINE";
end
rec.frozen_sage_sha256=string(m.frozen_sage_sha256);
rec.amplitude_reference_status=string(m.amplitude_reference_status);
rec.metadata_path=string(src.metadata_path);
rec.metadata_sha_expected=src.metadata_sha_expected;
if src.metadata_path~=""
    rec.metadata_sha_actual=sha256File(src.metadata_path);
    assert(rec.metadata_sha_actual==src.metadata_sha_expected, ...
        'GNSS:SAGE:GateEMetadataShaMismatch','Metadata SHA mismatch.');
else
    rec.metadata_sha_actual=src.baseline_evidence_sha;
end
manifestCsv=resolveProjectPath(projectRoot,stage2InputManifest.stage2_selected_paths_csv_path(manifestRow));
stage2Csv=manifestCsv;
if legacyBaseline
    % The old baseline read-back predates the source-file pin fields. Bind its
    % selected-path CSV to the SHA-pinned WP5 input manifest and locate the
    % Stage0 table beside that exact CSV; both remain explicitly unpinned in
    % the legacy receipt and the observed Stage0 SHA is recorded below.
    src.stage0_path=fullfile(fileparts(stage2Csv),'stage0_valid_40ms_windows.csv');
    rec.source_stage0_sha_expected="UNPINNED_LEGACY_BASELINE";
    rec.source_stage2_csv_sha_expected=lower(string( ...
        stage2InputManifest.stage2_selected_paths_csv_sha256(manifestRow)));
else
    assert(samePath(resolveProjectPath(projectRoot, ...
        string(m.source_stage2_selected_paths_path)),stage2Csv) ...
        && lower(string(m.source_stage2_selected_paths_sha256)) == ...
        lower(string(stage2InputManifest.stage2_selected_paths_csv_sha256(manifestRow))), ...
        'GNSS:SAGE:GateEStageInputPinMismatch', ...
        'Release metadata Stage2 path/hash differs from WP5 input manifest.');
    src.stage0_path=resolveProjectPath(projectRoot,string(m.source_stage0_windows_path));
    rec.source_stage0_sha_expected=lower(string(m.source_stage0_windows_sha256));
    rec.source_stage2_csv_sha_expected=lower(string(m.source_stage2_selected_paths_sha256));
end
stage2CsvSha=sha256File(stage2Csv);
rec.source_stage0_path=string(src.stage0_path);
rec.source_stage0_sha_actual=sha256File(src.stage0_path);
rec.source_stage2_csv_path=string(stage2Csv);
rec.source_stage2_csv_sha_actual=stage2CsvSha;
assert(isfile(src.stage0_path) ...
    && (legacyBaseline || rec.source_stage0_sha_expected==rec.source_stage0_sha_actual) ...
    && rec.source_stage2_csv_sha_expected==stage2CsvSha ...
    && lower(string(stage2InputManifest.stage2_selected_paths_csv_sha256(manifestRow)))==stage2CsvSha ...
    && samePath(stage2Csv,manifestCsv), ...
    'GNSS:SAGE:GateEStageInputPinMismatch','Stage0/Stage2 source CSV pin mismatch.');
csvCheck=verify_mainline_stage2_path_csv_attributes(stage2Csv,stage2Run);
rec.stage2_csv_mapping_status=csvCheck.status;
rec.stage2_csv_max_attribute_difference=csvCheck.max_abs_attribute_difference;
assert(csvCheck.status=="PASS",'GNSS:SAGE:GateEStage2CsvMappingMismatch','Stage2 CSV mapping mismatch.');
if src.receipt_type=="EXISTING_BASELINE_READBACK"
    rec.gate_e="PASS_WITH_LIMITATIONS";
    rec.limitations="Legacy baseline lacks historical cohort, Stage0 and HDF5 SHA pins. Run identity and frozen SAGE SHA match the cohort/WP5 manifest; Stage2 CSV is manifest-SHA-pinned; sibling Stage0 CSV is observed and fully aligned to HDF5; HDF5 SHA is observed but not historically receipt-pinned.";
else
    rec.gate_e="PASS";
end
end

function [src,receipt]=getEvidence(projectRoot,releaseRoot,request,completion,requestSha,runId)
completed=fieldStrings(completion.tasks,'run_id');
skipped=fieldStrings(request.skipped_existing_pass,'run_id');
ci=find(completed==runId,1); si=find(skipped==runId,1);
assert(xor(~isempty(ci),~isempty(si)),'GNSS:SAGE:GateEReceiptMapMismatch','Expected exactly one receipt source.');
src=struct('current_release',~isempty(ci),'identity_run_id',"",'identity_scene',"",'identity_prn',"",'identity_channel',NaN);
if src.current_release
    row=recordAt(completion.tasks,ci); src.receipt_type="CURRENT_RELEASE_PASS";
    src.receipt_path=resolveProjectPath(projectRoot,string(row.receipt_path));
    src.receipt_sha_expected=lower(string(row.receipt_sha256));
    src.source_request_path=fullfile(releaseRoot,'release_request.json');
    src.source_request_sha_expected=lower(string(requestSha));
    src.source_request_sha_actual=lower(string(requestSha));
else
    row=recordAt(request.skipped_existing_pass,si); src.receipt_type=string(row.receipt_type);
    src.receipt_path=resolveProjectPath(projectRoot,string(row.receipt_path));
    src.receipt_sha_expected=lower(string(row.receipt_sha256));
    src.source_request_path=resolveProjectPath(projectRoot,string(row.source_release_request_path));
    src.source_request_sha_expected=lower(string(row.source_release_request_sha256));
    src.source_request_sha_actual=sha256File(src.source_request_path);
end
receipt=readJson(src.receipt_path);
src.receipt_status=string(receipt.status); src.receipt_run_id=string(receipt.run_id);
src.receipt_request_sha=lower(string(receipt.request_sha256));
src.metadata_path=""; src.metadata_sha_expected=""; src.hdf5_sha_expected="";
if isfield(receipt,'identity')
    src.identity_run_id=string(receipt.identity.run_id);
    src.identity_scene=string(receipt.identity.scene_id);
    src.identity_prn=string(receipt.identity.prn);
    src.identity_channel=double(receipt.identity.tracking_channel);
end
if src.receipt_type=="EXISTING_BASELINE_READBACK"
    resultPath=resolveProjectPath(projectRoot,string(receipt.result_path));
    src.baseline_evidence_sha=sha256File(resultPath);
    baseline=readJson(resultPath);
    assert(string(baseline.status)=="PASS" && string(baseline.run_id)==runId ...
        && logical(baseline.hdf5_payload_read) && ~logical(baseline.existing_outputs_modified), ...
        'GNSS:SAGE:GateEBaselineReadbackInvalid','Baseline readback evidence invalid.');
    src.hdf5_path=canonicalPath(string(baseline.validation.hdf5_path));
    src.metadata=baseline.metadata;
else
    out=receipt.outputs;
    paths=strings(numel(out),1);
    for outputIndex=1:numel(out)
        outputItem=recordAt(out,outputIndex);
        paths(outputIndex)=string(outputItem.path);
    end
    hi=find(endsWith(lower(paths),'.h5'),1);
    mi=find(endsWith(lower(paths),'_metadata.json'),1);
    assert(~isempty(hi)&&~isempty(mi),'GNSS:SAGE:GateEOutputReceiptMissing','Receipt lacks HDF5/metadata outputs.');
    src.hdf5_path=resolveProjectPath(projectRoot,paths(hi));
    hdf5Output=recordAt(out,hi);
    src.hdf5_sha_expected=lower(string(hdf5Output.sha256));
    src.metadata_path=resolveProjectPath(projectRoot,paths(mi));
    metadataOutput=recordAt(out,mi);
    src.metadata_sha_expected=lower(string(metadataOutput.sha256));
    src.metadata=readJson(src.metadata_path);
end
assert(isfile(src.hdf5_path),'GNSS:SAGE:GateEOutputMissing','HDF5 missing.');
end

function windows=buildWindows(stage2Run,rec,features)
idsInput=doubleColumn(stage2Run.window_id); [ids,~,g]=unique(idsInput,'stable');
first=accumarray(g,(1:height(stage2Run)).',[],@min); paths=accumarray(g,1);
mpc=doubleColumn(stage2Run.is_multipath)==1; mpcCount=accumarray(g,double(mpc));
time=nan(numel(ids),1); if ismember('recording_time_s',stage2Run.Properties.VariableNames),v=stage2Run.recording_time_s;time=doubleColumn(v(first));end
directDelay=nan(numel(ids),1); if ismember('delay_samples',stage2Run.Properties.VariableNames),v=stage2Run.delay_samples;for j=1:numel(ids),r=find(g==j&~mpc,1);if ~isempty(r),directDelay(j)=doubleColumn(v(r));end,end,end
n=numel(ids);
windows=table(repmat(rec.run_id,n,1),repmat(rec.scene_id,n,1),repmat(rec.prn,n,1), ...
 repmat(rec.channel,n,1),ids,time,paths,mpcCount,repmat("NO_CIR_FEATURE",n,1), ...
 nan(n,1),nan(n,1),nan(n,1),nan(n,1),nan(n,1),nan(n,1),nan(n,1),nan(n,1), ...
 nan(n,1),false(n,1),directDelay,nan(n,1),repmat(rec.hdf5_sha_actual,n,1), ...
 repmat(rec.receipt_type,n,1),'VariableNames',{'run_id','scene_id','prn','tracking_channel','window_id', ...
 'stage2_recording_time_s','stage2_path_count','stage2_mpc_count','cir_link_status', ...
 'stage0_sample_start_zero_based','stage0_recording_time_s','cir_snapshot_count', ...
 'pdp_total_power_relative_units','pdp_peak_power_relative_units','pdp_peak_code_delay_samples', ...
 'pdp_centroid_code_delay_samples','pdp_rms_width_code_delay_samples', ...
 'pdp_negative_delay_power_fraction','pdp_peak_at_grid_boundary', ...
 'stage2_direct_delay_samples','pdp_peak_minus_sage_direct_delay_samples', ...
 'source_hdf5_sha256','source_receipt_type'});
if isempty(features),windows.cir_link_status=repmat("HDF5_AUDIT_FAILED",n,1);return;end
[matched,fr]=ismember(ids,doubleColumn(features.window_id));
fields={'stage0_sample_start_zero_based','stage0_recording_time_s','cir_snapshot_count', ...
 'pdp_total_power_relative_units','pdp_peak_power_relative_units','pdp_peak_code_delay_samples', ...
 'pdp_centroid_code_delay_samples','pdp_rms_width_code_delay_samples', ...
 'pdp_negative_delay_power_fraction','pdp_peak_at_grid_boundary'};
for j=1:numel(fields),f=fields{j};v=features.(f);windows.(f)(matched)=v(fr(matched));end
windows.cir_link_status(matched)="CIR_PDP_VERIFIED";
windows.pdp_peak_minus_sage_direct_delay_samples(matched)= ...
 windows.pdp_peak_code_delay_samples(matched)-windows.stage2_direct_delay_samples(matched);
end

function s=summarizeScenes(stage2,w)
