function testKeepsDirectTransientPersistentAndConfirmedClasses(testCase)
tempRoot = tempname;
mkdir(tempRoot);
cleanup = onCleanup(@() rmdir(tempRoot, 's')); %#ok<NASGU>

stage2 = table((1:5).', [1; 2; 2; 2; 2], [0; 1; 1; 1; 1], ...
    (1:5).', [2; 2; 2; 2; 2], ...
    'VariableNames', {'window_id', 'path_id', 'is_multipath', ...
    'recording_time_s', 'selected_L'});
stage3 = table([3; 4; 5], [1; 1; 1], [true; true; true], ...
    [3; 4; 5], [3; 3; 4], ...
    'VariableNames', {'center_window_id', 'multipath_id', ...
    'persistence_pass', 'matched_window_count', ...
    'longest_consecutive_count'});
reliable = table([3; 4; 5], 'VariableNames', {'center_window_id'});
stage4Summary = table([3; 4], [true; true], [1; 2], ...
    'VariableNames', {'center_window_id', 'joint_valid', ...
    'joint_selected_L'});
stage4Paths = table(4, 2, 1, ...
    'VariableNames', {'center_window_id', 'path_id', 'is_multipath'});
alpha = makeAlphaTable([1; 2; 2; 3; 3; 4; 4; 5; 5], ...
    [1; 1; 2; 1; 2; 1; 2; 1; 2], ones(9, 1), zeros(9, 1), ...
    ones(9, 1), zeros(9, 1), repmat("AVAILABLE", 9, 1), ...
    repmat("NONE", 9, 1), repmat("PASS", 9, 1));

stage2Path = fullfile(tempRoot, 'stage2.csv');
stage3Path = fullfile(tempRoot, 'stage3.csv');
reliablePath = fullfile(tempRoot, 'reliable.csv');
stage4SummaryPath = fullfile(tempRoot, 'stage4_summary.csv');
stage4PathsPath = fullfile(tempRoot, 'stage4_paths.csv');
alphaPath = fullfile(tempRoot, 'alpha.csv');
outputPath = fullfile(tempRoot, 'ledger.csv');
writetable(stage2, stage2Path);
writetable(stage3, stage3Path);
writetable(reliable, reliablePath);
writetable(stage4Summary, stage4SummaryPath);
writetable(stage4Paths, stage4PathsPath);
writetable(alpha, alphaPath);

provenance = struct('run_id', 'test_run', 'scene_id', 'test_scene', ...
    'prn', 'G28', 'tracking_channel', 1, ...
    'sample_rate_hz', 10230000, ...
    'frozen_sage_sha256', repmat('b', 1, 64), ...
    'stage2_mat_sha256', repmat('e', 1, 64), ...
    'selected_paths_csv_sha256', repmat('f', 1, 64));
build_mpc_modeling_ledger(stage2Path, stage3Path, reliablePath, ...
    stage4SummaryPath, stage4PathsPath, alphaPath, outputPath, provenance);

actual = readtable(outputPath, 'TextType', 'string');
testCase.verifyEqual(height(actual), 5);
testCase.verifyEqual(actual.modeling_class, ...
    ["DIRECT_PATH"; "TRANSIENT_MPC"; "PERSISTENT_MPC"; ...
    "HIGH_CONFIDENCE_MPC"; "PERSISTENT_MPC"]);
testCase.verifyEqual(actual.primary_modeling_pool, ...
    ["NO"; "NO"; "YES"; "YES"; "YES"]);
testCase.verifyEqual(actual.stage4_confirmed, ...
    ["NA"; "UNMAPPED"; "NO"; "YES"; "UNMAPPED"]);
testCase.verifyEqual(actual.stage3_persistent(1), "NA");
testCase.verifyEqual(sum(actual.is_multipath == 1), 4);
testCase.verifyEqual(sum(actual.primary_modeling_pool == "YES"), 3);
testCase.verifyTrue(all(actual.alpha_status == "AVAILABLE"));

alpha.run_id(1) = "another_run";
writetable(alpha, alphaPath);
testCase.verifyError(@() build_mpc_modeling_ledger( ...
    stage2Path, stage3Path, reliablePath, stage4SummaryPath, ...
    stage4PathsPath, alphaPath, fullfile(tempRoot, 'wrong_run.csv'), ...
    provenance), 'GNSS:SAGE:AlphaProvenanceMismatch');
end

