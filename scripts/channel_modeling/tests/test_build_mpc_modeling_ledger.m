function alpha = makeAlphaTable(windowId, pathId, alphaReal, alphaImag, ...
    alphaMagnitude, alphaPhase, alphaStatus, alphaMissingReason, ...
    relativePowerStatus)
rowCount = numel(windowId);
alpha = table(windowId, pathId, alphaReal, alphaImag, alphaMagnitude, ...
    alphaPhase, alphaStatus, alphaMissingReason, relativePowerStatus, ...
    repmat("YES", rowCount, 1), ...
    'VariableNames', {'window_id', 'path_id', 'alpha_real', ...
    'alpha_imag', 'alpha_magnitude', 'alpha_phase_rad', ...
    'alpha_status', 'alpha_missing_reason', ...
    'relative_power_check_status', ...
    'SAGE_ALPHA_IS_FROM_WINDOW_NORMALIZED_IQ'});
alpha.run_id = repmat("test_run", rowCount, 1);
alpha.scene_id = repmat("test_scene", rowCount, 1);
alpha.prn = repmat("G28", rowCount, 1);
alpha.tracking_channel = ones(rowCount, 1);
alpha.sample_rate_hz = repmat(10230000, rowCount, 1);
alpha.frozen_sage_sha256 = repmat(string(repmat('b', 1, 64)), ...
    rowCount, 1);
alpha.source_stage2_mat_path = repmat("source/stage2.mat", ...
    rowCount, 1);
alpha.source_selected_paths_csv_path = repmat( ...
    "source/stage2_selected_paths.csv", rowCount, 1);
alpha.stage2_mat_sha256 = repmat(string(repmat('e', 1, 64)), rowCount, 1);
alpha.selected_paths_csv_sha256 = ...
    repmat(string(repmat('f', 1, 64)), rowCount, 1);
end
