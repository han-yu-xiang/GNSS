testCase.verifyEqual(height(actual), 1);
testCase.verifyEqual(actual.window_id, 9);
testCase.verifyEqual(actual.path_id, 2);
testCase.verifyEqual(actual.alpha_status, "MISSING");
testCase.verifyEqual(actual.alpha_missing_reason, ...
    "NO_STAGE2_FIT_FOR_WINDOW");
testCase.verifyTrue(isnan(actual.alpha_real));
testCase.verifyEqual(actual.modeling_class, "TRANSIENT_MPC");
end

