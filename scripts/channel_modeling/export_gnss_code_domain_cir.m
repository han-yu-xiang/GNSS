function [buffer, writePosition, uniqueStartCount, previousSampleStart] = ...
    flushSnapshotBuffer(filename, buffer, rowCount, writePosition, ...
    uniqueStartCount, previousSampleStart, chunkRows)
rowCount = min(rowCount, size(buffer.cirReal, 1));
for firstRow = 1:chunkRows:rowCount
    lastRow = min(firstRow + chunkRows - 1, rowCount);
    rows = firstRow:lastRow;
    starts = buffer.sampleStart(rows);
    assert(all(diff(starts) >= 0) && (isnan(previousSampleStart) ...
        || starts(1) >= previousSampleStart), ...
        'GNSS:SAGE:CIRTimeOrderInvalid', ...
        'Snapshot sample starts are not monotonic.');
    additionalUniqueStarts = 1 + sum(diff(starts) > 0);
    if ~isnan(previousSampleStart) && starts(1) == previousSampleStart
        additionalUniqueStarts = additionalUniqueStarts - 1;
    end
    uniqueStartCount = uniqueStartCount + additionalUniqueStarts;
    writeStart = writePosition + 1;
    writeCount = numel(rows);
    h5write(filename, '/cir_real', buffer.cirReal(rows, :), ...
        [writeStart, 1], [writeCount, size(buffer.cirReal, 2)]);
    h5write(filename, '/cir_imag', buffer.cirImag(rows, :), ...
        [writeStart, 1], [writeCount, size(buffer.cirImag, 2)]);
    writeVectorRows(filename, '/time_s', buffer.timeS(rows), writeStart);
    writeVectorRows(filename, '/raw_iq_rms', ...
        buffer.rawIqRms(rows), writeStart);
    writeVectorRows(filename, '/tracking_doppler_hz', ...
        buffer.trackingDopplerHz(rows), writeStart);
    writeVectorRows(filename, '/code_frequency_hz', ...
        buffer.codeFrequencyHz(rows), writeStart);
    writeVectorRows(filename, '/cn0_db_hz', buffer.cn0DbHz(rows), writeStart);
    writeVectorRows(filename, '/nav_symbol', buffer.navSymbol(rows), writeStart);
    writeVectorRows(filename, '/window_id', buffer.windowId(rows), writeStart);
    writeVectorRows(filename, '/snapshot_index_in_window', ...
        buffer.snapshotIndex(rows), writeStart);
    writeVectorRows(filename, '/sample_start_zero_based', starts, writeStart);
    writeVectorRows(filename, '/nav_symbol_transition_offset_samples', ...
        buffer.navTransitionOffset(rows), writeStart);
    writePosition = writePosition + writeCount;
    previousSampleStart = starts(end);
end
names = fieldnames(buffer);
for index = 1:numel(names)
    values = buffer.(names{index});
    buffer.(names{index}) = values(rowCount + 1:end, :);
end
end

function caCode = generateGpsCaCode(prn)
g2TapTable = [ ...
    2,6; 3,7; 4,8; 5,9; 1,9; 2,10; 1,8; 2,9; ...
    3,10; 2,3; 3,4; 5,6; 6,7; 7,8; 8,9; 9,10; ...
    1,4; 2,5; 3,6; 4,7; 5,8; 6,9; 1,3; 4,6; ...
    5,7; 6,8; 7,9; 8,10; 1,6; 2,7; 3,8; 4,9];
assert(prn >= 1 && prn <= size(g2TapTable, 1), ...
    'GNSS:SAGE:UnsupportedPrn', 'Unsupported GPS PRN: %d', prn);
g1 = -ones(1, 10);
g2 = -ones(1, 10);
caCode = zeros(1023, 1);
taps = g2TapTable(prn, :);
for index = 1:1023
    caCode(index) = g1(10) * g2(taps(1)) * g2(taps(2));
    g1Feedback = g1(3) * g1(10);
    g2Feedback = g2(2) * g2(3) * g2(6) ...
        * g2(8) * g2(9) * g2(10);
    g1 = [g1Feedback, g1(1:9)]; %#ok<AGROW>
    g2 = [g2Feedback, g2(1:9)]; %#ok<AGROW>
end
end

