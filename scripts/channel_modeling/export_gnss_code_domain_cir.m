function summary = export_gnss_code_domain_cir( ...
    rawIqPath, stage0WindowsCsvPath, stage2SelectedPathsCsvPath, ...
    sceneMetadataPath, outputH5Path, metadataJsonPath, ...
    delayComparisonCsvPath, provenance)
%EXPORT_GNSS_CODE_DOMAIN_CIR Create raw-scale, Stage0-aligned CIR sidecars.

requiredProvenance = {'project_root', 'run_id', 'scene_id', 'prn', ...
    'tracking_channel', 'sample_rate_hz', 'frozen_sage_sha256', ...
    'raw_iq_size_bytes', 'scene_metadata_sha256', ...
    'cohort_json_path', 'cohort_sha256', ...
    'cir_tasks_json_path', 'cir_tasks_sha256'};
assert(all(isfield(provenance, requiredProvenance)), ...
    'GNSS:SAGE:CIRProvenanceMissing', ...
    'Required run provenance is incomplete.');
projectRoot = canonicalPath(provenance.project_root);
assert(isfolder(projectRoot), 'GNSS:SAGE:CIRProjectRootMissing', ...
    'Pinned project root does not exist.');
assertFrozenSourcePins(projectRoot, provenance.frozen_sage_sha256);
provenance.cohort_json_path = resolveProjectPath(projectRoot, ...
    char(provenance.cohort_json_path));
provenance.cir_tasks_json_path = resolveProjectPath(projectRoot, ...
    char(provenance.cir_tasks_json_path));
[authorizedTask, cohortTask, cohortDocument] = ...
    loadAuthorizedCirTask(provenance);
assert(strcmp(authorizedTask.output_namespace, ...
    cohortTask.output_namespace), ...
    'GNSS:SAGE:CIRIdentityAuthorizationMismatch', ...
    'cir_tasks.json and cohort.json disagree on the output namespace.');
assertAuthorizedCohortInput(projectRoot, authorizedTask.output_namespace, ...
    cohortTask.stage_csvs.stage0_valid_windows, stage0WindowsCsvPath, ...
    'Stage0');
assertAuthorizedCohortInput(projectRoot, authorizedTask.output_namespace, ...
    cohortTask.stage_csvs.stage2_selected_paths, ...
    stage2SelectedPathsCsvPath, 'Stage2');
assertUniqueOutputPaths({outputH5Path, metadataJsonPath, ...
    delayComparisonCsvPath});
assertSceneMetadataPath(projectRoot, sceneMetadataPath);
rawIqPath = resolveProjectPath(projectRoot, char(rawIqPath));
stage0WindowsCsvPath = resolveProjectPath(projectRoot, ...
    char(stage0WindowsCsvPath));
stage2SelectedPathsCsvPath = resolveProjectPath(projectRoot, ...
    char(stage2SelectedPathsCsvPath));
sceneMetadataPath = resolveProjectPath(projectRoot, ...
    char(sceneMetadataPath));
outputH5Path = canonicalPath(outputH5Path);
metadataJsonPath = canonicalPath(metadataJsonPath);
delayComparisonCsvPath = canonicalPath(delayComparisonCsvPath);
prnToken = regexp(char(provenance.prn), '^G([0-9]{1,2})$', ...
    'tokens', 'once');
prnNumber = NaN;
if ~isempty(prnToken)
    prnNumber = str2double(prnToken{1});
end
trackingChannel = double(provenance.tracking_channel);
sampleRateHz = double(provenance.sample_rate_hz);
assert(isfinite(prnNumber) && prnNumber == floor(prnNumber) ...
    && prnNumber >= 1 && prnNumber <= 32 ...
    && isscalar(trackingChannel) && isfinite(trackingChannel) ...
    && trackingChannel == floor(trackingChannel) ...
    && trackingChannel >= 0 && trackingChannel <= 11 ...
    && isscalar(sampleRateHz) && sampleRateHz == 10230000 ...
    && strcmpi(provenance.frozen_sage_sha256, ...
    'bffc123c97af77f0a797f417d3866e9a34feab7729c5c1575352f53bc3571b9c'), ...
    'GNSS:SAGE:CIRScopeMismatch', ...
    'CIR identity, 10.23 MHz rate, or frozen SAGE source is not approved.');
assert(strcmp(char(provenance.run_id), char(authorizedTask.run_id)) ...
    && strcmp(char(provenance.scene_id), char(authorizedTask.scene_id)) ...
    && strcmp(char(provenance.prn), char(authorizedTask.prn)) ...
    && trackingChannel == double(authorizedTask.tracking_channel), ...
    'GNSS:SAGE:CIRIdentityAuthorizationMismatch', ...
    'Requested CIR identity does not match the frozen cir_tasks.json row.');
assert(isscalar(provenance.raw_iq_size_bytes) ...
    && isfinite(double(provenance.raw_iq_size_bytes)) ...
    && double(provenance.raw_iq_size_bytes) > 0 ...
    && double(provenance.raw_iq_size_bytes) == floor( ...
    double(provenance.raw_iq_size_bytes)), ...
    'GNSS:SAGE:CIRRawIqSizePinInvalid', ...
    'Pinned raw-IQ byte size must be a positive integer.');
assert(isfile(rawIqPath) && isfile(stage0WindowsCsvPath) ...
    && isfile(stage2SelectedPathsCsvPath) ...
    && isfile(sceneMetadataPath), ...
    'GNSS:SAGE:CIRInputMissing', ...
    'Required target-scene CIR input is missing.');
assert(~isfile(outputH5Path) && ~isfolder(outputH5Path) ...
    && ~isfile(metadataJsonPath) && ~isfolder(metadataJsonPath) ...
    && ~isfile(delayComparisonCsvPath) ...
    && ~isfolder(delayComparisonCsvPath), ...
    'GNSS:SAGE:CIROutputCollision', ...
    'Refusing to overwrite an existing CIR sidecar or comparison.');

rawInfo = dir(rawIqPath);
assert(rawInfo.bytes == double(provenance.raw_iq_size_bytes) ...
    && rawInfo.bytes > 0 && mod(rawInfo.bytes, 4) == 0, ...
    'GNSS:SAGE:RawIqSizeMismatch', ...
    'Raw-IQ size changed; SHA-256 is intentionally not recomputed.');
expectedSceneMetadataHash = lower(char(provenance.scene_metadata_sha256));
assert(isSha256(expectedSceneMetadataHash) ...
    && strcmp(sha256File(sceneMetadataPath), expectedSceneMetadataHash), ...
    'GNSS:SAGE:CIRSceneMetadataHashMismatch', ...
    'Scene metadata CSV differs from its pinned SHA-256.');
sceneMetadataText = readUtf8Text(sceneMetadataPath);
sceneMetadata = readtable(sceneMetadataPath);
requiredSceneMetadataColumns = {'scene_id', 'raw_file_path', ...
    'raw_file_size_bytes', 'sample_rate'};
assert(all(ismember(requiredSceneMetadataColumns, ...
    sceneMetadata.Properties.VariableNames)), ...
    'GNSS:SAGE:SceneMetadataSchemaMismatch', ...
    'Scene metadata CSV lacks required raw-IQ provenance columns.');
sceneMatches = find(strcmp(string(sceneMetadata.scene_id), ...
    string(provenance.scene_id)));
assert(numel(sceneMatches) == 1, ...
    'GNSS:SAGE:SceneMetadataMismatch', ...
    'Scene metadata CSV must contain exactly one row for scene_id.');
sceneIndex = sceneMatches(1);
metadataRawPath = char(string( ...
    sceneMetadata.raw_file_path(sceneIndex)));
assert(double(sceneMetadata.sample_rate(sceneIndex)) ...
    == double(provenance.sample_rate_hz) ...
    && double(sceneMetadata.raw_file_size_bytes(sceneIndex)) ...
    == double(provenance.raw_iq_size_bytes), ...
    'GNSS:SAGE:SceneMetadataMismatch', ...
    'Scene metadata sample rate/raw size disagrees with run provenance.');
assert(strcmpi(resolveProjectPath(projectRoot, metadataRawPath), ...
    canonicalPath(rawIqPath)), ...
    'GNSS:SAGE:RawIqMetadataMismatch', ...
    'Scene metadata raw-IQ path disagrees with the input.');
metadataTextLower = lower(sceneMetadataText);
calibrationEvidenceFields = {'amplitude_calibration', ...
    'receiver_gain_calibration', 'volts_per_count', 'adc_scale_factor'};
calibrationMetadataFound = any(cellfun( ...
    @(name) contains(metadataTextLower, name), ...
    calibrationEvidenceFields));

coreDirectory = fullfile(projectRoot, ...
    'scripts', 'sage_pipeline', 'core');
previousPath = path;
pathCleanup = onCleanup(@() path(previousPath)); %#ok<NASGU>
addpath(coreDirectory, '-begin');
clear default_sage_configuration;
resolvedConfigurationPath = which('default_sage_configuration');
expectedConfigurationPath = fullfile(coreDirectory, ...
    'default_sage_configuration.m');
assert(~isempty(resolvedConfigurationPath) ...
    && strcmpi(canonicalPath(resolvedConfigurationPath), ...
    canonicalPath(expectedConfigurationPath)), ...
    'GNSS:SAGE:CIRFrozenSourceHashMismatch', ...
    'MATLAB did not resolve the pinned SAGE configuration from project_root.');
cfg = default_sage_configuration(prnNumber, ...
    sampleRateHz, false);
delayMaximum = cfg.mainDelayMaximumSamples ...
    + cfg.maximumExcessDelaySamples;
delaySamples = cfg.mainDelayMinimumSamples ...
    : cfg.delayStepSamples : delayMaximum;
assert(numel(delaySamples) == 451 ...
    && abs(delaySamples(1) + 5) < 1e-12 ...
    && abs(delaySamples(end) - 40) < 1e-12, ...
    'GNSS:SAGE:CIRDelayGridMismatch', ...
    'Frozen default configuration did not produce the expected delay grid.');

stageOutputDirectory = fileparts(stage0WindowsCsvPath);
dopplerSignPath = fullfile(stageOutputDirectory, 'doppler_sign.mat');
assert(isfile(dopplerSignPath), ...
    'GNSS:SAGE:DopplerSignMissing', ...
    'Frozen SAGE Doppler-sign evidence is missing.');
dopplerEvidence = load(dopplerSignPath, 'dopplerSignUsed');
assert(isfield(dopplerEvidence, 'dopplerSignUsed') ...
    && ismember(double(dopplerEvidence.dopplerSignUsed), [-1, 1]), ...
    'GNSS:SAGE:DopplerSignInvalid', ...
    'Frozen SAGE Doppler-sign evidence is invalid.');
dopplerSignUsed = double(dopplerEvidence.dopplerSignUsed);

windows = readtable(stage0WindowsCsvPath);
requiredWindowColumns = {'window_id', 'sample_start_zero_based', ...
    'recording_time_s', 'nav_symbol_1', 'nav_symbol_2', ...
    'split_samples', 'tracking_doppler_hz', 'code_frequency_hz', ...
    'cn0_db_hz'};
assert(all(ismember(requiredWindowColumns, ...
    windows.Properties.VariableNames)) && height(windows) > 0, ...
    'GNSS:SAGE:Stage0WindowSchemaMismatch', ...
    'Stage0 window catalog is empty or missing required fields.');

samplesPerMs = cfg.samplesPerMs;
samplesPer40Ms = cfg.samplesPer40Ms;
assert(samplesPerMs == 10230 && samplesPer40Ms == 40 * samplesPerMs, ...
    'GNSS:SAGE:CIRSampleGridMismatch', ...
    'Frozen configuration does not yield exact 1 ms sample blocks.');
windowIds = double(windows.window_id);
sampleStarts = double(windows.sample_start_zero_based);
assert(all(isfinite(windowIds)) && all(windowIds == floor(windowIds)) ...
    && all(windowIds > 0) && all(windowIds <= double(intmax('uint32'))) ...
    && all(isfinite(sampleStarts)) && all(sampleStarts >= 0) ...
    && all(sampleStarts == floor(sampleStarts)), ...
    'GNSS:SAGE:Stage0WindowInvalid', ...
    'Stage0 window IDs and sample starts must be finite integer values.');
assert(numel(unique(windowIds)) == height(windows), ...
    'GNSS:SAGE:Stage0WindowDuplicateId', ...
    'Stage0 window IDs must be unique.');
windows = sortrows(windows, ...
    {'sample_start_zero_based', 'window_id'});
windowIds = double(windows.window_id);
sampleStarts = double(windows.sample_start_zero_based);

stage2Paths = readtable(stage2SelectedPathsCsvPath);
requiredStage2Columns = {'window_id', 'path_id', ...
    'recording_time_s', 'delay_samples'};
assert(all(ismember(requiredStage2Columns, ...
    stage2Paths.Properties.VariableNames)), ...
    'GNSS:SAGE:CIRStage2SchemaMismatch', ...
    'Stage2 selected-path catalog is missing required fields.');
primaryRows = stage2Paths(double(stage2Paths.path_id) == 1, :);
primaryWindowIds = double(primaryRows.window_id);
assert(height(primaryRows) > 0 && all(isfinite(primaryWindowIds)) ...
    && numel(unique(primaryWindowIds)) == height(primaryRows), ...
    'GNSS:SAGE:CIRStage2PrimaryIdentityInvalid', ...
    'Stage2 primary paths must have unique finite window IDs.');
[primaryMapped, primaryWindowIndex] = ismember(primaryWindowIds, windowIds);
assert(all(primaryMapped), ...
    'GNSS:SAGE:CIRStage2WindowMappingMismatch', ...
    'Stage2 primary path does not map to exactly one Stage0 window.');
primaryTimes = double(primaryRows.recording_time_s);
stage0PrimaryTimes = double(windows.recording_time_s(primaryWindowIndex));
assert(all(isfinite(primaryTimes)) && all(isfinite(stage0PrimaryTimes)) ...
    && all(abs(primaryTimes - stage0PrimaryTimes) ...
    <= eps(max(1, max(abs(stage0PrimaryTimes))))) ...
    && all(isfinite(double(primaryRows.delay_samples))), ...
    'GNSS:SAGE:CIRStage2WindowMetadataMismatch', ...
    'Stage2 primary time/delay metadata disagrees with its Stage0 window.');

snapshotCount = height(windows) * 40;
delayCount = numel(delaySamples);
pdpTimeS = double(windows.recording_time_s);
pdpWindowId = uint32(windows.window_id);
pdpStartSample = sampleStarts;
temporaryH5Path = [tempname(fileparts(outputH5Path)), '.h5'];
temporaryMetadataPath = [tempname(fileparts(metadataJsonPath)), '.json'];
temporaryComparisonPath = [tempname(fileparts(delayComparisonCsvPath)), '.csv'];
createHdf5Schema(temporaryH5Path, delaySamples, snapshotCount, ...
    height(windows), pdpWindowId, pdpTimeS, pdpStartSample);

comparison = table(primaryWindowIds, ...
    double(primaryRows.recording_time_s), ...
    double(primaryRows.delay_samples), ...
    zeros(height(primaryRows), 1), zeros(height(primaryRows), 1), ...
    'VariableNames', {'window_id', 'recording_time_s', ...
    'sage_primary_delay_samples', ...
    'pdp_dominant_peak_delay_samples', ...
    'pdp_minus_sage_delay_samples'});
primaryComparisonIndex = zeros(height(windows), 1);
primaryComparisonIndex(primaryWindowIndex) = (1:height(primaryRows)).';

g1g2Code = generateGpsCaCode(prnNumber);
rawFileId = fopen(rawIqPath, 'rb', 'ieee-le');
assert(rawFileId >= 0, 'GNSS:SAGE:RawIqOpenFailed', ...
    'Could not open target raw-IQ file.');
rawCleanup = onCleanup(@() fclose(rawFileId)); %#ok<NASGU>
sampleIndexWithinMs = (0:samplesPerMs - 1).';
buffer = emptySnapshotBuffer(delayCount);
writePosition = 0;
uniqueSnapshotStartCount = 0;
previousSampleStart = NaN;
writeChunkRows = 64;
maximumBufferedRows = 4096;

for windowIndex = 1:height(windows)
    row = windows(windowIndex, :);
    sampleStart = double(row.sample_start_zero_based);
    splitSamples = round(double(row.split_samples));
    nav1 = double(row.nav_symbol_1);
    nav2 = double(row.nav_symbol_2);
    assert(sampleStart >= 0 && sampleStart == floor(sampleStart) ...
        && sampleStart + samplesPer40Ms <= rawInfo.bytes / 4 ...
        && splitSamples > 0 && splitSamples < samplesPer40Ms ...
        && ismember(nav1, [-1, 1]) && ismember(nav2, [-1, 1]), ...
        'GNSS:SAGE:Stage0WindowInvalid', ...
        'Invalid Stage0 window identity, bounds, split, or navigation symbol.');
    status = fseek(rawFileId, sampleStart * 4, 'bof');
    assert(status == 0, 'GNSS:SAGE:RawIqSeekFailed', ...
        'Could not seek to Stage0 window %d.', double(row.window_id));
    rawInterleaved = fread(rawFileId, 2 * samplesPer40Ms, 'int16=>double');
    assert(numel(rawInterleaved) == 2 * samplesPer40Ms, ...
        'GNSS:SAGE:RawIqShortRead', ...
        'Short target raw-IQ read for Stage0 window %d.', ...
        double(row.window_id));
    rawWindow = complex(rawInterleaved(1:2:end), ...
        rawInterleaved(2:2:end));

    trackedCodeFrequencyHz = double(row.code_frequency_hz);
    if ~isfinite(trackedCodeFrequencyHz) || trackedCodeFrequencyHz <= 0
        trackedCodeFrequencyHz = cfg.nominalCodeRateHz;
    end
    trackedDopplerHz = double(row.tracking_doppler_hz);
    cn0 = double(row.cn0_db_hz);
    assert(isfinite(trackedDopplerHz) && isfinite(cn0), ...
        'GNSS:SAGE:Stage0TrackingValueInvalid', ...
        'Stage0 tracking Doppler and C/N0 must be finite.');
    carrierReferenceHz = dopplerSignUsed * trackedDopplerHz;
    windowCir = complex(zeros(40, delayCount, 'double'));
    windowRms = zeros(40, 1);
    windowTimeS = zeros(40, 1);
    windowSampleStart = zeros(40, 1);
    windowTrackingDoppler = repmat(trackedDopplerHz, 40, 1);
    windowCodeFrequency = repmat(trackedCodeFrequencyHz, 40, 1);
    windowCn0 = repmat(cn0, 40, 1);
    windowNavSymbol = zeros(40, 1, 'int8');
    windowTransitionOffset = zeros(40, 1, 'int32');

    for snapshotIndex = 0:39
        offset = snapshotIndex * samplesPerMs;
        sampleRange = offset + (1:samplesPerMs);
        rawSnapshot = rawWindow(sampleRange);
        relativeSamples = offset + sampleIndexWithinMs;
        navSigns = repmat(nav2, samplesPerMs, 1);
        navSigns(relativeSamples < splitSamples) = nav1;
        navAtStart = navSigns(1);
        firstTransition = find(navSigns ~= navAtStart, 1, 'first');
        if isempty(firstTransition)
            transitionOffset = 0;
        else
            transitionOffset = firstTransition - 1;
        end

        globalSampleIndex = relativeSamples;
        chipPhase = mod(globalSampleIndex ...
            * trackedCodeFrequencyHz / cfg.fsHz, 1023);
        chipIndex = floor(chipPhase) + 1;
        localCode = g1g2Code(chipIndex);
        [cirSnapshot, rmsValue] = ...
            compute_gnss_code_domain_cir_snapshot( ...
            rawSnapshot, localCode, delaySamples, cfg.fsHz, ...
            carrierReferenceHz, offset / cfg.fsHz, navSigns);

        rowIndex = snapshotIndex + 1;
        windowCir(rowIndex, :) = cirSnapshot;
        windowRms(rowIndex) = rmsValue;
        windowTimeS(rowIndex) = (sampleStart + offset) / cfg.fsHz;
        windowSampleStart(rowIndex) = sampleStart + offset;
        windowNavSymbol(rowIndex) = int8(navAtStart);
        windowTransitionOffset(rowIndex) = int32(transitionOffset);
    end

    assert(all(isfinite(real(windowCir(:)))) ...
        && all(isfinite(imag(windowCir(:)))) ...
        && all(isfinite(windowRms)) && all(windowRms > 0), ...
        'GNSS:SAGE:CIRNonfiniteOutput', ...
        'CIR output contains nonfinite values or nonpositive raw-IQ RMS.');
    windowPdp = mean(abs(windowCir).^2, 1);
    assert(all(isfinite(windowPdp)), ...
        'GNSS:SAGE:CIRNonfiniteOutput', ...
        'PDP output contains nonfinite values.');
    h5write(temporaryH5Path, '/pdp_power', windowPdp, ...
        [windowIndex, 1], [1, delayCount]);

    comparisonIndex = primaryComparisonIndex(windowIndex);
    if comparisonIndex > 0
        [~, peakIndex] = max(windowPdp);
        comparison.pdp_dominant_peak_delay_samples(comparisonIndex) = ...
            delaySamples(peakIndex);
        comparison.pdp_minus_sage_delay_samples(comparisonIndex) = ...
            delaySamples(peakIndex) ...
            - comparison.sage_primary_delay_samples(comparisonIndex);
    end

    buffer = appendSnapshotBuffer(buffer, real(windowCir), ...
        imag(windowCir), windowRms, windowTimeS, ...
        windowTrackingDoppler, windowCodeFrequency, windowCn0, ...
        windowNavSymbol, repmat(uint32(row.window_id), 40, 1), ...
        uint8((1:40).'), windowSampleStart, windowTransitionOffset);
    [~, order] = sortrows([buffer.sampleStart, ...
        double(buffer.windowId), double(buffer.snapshotIndex)], [1, 2, 3]);
    buffer = reorderSnapshotBuffer(buffer, order);
    if windowIndex < height(windows)
        nextWindowStart = sampleStarts(windowIndex + 1);
        safeRows = find(buffer.sampleStart >= nextWindowStart, 1) - 1;
        if isempty(safeRows)
            safeRows = size(buffer.cirReal, 1);
        end
    else
        safeRows = size(buffer.cirReal, 1);
    end
    [buffer, writePosition, uniqueSnapshotStartCount, ...
        previousSampleStart] = flushSnapshotBuffer( ...
        temporaryH5Path, buffer, safeRows, writePosition, ...
        uniqueSnapshotStartCount, previousSampleStart, writeChunkRows);
    assert(size(buffer.cirReal, 1) <= maximumBufferedRows, ...
        'GNSS:SAGE:CIRBufferLimitExceeded', ...
        'Overlapping-window buffer exceeded the bounded 4096-row limit.');
    if mod(windowIndex, 50) == 0 || windowIndex == height(windows)
        fprintf('CIR_STAGE0_WINDOWS=%d/%d\n', ...
            windowIndex, height(windows));
    end
end

clear rawCleanup;
assert(writePosition == snapshotCount && isempty(buffer.sampleStart), ...
    'GNSS:SAGE:CIRSnapshotCountMismatch', ...
    'CIR snapshot count does not equal 40 times Stage0 windows.');
assert(all(isfinite(comparison.pdp_minus_sage_delay_samples)), ...
    'GNSS:SAGE:CIRDelayComparisonInvalid', ...
    'Primary SAGE/CIR delay comparison is nonfinite.');
writetable(comparison, temporaryComparisonPath);

absoluteDifference = abs(comparison.pdp_minus_sage_delay_samples);
summary = struct( ...
    'scene_id', provenance.scene_id, ...
    'prn', provenance.prn, ...
    'tracking_channel', double(provenance.tracking_channel), ...
    'sample_rate_hz', double(provenance.sample_rate_hz), ...
    'stage0_window_count', height(windows), ...
    'cir_snapshot_count', snapshotCount, ...
    'unique_cir_snapshot_start_samples', ...
        uniqueSnapshotStartCount, ...
    'delay_grid_count', delayCount, ...
    'delay_grid_min_samples', delaySamples(1), ...
    'delay_grid_max_samples', delaySamples(end), ...
    'pdp_window_count', height(windows), ...
    'pdp_snapshots_per_window', 40, ...
    'time_monotonic_nondecreasing', true, ...
    'raw_iq_sha256_status', 'NOT_RECOMPUTED', ...
    'doppler_sign_used', dopplerSignUsed, ...
    'amplitude_reference_status', ...
        'UNKNOWN_RECEIVER_GAIN_OR_AGC', ...
    'primary_delay_comparison_count', height(comparison), ...
    'primary_delay_difference_max_abs_samples', max(absoluteDifference), ...
    'primary_delay_difference_median_samples', ...
        median(comparison.pdp_minus_sage_delay_samples));

metadata = struct();
metadata.format_version = 1;
metadata.created_utc = char(datetime('now', 'TimeZone', 'UTC'));
metadata.created_time_zone = 'UTC';
metadata.run_id = provenance.run_id;
metadata.scene_id = provenance.scene_id;
metadata.prn = provenance.prn;
metadata.tracking_channel = double(provenance.tracking_channel);
taskDocument = jsondecode(readUtf8Text(provenance.cir_tasks_json_path));
metadata.cohort_id = taskDocument.cohort_id;
metadata.cohort_json_path = canonicalPath(provenance.cohort_json_path);
metadata.source_cohort_sha256 = lower(char(provenance.cohort_sha256));
metadata.cir_tasks_sha256 = lower(char(provenance.cir_tasks_sha256));
metadata.source_stage0_windows_path = canonicalPath(stage0WindowsCsvPath);
metadata.source_stage0_windows_sha256 = lower(char( ...
    cohortTask.stage_csvs.stage0_valid_windows.sha256));
metadata.source_stage2_selected_paths_path = ...
    canonicalPath(stage2SelectedPathsCsvPath);
metadata.source_stage2_selected_paths_sha256 = lower(char( ...
    cohortTask.stage_csvs.stage2_selected_paths.sha256));
metadata.scene_metadata_path = sceneMetadataPath;
metadata.scene_metadata_sha256 = sha256File(sceneMetadataPath);
metadata.authorized_output_namespace = char( ...
    authorizedTask.output_namespace);
metadata.sample_rate_hz = double(provenance.sample_rate_hz);
metadata.raw_iq_path = canonicalPath(rawIqPath);
metadata.raw_iq_size_bytes = rawInfo.bytes;
metadata.raw_iq_sha256 = 'NOT_RECOMPUTED';
metadata.frozen_sage_sha256 = provenance.frozen_sage_sha256;
metadata.doppler_sign_used = dopplerSignUsed;
metadata.delay_grid_samples = delaySamples;
metadata.delay_grid_source = ...
    'default_sage_configuration: mainDelayMinimumSamples:delayStepSamples:(mainDelayMaximumSamples+maximumExcessDelaySamples)';
metadata.cir_definition = ...
    ['One-ms coherent code-domain correlation: samplewise NAV sign wipe; ' ...
    'per-snapshot complex-mean removal; tracking-Doppler wipe using ' ...
    'dopplerSignUsed*tracking_doppler_hz; tracked-rate GPS C/A code; ' ...
    'no per-snapshot RMS normalization; correlation divided by sample count.'];
metadata.fractional_delay_interpolation = ...
    'PCHIP interpolation of integer-delay circular FFT correlations; delay samples are from frozen default configuration.';
metadata.raw_iq_rms_definition = ...
    'sqrt(mean(abs(raw complex int16 IQ)^2)) before NAV wipe, DC removal, or normalization; units are ADC counts.';
metadata.time_axis_semantics = ...
    ['Absolute recording seconds from zero-based raw sample index. ' ...
    'Snapshots are sorted nondecreasing by sample start; overlapping ' ...
    'Stage0 40-ms windows intentionally repeat timestamps under separate window IDs.'];
metadata.pdp_definition = ...
    'For every Stage0 window, arithmetic mean of the powers of its 40 one-ms CIR snapshots; no coherent complex sum.';
metadata.nav_symbol_semantics = ...
    ['nav_symbol is the sign applied to the first sample in each snapshot; ' ...
    'nav_symbol_transition_offset_samples is 0 when there is no in-snapshot ' ...
    'transition and otherwise the number of leading samples using that sign.'];
metadata.amplitude_reference_status = ...
    'UNKNOWN_RECEIVER_GAIN_OR_AGC';
metadata.amplitude_calibration_metadata_found = ...
    calibrationMetadataFound;
metadata.stage0_window_count = height(windows);
metadata.cir_snapshot_count = snapshotCount;
metadata.unique_cir_snapshot_start_samples = ...
    uniqueSnapshotStartCount;
metadata.delay_grid_count = delayCount;
metadata.pdp_snapshots_per_window = 40;
metadata.primary_delay_comparison = struct( ...
    'count', height(comparison), ...
    'max_abs_difference_samples', max(absoluteDifference), ...
    'median_signed_difference_samples', ...
    median(comparison.pdp_minus_sage_delay_samples), ...
    'csv_path', delayComparisonCsvPath);
metadata.validation = struct( ...
    'cir_all_finite', true, 'raw_iq_rms_all_positive', true, ...
    'time_monotonic_nondecreasing', true, ...
    'delay_grid_fixed', true, ...
    'pdp_stage0_window_one_to_one', true, ...
    'pdp_40ms_arithmetic_mean_of_40_powers', true);

metadataText = jsonencode(metadata);
