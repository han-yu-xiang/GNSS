    && strcmp(cohortDocument.cohort_id, taskDocument.cohort_id) ...
    && double(cohortDocument.schema_version) == 1 ...
    && double(cohortDocument.eligible_count) == ...
    numel(cohortDocument.tasks), ...
    'GNSS:SAGE:CIRCohortInvalid', ...
    'cohort.json does not have the expected version-1 task schema.');

