function pathText = resolveProjectPath(projectRoot, pathValue)
pathValue = char(pathValue);
candidate = java.io.File(pathValue);
if candidate.isAbsolute()
    pathText = canonicalPath(pathValue);
else
    pathText = canonicalPath(fullfile(projectRoot, ...
        strrep(pathValue, '/', filesep)));
end
end

function pathText = canonicalPath(pathValue)
pathText = char(java.io.File(char(pathValue)).getCanonicalPath());
end

function inside = isPathWithin(parentPath, childPath)
parentPath = canonicalPath(parentPath);
childPath = canonicalPath(childPath);
prefix = [parentPath, filesep];
inside = numel(childPath) > numel(prefix) ...
    && strncmpi(childPath, prefix, numel(prefix));
end

function valid = isSha256(value)
value = lower(char(value));
valid = numel(value) == 64 ...
    && ~isempty(regexp(value, '^[0-9a-f]{64}$', 'once'));
end

function digest = sha256File(filename)
fileId = fopen(filename, 'rb');
assert(fileId >= 0, 'GNSS:SAGE:CIRFileHashReadFailed', ...
    'Could not open file for SHA-256: %s', filename);
fileCleanup = onCleanup(@() fclose(fileId)); %#ok<NASGU>
messageDigest = java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes = fread(fileId, 1024 * 1024, '*uint8');
    if isempty(bytes)
        break;
    end
    messageDigest.update(int8(bytes));
end
digestBytes = typecast(messageDigest.digest(), 'uint8');
digest = lower(reshape(dec2hex(digestBytes, 2).', 1, []));
clear fileCleanup;
end

