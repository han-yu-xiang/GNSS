        'GNSS:SAGE:CIRCohortInvalid', ...
        'cohort.json task rows are missing required source references.');
    cohortRunIds = cellfun(@(row) char(row.run_id), cohortTasks, ...
        'UniformOutput', false);
elseif isstruct(cohortTasks)
    assert(~isempty(cohortTasks) ...
        && all(isfield(cohortTasks, requiredCohortTaskFields)), ...
        'GNSS:SAGE:CIRCohortInvalid', ...
        'cohort.json task rows are missing required source references.');
    cohortRunIds = {cohortTasks.run_id};
else
    error('GNSS:SAGE:CIRCohortInvalid', ...
        'cohort.json tasks must decode to a struct array or cell array of task structs.');
end
cohortMatches = find(strcmp(cohortRunIds, char(provenance.run_id)));
assert(numel(cohortMatches) == 1, ...
    'GNSS:SAGE:CIRIdentityAuthorizationMismatch', ...
    'run_id must match exactly one frozen cohort.json row.');
