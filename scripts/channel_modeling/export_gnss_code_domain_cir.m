    && strcmp(task.prn, cohortTask.prn) ...
    && double(task.tracking_channel) == ...
    double(cohortTask.tracking_channel) ...
    && strcmp(task.output_namespace, cohortTask.output_namespace) ...
    && strcmpi(char(provenance.frozen_sage_sha256), ...
    cohortTask.source_frozen_sage_sha256) ...
    && any(strcmp(cohortTask.source_summary_status, ...
    {'COMPLETE', 'ALREADY_COMPLETE'})), ...
    'GNSS:SAGE:CIRIdentityAuthorizationMismatch', ...
    'cir_tasks.json row conflicts with frozen cohort provenance.');
requiredStageCsvs = {'stage0_valid_windows', 'stage2_selected_paths'};
assert(isstruct(cohortTask.stage_csvs) ...
    && all(isfield(cohortTask.stage_csvs, requiredStageCsvs)), ...
    'GNSS:SAGE:CIRCohortInvalid', ...
    'cohort.json lacks the required Stage0 or Stage2 CSV reference.');
