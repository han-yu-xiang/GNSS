function scope = assert_wp5_alpha_full_frozen_scope(projectRoot, manifest, preflight)
%ASSERT_WP5_ALPHA_FULL_FROZEN_SCOPE Bind a batch manifest to frozen inputs.
% This guard runs before the batch creates any outputs. It independently
% rechecks the approved cohort, Stage2 ledger, Stage4 pins and ordered run
% identities rather than trusting an adjacent, re-hashable preflight JSON.

projectRoot = char(string(projectRoot));
expected = struct( ...
    'cohort_sha256', '287e891fae0cd294a85c073080611a19b7389ece46240b89cb1d5dab4df90229', ...
    'stage2_ledger_sha256', 'bbb8cac8338194b5527e00812a6547129a58466cc5fdd7db36b8c44bba01e551', ...
    'stage4_pin_manifest_sha256', '32c10789efefe4e87cabee4ac8978cd36a4a132f4d3b5640c8e4b8b0851a635d', ...
    'frozen_sage_sha256', 'bffc123c97af77f0a797f417d3866e9a34feab7729c5c1575352f53bc3571b9c', ...
    'run_count', 83, 'path_count', 16761, 'window_count', 7847, ...
    'mpc_count', 8914, 'direct_count', 7847, 'excluded_count', 6);

cohortPath = fullfile(projectRoot, 'dataset_generation_logs', ...
    'channel_modeling', ...
    'mainline_1023_cohort_v1_20261022T082520Z', 'cohort.json');
ledgerPath = fullfile(projectRoot, 'dataset_generation_logs', ...
    'channel_modeling', ...
    'mainline_1023_model_v1_20261023T135341Z', 'stage2_ledger.csv');
repositoryRoot = fileparts(fileparts(fileparts(mfilename('fullpath'))));
stage4PinPath = fullfile(repositoryRoot, 'reports', ...
    'data_consolidation_20261003', 'mainline_1023_model_v1', ...
    'stage4_joint_summary_sha256_pins_20261023.json');
sagePath = fullfile(projectRoot, 'scripts', 'sage_pipeline', ...
    'run_nav_sage_pipeline.m');

fixedPaths = {cohortPath, ledgerPath, stage4PinPath, sagePath};
fixedShas = {expected.cohort_sha256, expected.stage2_ledger_sha256, ...
    expected.stage4_pin_manifest_sha256, expected.frozen_sage_sha256};
for k = 1:numel(fixedPaths)
    assert(isfile(fixedPaths{k}) && ...
        strcmpi(sha256File(fixedPaths{k}), fixedShas{k}), ...
        'GNSS:WP5:FrozenPinMismatch', ...
        'A canonical frozen input is missing or its SHA differs: %s', ...
        fixedPaths{k});
end

preflightFields = {'cohort_sha256', 'stage2_ledger_sha256', ...
    'stage4_pin_manifest_sha256', 'frozen_sage_sha256', 'run_count', ...
    'stage2_path_count', 'stage2_window_count', 'stage2_mpc_count', ...
    'stage2_direct_count', 'ready_run_count', ...
    'rejected_run_count', 'input_manifest_sha256', 'status'};
assert(all(isfield(preflight, preflightFields)), ...
    'GNSS:WP5:FrozenPinMismatch', ...
    'Source preflight lacks required frozen-scope fields.');
for k = 1:4
    field = preflightFields{k};
    assert(strcmpi(char(string(preflight.(field))), fixedShas{k}), ...
        'GNSS:WP5:FrozenPinMismatch', ...
        'Source preflight %s differs from the approved frozen pin.', field);
end
expectedCountFields = {'run_count', 'stage2_path_count', ...
    'stage2_window_count', 'stage2_mpc_count', 'stage2_direct_count'};
expectedCountValues = [expected.run_count, expected.path_count, ...
    expected.window_count, expected.mpc_count, expected.direct_count];
for k = 1:numel(expectedCountFields)
    field = expectedCountFields{k};
    assert(isnumeric(preflight.(field)) && isscalar(preflight.(field)) ...
        && double(preflight.(field)) == expectedCountValues(k), ...
        'GNSS:WP5:FrozenPinMismatch', ...
        'Source preflight %s differs from the approved frozen count.', field);
end

cohort = jsondecode(fileread(cohortPath));
stage4Pins = jsondecode(fileread(stage4PinPath));
assert(isfield(cohort, 'tasks') && numel(cohort.tasks) == expected.run_count ...
    && double(cohort.eligible_count) == expected.run_count ...
    && double(cohort.excluded_count) == expected.excluded_count ...
    && isfield(stage4Pins, 'stage4_joint_summary_sha256_by_run_id') ...
    && double(stage4Pins.task_count) == expected.run_count ...
    && strcmpi(char(stage4Pins.cohort_sha256), expected.cohort_sha256), ...
    'GNSS:WP5:FrozenPinMismatch', ...
    'Canonical cohort or Stage4 pin manifest has inconsistent scope.');

scopeFields = {'run_id', 'scene_id', 'prn', 'tracking_channel', ...
    'frozen_sage_sha256', 'relocation_receipt_path', ...
    'relocation_receipt_sha256', 'stage2_mat_path', 'stage2_mat_sha256', ...
    'stage2_selected_paths_csv_path', ...
    'stage2_selected_paths_csv_sha256', 'stage3_persistence_csv_path', ...
    'stage3_persistence_csv_sha256', ...
    'stage3_reliable_centers_csv_path', ...
    'stage4_joint_summary_csv_path', 'stage4_joint_summary_csv_sha256', ...
    'stage4_joint_paths_csv_path', 'stage4_joint_paths_csv_sha256', ...
    'stage2_path_rows', 'stage2_window_count', 'stage2_mpc_count', ...
    'stage2_direct_count', 'preflight_status'};
assert(all(ismember(scopeFields, manifest.Properties.VariableNames)), ...
    'GNSS:WP5:FrozenRunIdentityMismatch', ...
    'Manifest lacks a field required to verify the approved run identity.');

frozenLedger = readtable(ledgerPath, 'Delimiter', ',', 'TextType', 'string');
ledgerFields = {'run_id', 'scene_id', 'prn', 'tracking_channel', ...
    'window_id', 'path_id', 'is_multipath', 'source_stage2_csv_sha256'};
assert(all(ismember(ledgerFields, frozenLedger.Properties.VariableNames)) ...
    && height(frozenLedger) == expected.path_count, ...
    'GNSS:WP5:FrozenPinMismatch', ...
    'Canonical Stage2 ledger schema or row count differs from the frozen scope.');
ledgerKeys = string(frozenLedger.run_id) + "|" + ...
    string(frozenLedger.window_id) + "|" + string(frozenLedger.path_id);
ledgerWindows = string(frozenLedger.run_id) + "|" + ...
    string(frozenLedger.window_id);
assert(numel(unique(ledgerKeys)) == expected.path_count ...
    && numel(unique(ledgerWindows)) == expected.window_count ...
    && sum(double(frozenLedger.is_multipath) == 1) == expected.mpc_count ...
    && sum(double(frozenLedger.is_multipath) == 0) == expected.direct_count, ...
    'GNSS:WP5:FrozenPinMismatch', ...
    'Canonical Stage2 ledger identities or aggregate counts differ.');

cohortRunIds = strings(expected.run_count, 1);
for k = 1:expected.run_count
    task = cohortTaskAt(cohort.tasks, k);
    cohortRunIds(k) = string(task.run_id);
end
manifestRunIds = string(manifest.run_id(:));
assert(numel(unique(cohortRunIds)) == expected.run_count ...
    && isequal(manifestRunIds, cohortRunIds), ...
    'GNSS:WP5:FrozenRunOrderMismatch', ...
    'Manifest run identities or order differ from the frozen cohort.');

readyCount = sum(string(manifest.preflight_status) == "READY");
rejectedCount = sum(string(manifest.preflight_status) == "REJECTED");
expectedPreflightStatus = 'PREFLIGHT_PARTIAL';
if rejectedCount == 0
    expectedPreflightStatus = 'PREFLIGHT_PASS';
end
assert(readyCount + rejectedCount == expected.run_count ...
    && double(preflight.ready_run_count) == readyCount ...
    && double(preflight.rejected_run_count) == rejectedCount ...
    && strcmp(char(preflight.status), expectedPreflightStatus), ...
    'GNSS:WP5:FrozenPinMismatch', ...
    'Preflight status or ready/rejected counts do not match the manifest.');

ledgerRunIds = string(frozenLedger.run_id);
stage4Map = stage4Pins.stage4_joint_summary_sha256_by_run_id;
for k = 1:expected.run_count
    task = cohortTaskAt(cohort.tasks, k);
    row = manifest(k, :);
    runId = cohortRunIds(k);
    ledgerRows = frozenLedger(ledgerRunIds == runId, :);
    taskCounts = task.stage_counts_from_gate_a;
    expectedRows = height(ledgerRows);
    expectedWindows = numel(unique(double(ledgerRows.window_id)));
    expectedMpc = sum(double(ledgerRows.is_multipath) == 1);
    expectedDirect = sum(double(ledgerRows.is_multipath) == 0);
    sourceShas = unique(lower(string(ledgerRows.source_stage2_csv_sha256)));
    assert(~isempty(ledgerRows) && numel(sourceShas) == 1 ...
        && string(row.scene_id) == string(task.scene_id) ...
        && string(row.prn) == string(task.prn) ...
        && double(row.tracking_channel) == double(task.tracking_channel) ...
        && string(row.frozen_sage_sha256) == expected.frozen_sage_sha256 ...
        && double(row.stage2_path_rows) == expectedRows ...
        && double(row.stage2_window_count) == expectedWindows ...
        && double(row.stage2_mpc_count) == expectedMpc ...
        && double(row.stage2_direct_count) == expectedDirect ...
        && expectedRows == double(taskCounts.stage2_selected_path_count) ...
        && expectedMpc == double(taskCounts.stage2_mpc_count) ...
        && expectedDirect == double(taskCounts.direct_path_count) ...
        && string(row.stage2_selected_paths_csv_sha256) == sourceShas(1), ...
        'GNSS:WP5:FrozenRunIdentityMismatch', ...
        'Manifest identity or Stage2 mapping differs for %s.', runId);

    namespace = char(task.output_namespace);
    assertPath(projectRoot, row.relocation_receipt_path, ...
        char(task.relocation_receipt.path), runId, 'relocation receipt');
    assertHash(row.relocation_receipt_sha256, ...
        char(task.relocation_receipt.sha256), runId, 'relocation receipt');
    assertPath(projectRoot, row.stage2_mat_path, ...
        fullfile(namespace, 'stage2_nav_sage_L1_L4.mat'), runId, 'Stage2 MAT');
    assertPath(projectRoot, row.stage2_selected_paths_csv_path, ...
        char(task.stage_csvs.stage2_selected_paths.path), runId, 'Stage2 CSV');
    assertPath(projectRoot, row.stage3_persistence_csv_path, ...
        char(task.stage_csvs.stage3_persistence.path), runId, 'Stage3 persistence');
    assertPath(projectRoot, row.stage3_reliable_centers_csv_path, ...
        fullfile(namespace, 'stage3_reliable_centers.csv'), runId, ...
        'Stage3 reliable centers');
    assertPath(projectRoot, row.stage4_joint_paths_csv_path, ...
        char(task.stage_csvs.stage4_joint_paths.path), runId, 'Stage4 paths');
    assertHash(row.stage3_persistence_csv_sha256, ...
        char(task.stage_csvs.stage3_persistence.sha256), runId, 'Stage3 persistence');
    assertHash(row.stage4_joint_paths_csv_sha256, ...
        char(task.stage_csvs.stage4_joint_paths.sha256), runId, 'Stage4 paths');
    assertHash(row.stage2_selected_paths_csv_sha256, ...
        char(task.stage_csvs.stage2_selected_paths.sha256), runId, 'Stage2 CSV');

    assert(isfield(stage4Map, char(runId)), ...
        'GNSS:WP5:FrozenRunIdentityMismatch', ...
        'Stage4 pin manifest has no entry for %s.', runId);
    stage4Pin = stage4Map.(char(runId));
    assertPath(projectRoot, row.stage4_joint_summary_csv_path, ...
        char(stage4Pin.path), runId, 'Stage4 summary');
    assertHash(row.stage4_joint_summary_csv_sha256, ...
        char(stage4Pin.sha256), runId, 'Stage4 summary');
end

scope = struct('sage_sha256', expected.frozen_sage_sha256, ...
    'run_count', expected.run_count, 'path_count', expected.path_count, ...
    'window_count', expected.window_count, 'mpc_count', expected.mpc_count, ...
    'direct_count', expected.direct_count);
end

function assertPath(projectRoot, actual, expectedRelative, runId, label)
expectedPath = fullPath(projectRoot, expectedRelative);
actualPath = char(java.io.File(char(string(actual))).getCanonicalPath());
assert(strcmpi(actualPath, expectedPath), ...
    'GNSS:WP5:FrozenRunIdentityMismatch', ...
    '%s path differs from frozen identity for %s.', label, runId);
end

function assertHash(actual, expected, runId, label)
actual = lower(char(string(actual)));
expected = lower(char(string(expected)));
assert(~isempty(regexp(actual, '^[0-9a-f]{64}$', 'once')) ...
    && strcmp(actual, expected), ...
    'GNSS:WP5:FrozenRunIdentityMismatch', ...
    '%s SHA differs from frozen identity for %s.', label, runId);
end

function path = fullPath(root, relative)
relative = strrep(char(string(relative)), '/', filesep);
path = char(java.io.File(fullfile(root, relative)).getCanonicalPath());
end

function task = cohortTaskAt(tasks, index)
if iscell(tasks)
    task = tasks{index};
else
    task = tasks(index);
end
assert(isstruct(task) && isscalar(task), ...
    'GNSS:WP5:FrozenRunIdentityMismatch', ...
    'Frozen cohort task entry %d is not a JSON object.', index);
end

function sha = sha256File(path)
fid = fopen(path, 'rb');
assert(fid >= 0, 'GNSS:WP5:HashReadFailed', ...
    'Could not open file for SHA-256: %s', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
digest = java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes = fread(fid, 1024 * 1024, '*uint8');
    if isempty(bytes), break; end
    digest.update(typecast(bytes(:), 'int8'));
end
raw = typecast(digest.digest(), 'uint8');
sha = lower(reshape(dec2hex(raw, 2).', 1, []));
end
