function summary = validate_gnss_code_domain_cir(hdf5Path, ...
    expectedStage0WindowCount)
%VALIDATE_GNSS_CODE_DOMAIN_CIR Verify CIR structure and PDP in bounded chunks.

if nargin < 2
    expectedStage0WindowCount = [];
end
assert(isfile(hdf5Path), 'GNSS:SAGE:CIRValidationInputMissing', ...
    'CIR HDF5 file is missing.');
if ~isempty(expectedStage0WindowCount)
    assert(isscalar(expectedStage0WindowCount) ...
        && isfinite(expectedStage0WindowCount) ...
        && expectedStage0WindowCount >= 1 ...
        && expectedStage0WindowCount == floor(expectedStage0WindowCount), ...
        'GNSS:SAGE:CIRValidationExpectedWindowCountInvalid', ...
        'Expected Stage0 window count must be a positive integer.');
end

try
    info = h5info(hdf5Path);
catch exception
    error('GNSS:SAGE:CIRValidationReadFailed', ...
        'Could not read CIR HDF5 metadata: %s', exception.message);
end
datasetNames = {info.Datasets.Name};
required = {'cir_real', 'cir_imag', 'time_s', 'delay_samples', ...
    'raw_iq_rms', 'tracking_doppler_hz', 'code_frequency_hz', ...
    'cn0_db_hz', 'nav_symbol', 'window_id', ...
    'snapshot_index_in_window', 'sample_start_zero_based', ...
    'nav_symbol_transition_offset_samples', 'pdp_window_id', ...
    'pdp_time_s', 'pdp_start_sample_zero_based', ...
    'pdp_interval_count', 'pdp_power'};
assert(all(ismember(required, datasetNames)), ...
    'GNSS:SAGE:CIRValidationSchemaMismatch', ...
    'CIR HDF5 file is missing a required dataset.');

cirRealSize = datasetDimensions(info, 'cir_real');
cirImagSize = datasetDimensions(info, 'cir_imag');
pdpPowerSize = datasetDimensions(info, 'pdp_power');
assert(numel(cirRealSize) == 2 && numel(cirImagSize) == 2 ...
    && isequal(cirImagSize, cirRealSize) ...
    && numel(pdpPowerSize) == 2, ...
    'GNSS:SAGE:CIRValidationDimensionsMismatch', ...
    'CIR/PDP datasets must be two-dimensional and shape-compatible.');
nSnapshots = cirRealSize(1);
nDelays = cirRealSize(2);
if ~isempty(expectedStage0WindowCount)
    nWindows = double(expectedStage0WindowCount);
else
    pdpWindowId = readHdf5Dataset(hdf5Path, '/pdp_window_id');
    nWindows = numel(pdpWindowId);
end

timeS = double(readHdf5Dataset(hdf5Path, '/time_s'));
delaySamples = double(readHdf5Dataset(hdf5Path, '/delay_samples'));
rawIqRms = double(readHdf5Dataset(hdf5Path, '/raw_iq_rms'));
trackingDopplerHz = double(readHdf5Dataset( ...
    hdf5Path, '/tracking_doppler_hz'));
codeFrequencyHz = double(readHdf5Dataset( ...
    hdf5Path, '/code_frequency_hz'));
cn0DbHz = double(readHdf5Dataset(hdf5Path, '/cn0_db_hz'));
navSymbol = double(readHdf5Dataset(hdf5Path, '/nav_symbol'));
navTransitionOffset = double(readHdf5Dataset( ...
    hdf5Path, '/nav_symbol_transition_offset_samples'));
windowId = readHdf5Dataset(hdf5Path, '/window_id');
snapshotIndex = readHdf5Dataset(hdf5Path, '/snapshot_index_in_window');
sampleStart = double(readHdf5Dataset( ...
    hdf5Path, '/sample_start_zero_based'));
pdpWindowId = readHdf5Dataset(hdf5Path, '/pdp_window_id');
pdpTimeS = double(readHdf5Dataset(hdf5Path, '/pdp_time_s'));
pdpStartSample = double(readHdf5Dataset( ...
    hdf5Path, '/pdp_start_sample_zero_based'));
pdpIntervalCount = readHdf5Dataset(hdf5Path, '/pdp_interval_count');
pdpWindowId = pdpWindowId(:);
nWindows = numel(pdpWindowId);

expectedDelaySamples = -5:0.1:40;
assert(nSnapshots == 40 * nWindows, ...
    'GNSS:SAGE:CIRValidationSnapshotCountMismatch', ...
    'CIR snapshot count must equal 40 times the Stage0 window count.');
if ~isempty(expectedStage0WindowCount)
    assert(nWindows == double(expectedStage0WindowCount), ...
        'GNSS:SAGE:CIRValidationSnapshotCountMismatch', ...
        'HDF5 PDP window count disagrees with the expected Stage0 count.');
end
assert(nWindows > 0 && nDelays == 451 ...
    && isequal(cirRealSize, [nSnapshots, 451]) ...
    && isequal(pdpPowerSize, [nWindows, 451]) ...
    && isequal(delaySamples(:), expectedDelaySamples(:)), ...
    'GNSS:SAGE:CIRValidationDimensionsMismatch', ...
    'CIR/PDP dimensions or frozen 451-bin delay grid are invalid.');
assertVectorDimensions(info, 'time_s', nSnapshots);
assertVectorDimensions(info, 'delay_samples', 451);
assertVectorDimensions(info, 'raw_iq_rms', nSnapshots);
assertVectorDimensions(info, 'tracking_doppler_hz', nSnapshots);
assertVectorDimensions(info, 'code_frequency_hz', nSnapshots);
assertVectorDimensions(info, 'cn0_db_hz', nSnapshots);
assertVectorDimensions(info, 'nav_symbol', nSnapshots);
assertVectorDimensions(info, 'window_id', nSnapshots);
assertVectorDimensions(info, 'snapshot_index_in_window', nSnapshots);
assertVectorDimensions(info, 'sample_start_zero_based', nSnapshots);
assertVectorDimensions(info, ...
    'nav_symbol_transition_offset_samples', nSnapshots);
assertVectorDimensions(info, 'pdp_window_id', nWindows);
assertVectorDimensions(info, 'pdp_time_s', nWindows);
assertVectorDimensions(info, 'pdp_start_sample_zero_based', nWindows);
assertVectorDimensions(info, 'pdp_interval_count', nWindows);

windowIds = double(windowId(:));
snapshotIndices = double(snapshotIndex(:));
pdpWindowIds = double(pdpWindowId(:));
sampleStarts = sampleStart(:);
timeS = timeS(:);
rawIqRms = rawIqRms(:);
pdpTimeS = pdpTimeS(:);
pdpStartSample = pdpStartSample(:);
pdpIntervalCount = double(pdpIntervalCount(:));
assert(numel(unique(pdpWindowIds)) == nWindows ...
    && all(isfinite(pdpWindowIds)) && all(pdpWindowIds > 0) ...
    && all(pdpWindowIds == floor(pdpWindowIds)) ...
    && isequal(unique(windowIds), sort(pdpWindowIds)), ...
    'GNSS:SAGE:CIRValidationPdpMappingMismatch', ...
    'PDP window IDs must uniquely cover all CIR snapshot windows.');
assert(numel(timeS) == nSnapshots && numel(rawIqRms) == nSnapshots ...
    && numel(windowIds) == nSnapshots ...
    && numel(snapshotIndices) == nSnapshots ...
    && numel(sampleStarts) == nSnapshots ...
    && numel(pdpTimeS) == nWindows ...
    && numel(pdpStartSample) == nWindows ...
    && numel(pdpIntervalCount) == nWindows, ...
    'GNSS:SAGE:CIRValidationDimensionsMismatch', ...
    'A snapshot or Stage0 metadata vector has an inconsistent length.');
assert(all(isfinite(timeS)) && all(diff(timeS) >= 0) ...
    && all(isfinite(sampleStarts)) ...
    && all(sampleStarts >= 0) ...
    && all(sampleStarts == floor(sampleStarts)) ...
    && all(isfinite(rawIqRms)) && all(rawIqRms > 0) ...
    && all(isfinite(trackingDopplerHz)) ...
    && all(isfinite(codeFrequencyHz)) && all(codeFrequencyHz > 0) ...
    && all(isfinite(cn0DbHz)) ...
    && all(ismember(navSymbol, [-1, 1])) ...
    && all(isfinite(navTransitionOffset)) ...
    && all(navTransitionOffset >= 0) ...
    && all(navTransitionOffset < 10230) ...
    && all(navTransitionOffset == floor(navTransitionOffset)) ...
    && all(isfinite(pdpTimeS)) && all(isfinite(pdpStartSample)) ...
    && all(pdpStartSample >= 0) ...
    && all(pdpStartSample == floor(pdpStartSample)) ...
    && all(pdpIntervalCount == 40) ...
    && all(isfinite(windowIds)) && all(windowIds > 0) ...
    && all(windowIds == floor(windowIds)) ...
    && all(snapshotIndices >= 1) && all(snapshotIndices <= 40) ...
    && all(snapshotIndices == floor(snapshotIndices)), ...
    'GNSS:SAGE:CIRValidationValuesInvalid', ...
    'CIR/PDP metadata contains invalid values or unordered time.');
deltaStart = diff(sampleStarts);
deltaWindowId = diff(windowIds);
deltaSnapshotIndex = diff(snapshotIndices);
badTieOrder = deltaStart == 0 & (deltaWindowId < 0 ...
    | (deltaWindowId == 0 & deltaSnapshotIndex <= 0));
assert(all(deltaStart >= 0) && ~any(badTieOrder), ...
    'GNSS:SAGE:CIRValidationSnapshotOrderMismatch', ...
    'CIR snapshots are not sorted by sample, window ID, and index.');
assert(all(abs(timeS - sampleStarts / 10230000) ...
    <= eps(max(1, max(abs(timeS))))), ...
    'GNSS:SAGE:CIRValidationStage0AlignmentMismatch', ...
    'Snapshot time values must equal zero-based samples at 10.23 MHz.');
assert(all(diff(pdpStartSample) >= 0) ...
    && all(diff(pdpTimeS) >= 0), ...
    'GNSS:SAGE:CIRValidationStage0AlignmentMismatch', ...
    'PDP Stage0 starts and times must be nondecreasing.');

pdpAbsoluteTolerance = 0;
pdpRelativeTolerance = 0;
pdpMeanExactlyRecomputed = true;
maxPdpRecomputationDifference = 0;
completedWindows = 0;
activeWindowIds = zeros(0, 1);
activeSnapshotCounts = zeros(0, 1, 'uint8');
activeFirstSampleStarts = zeros(0, 1);
activeFirstTimes = zeros(0, 1);
activeCirReal = cell(0, 1);
activeCirImag = cell(0, 1);
pdpRowByWindowId = containers.Map( ...
    'KeyType', 'double', 'ValueType', 'double');
for windowIndex = 1:nWindows
    pdpRowByWindowId(pdpWindowIds(windowIndex)) = windowIndex;
end
chunkRows = 64;
maximumActiveWindows = 64;
for chunkStart = 1:chunkRows:nSnapshots
    chunkCount = min(chunkRows, nSnapshots - chunkStart + 1);
    cirReal = double(readHdf5Dataset(hdf5Path, '/cir_real', ...
        [chunkStart, 1], [chunkCount, nDelays]));
    cirImag = double(readHdf5Dataset(hdf5Path, '/cir_imag', ...
        [chunkStart, 1], [chunkCount, nDelays]));
    assert(all(isfinite(cirReal(:))) && all(isfinite(cirImag(:))), ...
        'GNSS:SAGE:CIRValidationValuesInvalid', ...
        'CIR contains nonfinite values.');

    for localRow = 1:chunkCount
        globalRow = chunkStart + localRow - 1;
        currentWindowId = windowIds(globalRow);
        assert(isKey(pdpRowByWindowId, currentWindowId), ...
            'GNSS:SAGE:CIRValidationPdpMappingMismatch', ...
            'A CIR snapshot references a window absent from the PDP map.');
        activeIndex = find(activeWindowIds == currentWindowId, 1);
        if isempty(activeIndex)
            assert(numel(activeWindowIds) < maximumActiveWindows, ...
                'GNSS:SAGE:CIRValidationOverlapBufferExceeded', ...
                'More than 64 overlapping windows exceed the bounded QA buffer.');
            activeWindowIds(end + 1, 1) = currentWindowId; %#ok<AGROW>
            activeSnapshotCounts(end + 1, 1) = uint8(0); %#ok<AGROW>
            activeFirstSampleStarts(end + 1, 1) = NaN; %#ok<AGROW>
            activeFirstTimes(end + 1, 1) = NaN; %#ok<AGROW>
            activeCirReal{end + 1, 1} = zeros(0, nDelays); %#ok<AGROW>
            activeCirImag{end + 1, 1} = zeros(0, nDelays); %#ok<AGROW>
            activeIndex = numel(activeWindowIds);
        end
        nextSnapshotIndex = double(activeSnapshotCounts(activeIndex)) + 1;
        assert(snapshotIndices(globalRow) == nextSnapshotIndex, ...
            'GNSS:SAGE:CIRValidationSnapshotMappingMismatch', ...
            'A Stage0 window must contain ordered snapshot indices 1 through 40.');
        if nextSnapshotIndex == 1
            activeFirstSampleStarts(activeIndex) = sampleStarts(globalRow);
            activeFirstTimes(activeIndex) = timeS(globalRow);
        end
        expectedWindowSample = activeFirstSampleStarts(activeIndex) ...
            + (nextSnapshotIndex - 1) * 10230;
        assert(sampleStarts(globalRow) == expectedWindowSample, ...
            'GNSS:SAGE:CIRValidationStage0AlignmentMismatch', ...
            'Window snapshots must advance by 1 ms from their Stage0 start.');
        activeSnapshotCounts(activeIndex) = ...
            activeSnapshotCounts(activeIndex) + uint8(1);
        activeCirReal{activeIndex}(end + 1, :) = cirReal(localRow, :);
        activeCirImag{activeIndex}(end + 1, :) = cirImag(localRow, :);

        if activeSnapshotCounts(activeIndex) == 40
            recomputedPdp = mean(abs(complex( ...
                activeCirReal{activeIndex}, ...
                activeCirImag{activeIndex})).^2, 1);
            pdpRow = pdpRowByWindowId(currentWindowId);
            assert(pdpStartSample(pdpRow) ...
                == activeFirstSampleStarts(activeIndex) ...
                && abs(pdpTimeS(pdpRow) - activeFirstTimes(activeIndex)) ...
                <= eps(max(1, abs(activeFirstTimes(activeIndex)))), ...
                'GNSS:SAGE:CIRValidationStage0AlignmentMismatch', ...
                'PDP time/start do not match the corresponding Stage0 window.');
            expectedPdp = double(readHdf5Dataset(hdf5Path, ...
                '/pdp_power', [pdpRow, 1], [1, nDelays]));
            assert(all(isfinite(expectedPdp)), ...
                'GNSS:SAGE:CIRValidationValuesInvalid', ...
                'PDP contains nonfinite values.');
            difference = abs(recomputedPdp - expectedPdp);
            tolerance = pdpAbsoluteTolerance ...
                + pdpRelativeTolerance .* abs(expectedPdp);
            assert(all(difference <= tolerance), ...
                'GNSS:SAGE:CIRValidationPdpRecomputationMismatch', ...
                'Stored PDP disagrees with the mean power of its 40 CIR snapshots.');
            maxPdpRecomputationDifference = max( ...
                maxPdpRecomputationDifference, max(difference));
            pdpMeanExactlyRecomputed = pdpMeanExactlyRecomputed ...
                && isequal(recomputedPdp, expectedPdp);
            completedWindows = completedWindows + 1;
            keepWindow = true(numel(activeWindowIds), 1);
            keepWindow(activeIndex) = false;
            activeWindowIds = activeWindowIds(keepWindow);
            activeSnapshotCounts = activeSnapshotCounts(keepWindow);
            activeFirstSampleStarts = activeFirstSampleStarts(keepWindow);
            activeFirstTimes = activeFirstTimes(keepWindow);
            activeCirReal = activeCirReal(keepWindow);
            activeCirImag = activeCirImag(keepWindow);
        end
    end
end
assert(isempty(activeWindowIds) && isempty(activeSnapshotCounts) ...
    && isempty(activeFirstSampleStarts) && isempty(activeFirstTimes) ...
    && isempty(activeCirReal) && isempty(activeCirImag) ...
    && completedWindows == nWindows, ...
    'GNSS:SAGE:CIRValidationSnapshotMappingMismatch', ...
    'Every Stage0 window must map to exactly 40 CIR snapshots.');

summary = struct();
summary.hdf5_path = hdf5Path;
summary.snapshot_count = nSnapshots;
summary.delay_count = nDelays;
summary.delay_min_samples = min(delaySamples);
summary.delay_max_samples = max(delaySamples);
summary.time_monotonic_nondecreasing = all(diff(timeS) >= 0);
summary.raw_iq_rms_all_positive = all(rawIqRms > 0);
summary.cir_all_finite = true;
summary.pdp_window_count = nWindows;
summary.snapshots_per_pdp_window = 40;
summary.pdp_mean_exactly_recomputed = pdpMeanExactlyRecomputed;
summary.pdp_recomputation_absolute_tolerance = pdpAbsoluteTolerance;
summary.pdp_recomputation_relative_tolerance = pdpRelativeTolerance;
summary.max_pdp_recomputation_difference = ...
    maxPdpRecomputationDifference;
summary.unique_snapshot_start_samples = ...
    1 + sum(diff(sampleStarts) > 0);

fprintf('HDF5_CIR_VALIDATION=PASS\n');
fprintf('HDF5_CIR_SHAPE=%dx%d PDP_SHAPE=%dx%d\n', ...
    nSnapshots, nDelays, nWindows, nDelays);
fprintf(['HDF5_TIME_NONDECREASING=YES RMS_POSITIVE=YES ' ...
    'CIR_FINITE=YES PDP_EXACT_RECOMPUTATION=%d MAX_PDP_DIFF=%.17g\n'], ...
    pdpMeanExactlyRecomputed, maxPdpRecomputationDifference);
end

function dimensions = datasetDimensions(info, datasetName)
names = {info.Datasets.Name};
index = find(strcmp(names, datasetName), 1);
assert(~isempty(index), 'GNSS:SAGE:CIRValidationSchemaMismatch', ...
    'Required HDF5 dataset is missing: %s.', datasetName);
dimensions = double(info.Datasets(index).Dataspace.Size(:).');
end

function assertVectorDimensions(info, datasetName, expectedCount)
dimensions = datasetDimensions(info, datasetName);
assert(numel(dimensions) == 2 && dimensions(1) == expectedCount ...
    && dimensions(2) == 1, ...
    'GNSS:SAGE:CIRValidationDimensionsMismatch', ...
    'HDF5 vector %s has an inconsistent shape.', datasetName);
end

function values = readHdf5Dataset(filename, datasetName, varargin)
try
    values = h5read(filename, datasetName, varargin{:});
catch exception
    error('GNSS:SAGE:CIRValidationReadFailed', ...
        'Could not read HDF5 dataset %s: %s', ...
        datasetName, exception.message);
end
end
