function summary = run_mainline_wp5_alpha_full_batch(projectRoot, outputRoot)
%RUN_MAINLINE_WP5_ALPHA_FULL_BATCH Serially export alpha for a frozen manifest.
% Every run is written once into a new namespace; failures and earlier outputs
% are retained. Stage2 inputs are re-hashed immediately before each export.

projectRoot = char(string(projectRoot));
outputRoot = char(string(outputRoot));
manifestPath = fullfile(outputRoot, 'input_manifest.csv');
preflightPath = fullfile(outputRoot, 'source_preflight.json');
assert(isfolder(projectRoot) && isfolder(outputRoot) ...
    && isfile(manifestPath) && isfile(preflightPath), ...
    'GNSS:WP5:BatchInputMissing', ...
    'Project root, output root, manifest and preflight summary are required.');

manifestSha = sha256File(manifestPath);
preflight = jsondecode(fileread(preflightPath));
assert(isstruct(preflight) && isfield(preflight, 'input_manifest_sha256') ...
    && strcmpi(char(preflight.input_manifest_sha256), manifestSha), ...
    'GNSS:WP5:ManifestShaMismatch', ...
    'Input manifest differs from the completed source preflight.');
assert(any(strcmp(char(preflight.status), ...
    {'PREFLIGHT_PASS', 'PREFLIGHT_PARTIAL'})), ...
    'GNSS:WP5:PreflightStatusInvalid', ...
    'Source preflight is not in a recognized terminal state.');

manifest = readtable(manifestPath, 'Delimiter', ',', 'TextType', 'string');
required = {'run_id', 'scene_id', 'prn', 'tracking_channel', ...
    'sample_rate_hz', 'frozen_sage_sha256', 'stage2_mat_path', ...
    'stage2_mat_sha256', 'stage2_selected_paths_csv_path', ...
    'stage2_selected_paths_csv_sha256', 'stage3_persistence_csv_path', ...
    'stage3_persistence_csv_sha256', 'stage3_reliable_centers_csv_path', ...
    'stage3_reliable_centers_csv_sha256', 'stage4_joint_summary_csv_path', ...
    'stage4_joint_summary_csv_sha256', 'stage4_joint_paths_csv_path', ...
    'stage4_joint_paths_csv_sha256', 'stage2_path_rows', ...
    'stage2_window_count', 'stage2_mpc_count', 'stage2_direct_count', ...
    'preflight_status', 'preflight_reason'};
assert(all(ismember(required, manifest.Properties.VariableNames)), ...
    'GNSS:WP5:ManifestSchemaInvalid', ...
    'Input manifest is missing required source or identity fields.');
assert(height(manifest) == double(preflight.run_count) ...
    && numel(unique(manifest.run_id)) == height(manifest) ...
    && sum(manifest.preflight_status == "READY") == ...
        double(preflight.ready_run_count) ...
    && sum(manifest.preflight_status ~= "READY") == ...
        double(preflight.rejected_run_count), ...
    'GNSS:WP5:ManifestCountsInvalid', ...
    'Manifest run identities or preflight counts are inconsistent.');

alphaCombinedPath = fullfile(outputRoot, 'stage2_alpha_all_paths.csv');
ledgerCombinedPath = fullfile(outputRoot, ...
    'stage2_modeling_ledger_all_paths.csv');
auditPath = fullfile(outputRoot, 'run_export_audit.csv');
summaryPath = fullfile(outputRoot, 'batch_export_summary.json');
assert(~isfile(alphaCombinedPath) && ~isfile(ledgerCombinedPath) ...
    && ~isfile(auditPath) && ~isfile(summaryPath), ...
    'GNSS:WP5:BatchOutputCollision', ...
    'Batch output already exists; refusing to resume or overwrite it.');
for k = 1:height(manifest)
    assert(~isfolder(fullfile(outputRoot, char(manifest.run_id(k)))), ...
        'GNSS:WP5:RunOutputCollision', ...
        'Run output already exists; refusing to overwrite it: %s', ...
        manifest.run_id(k));
end

sagePath = fullfile(projectRoot, 'scripts', 'sage_pipeline', ...
    'run_nav_sage_pipeline.m');
assert(isfile(sagePath), 'GNSS:WP5:FrozenSageSourceMissing', ...
    'Frozen SAGE source is missing.');
sageSha = sha256File(sagePath);
expectedSageSha = unique(lower(string(manifest.frozen_sage_sha256)));
assert(numel(expectedSageSha) == 1 && expectedSageSha == sageSha, ...
    'GNSS:WP5:FrozenSageSourceMismatch', ...
    'Current frozen SAGE source SHA differs from the cohort pin.');

audit = struct('run_id', {}, 'status', {}, 'preflight_reason', {}, ...
    'error_identifier', {}, 'error_message', {}, 'started_utc', {}, ...
    'finished_utc', {}, 'elapsed_seconds', {}, 'stage2_path_rows', {}, ...
    'stage2_window_count', {}, 'stage2_mpc_count', {}, ...
    'stage2_direct_count', {}, 'alpha_available_count', {}, ...
    'alpha_missing_count', {}, 'relative_power_pass_count', {}, ...
    'relative_power_mismatch_count', {}, 'alpha_output_path', {}, ...
    'modeling_ledger_path', {});
systemStop = false;
repeatErrorId = "";
repeatErrorCount = 0;

for k = 1:height(manifest)
    row = manifest(k, :);
    runId = char(row.run_id);
    startedUtc = utcNow();
    clockStart = tic;
    entry = auditTemplate(runId, startedUtc);
    entry.preflight_reason = char(row.preflight_reason);
    if row.preflight_status ~= "READY"
        entry.status = 'REJECTED_PREFLIGHT';
        entry.finished_utc = utcNow();
        entry.elapsed_seconds = toc(clockStart);
        audit(end + 1) = entry; %#ok<AGROW>
        writeAudit(auditPath, audit);
        continue;
    end

    [inputsOkay, inputFailure] = verifyRunInputs(projectRoot, row, sageSha);
    if ~inputsOkay
        entry.status = 'REJECTED_INPUT_CHANGED';
        entry.error_identifier = 'GNSS:WP5:RunInputPinMismatch';
        entry.error_message = inputFailure;
        entry.finished_utc = utcNow();
        entry.elapsed_seconds = toc(clockStart);
        audit(end + 1) = entry; %#ok<AGROW>
        writeAudit(auditPath, audit);
        continue;
    end

    runOutput = fullfile(outputRoot, runId);
    assert(~isfolder(runOutput) && ~isfile(runOutput), ...
        'GNSS:WP5:RunOutputCollision', ...
        'Run output appeared after the initial collision check: %s', runId);
    [made, message] = mkdir(runOutput);
    assert(made, 'GNSS:WP5:RunOutputCreateFailed', ...
        'Could not create run output directory: %s', message);
    alphaPath = fullfile(runOutput, 'stage2_alpha.csv');
    ledgerPath = fullfile(runOutput, 'stage2_modeling_ledger.csv');
    provenance = struct('run_id', runId, 'scene_id', char(row.scene_id), ...
        'prn', char(row.prn), ...
        'tracking_channel', double(row.tracking_channel), ...
        'sample_rate_hz', double(row.sample_rate_hz), ...
        'frozen_sage_sha256', char(row.frozen_sage_sha256), ...
        'stage2_mat_sha256', char(row.stage2_mat_sha256), ...
        'selected_paths_csv_sha256', ...
            char(row.stage2_selected_paths_csv_sha256));
    try
        alpha = export_stage2_complex_alpha( ...
            char(row.stage2_mat_path), ...
            char(row.stage2_selected_paths_csv_path), alphaPath, provenance);
        ledgerResult = build_mpc_modeling_ledger( ...
            char(row.stage2_selected_paths_csv_path), ...
            char(row.stage3_persistence_csv_path), ...
            char(row.stage3_reliable_centers_csv_path), ...
            char(row.stage4_joint_summary_csv_path), ...
            char(row.stage4_joint_paths_csv_path), alphaPath, ledgerPath, ...
            provenance);
        assert(height(alpha) == double(row.stage2_path_rows) ...
            && ledgerResult.ledger_stage2_selected_path_rows == ...
                double(row.stage2_path_rows), ...
            'GNSS:WP5:RunRowConservationFailed', ...
            'Exporter or integrated ledger did not conserve Stage2 path rows.');
        entry.status = 'EXPORTED';
        entry.stage2_path_rows = height(alpha);
        entry.stage2_window_count = double(row.stage2_window_count);
        entry.stage2_mpc_count = sum(double(alpha.is_multipath) == 1);
        entry.stage2_direct_count = sum(double(alpha.is_multipath) == 0);
        entry.alpha_available_count = sum(alpha.alpha_status == "AVAILABLE");
        entry.alpha_missing_count = sum(alpha.alpha_status == "MISSING");
        entry.relative_power_pass_count = ...
            sum(alpha.relative_power_check_status == "PASS");
        entry.relative_power_mismatch_count = ...
            sum(alpha.relative_power_check_status == "MISMATCH");
        entry.alpha_output_path = alphaPath;
        entry.modeling_ledger_path = ledgerPath;
    catch exception
        entry.error_identifier = exception.identifier;
        entry.error_message = exception.message;
        entry.finished_utc = utcNow();
        entry.elapsed_seconds = toc(clockStart);
        if isPerRunDataError(exception.identifier)
            entry.status = 'FAILED_RUN_DATA';
            if string(exception.identifier) == repeatErrorId
                repeatErrorCount = repeatErrorCount + 1;
            else
                repeatErrorId = string(exception.identifier);
                repeatErrorCount = 1;
            end
            if repeatErrorCount >= 2
                systemStop = true;
            end
        else
            entry.status = 'STOPPED_SYSTEM_ERROR';
            systemStop = true;
        end
        audit(end + 1) = entry; %#ok<AGROW>
        writeAudit(auditPath, audit);
        if systemStop, break; end
        continue;
    end
    entry.finished_utc = utcNow();
    entry.elapsed_seconds = toc(clockStart);
    audit(end + 1) = entry; %#ok<AGROW>
    writeAudit(auditPath, audit);
end

exported = audit(strcmp({audit.status}, 'EXPORTED'));
alphaParts = cell(numel(exported), 1);
ledgerParts = cell(numel(exported), 1);
for k = 1:numel(exported)
    alphaParts{k} = readtable(exported(k).alpha_output_path, ...
        'Delimiter', ',', 'TextType', 'string');
    ledgerParts{k} = readtable(exported(k).modeling_ledger_path, ...
        'Delimiter', ',', 'TextType', 'string');
end
if ~isempty(alphaParts)
    alphaAll = vertcat(alphaParts{:});
    ledgerAll = vertcat(ledgerParts{:});
    writeTableNew(alphaAll, alphaCombinedPath);
    writeTableNew(ledgerAll, ledgerCombinedPath);
    totalPaths = height(alphaAll);
    totalMpc = sum(double(alphaAll.is_multipath) == 1);
    totalDirect = sum(double(alphaAll.is_multipath) == 0);
    totalWindows = numel(unique(string(alphaAll.run_id) + ":" + ...
        string(alphaAll.window_id)));
else
    totalPaths = 0;
    totalMpc = 0;
    totalDirect = 0;
    totalWindows = 0;
end

exportedCount = numel(exported);
failedCount = sum(contains(string({audit.status}), 'FAILED'));
rejectedCount = sum(contains(string({audit.status}), 'REJECTED'));
if exportedCount == height(manifest) && ~systemStop
    status = "COMPLETE";
elseif systemStop
    status = "STOPPED_SYSTEM_ERROR";
else
    status = "PARTIAL";
end
summary = struct('status', status, 'created_utc', utcNow(), ...
    'project_root', projectRoot, 'output_root', outputRoot, ...
    'input_manifest_sha256', manifestSha, ...
    'source_preflight_status', char(preflight.status), ...
    'run_count', height(manifest), 'exported_run_count', exportedCount, ...
    'failed_run_count', failedCount, 'rejected_run_count', rejectedCount, ...
    'stage2_path_count', totalPaths, 'stage2_window_count', totalWindows, ...
    'stage2_mpc_count', totalMpc, 'stage2_direct_count', totalDirect, ...
    'alpha_available_count', sum([audit.alpha_available_count]), ...
    'alpha_missing_count', sum([audit.alpha_missing_count]), ...
    'relative_power_mismatch_count', ...
        sum([audit.relative_power_mismatch_count]), ...
    'alpha_combined_path', pathOrEmpty(alphaCombinedPath, ~isempty(alphaParts)), ...
    'ledger_combined_path', pathOrEmpty(ledgerCombinedPath, ~isempty(alphaParts)), ...
    'run_audit_path', auditPath);
writeJsonReplace(summaryPath, summary);
end

function entry = auditTemplate(runId, startedUtc)
entry = struct('run_id', runId, 'status', '', 'preflight_reason', '', ...
    'error_identifier', '', 'error_message', '', 'started_utc', startedUtc, ...
    'finished_utc', '', 'elapsed_seconds', NaN, 'stage2_path_rows', 0, ...
    'stage2_window_count', 0, 'stage2_mpc_count', 0, ...
    'stage2_direct_count', 0, 'alpha_available_count', 0, ...
    'alpha_missing_count', 0, 'relative_power_pass_count', 0, ...
    'relative_power_mismatch_count', 0, 'alpha_output_path', '', ...
    'modeling_ledger_path', '');
end

function [okay, reason] = verifyRunInputs(projectRoot, row, sageSha)
okay = false;
reason = '';
paths = {char(row.stage2_mat_path), ...
    char(row.stage2_selected_paths_csv_path), ...
    char(row.stage3_persistence_csv_path), ...
    char(row.stage3_reliable_centers_csv_path), ...
    char(row.stage4_joint_summary_csv_path), ...
    char(row.stage4_joint_paths_csv_path)};
hashes = {char(row.stage2_mat_sha256), ...
    char(row.stage2_selected_paths_csv_sha256), ...
    char(row.stage3_persistence_csv_sha256), ...
    char(row.stage3_reliable_centers_csv_sha256), ...
    char(row.stage4_joint_summary_csv_sha256), ...
    char(row.stage4_joint_paths_csv_sha256)};
for k = 1:numel(paths)
    if ~isfile(paths{k})
        reason = sprintf('Input disappeared: %s', paths{k});
        return;
    end
    if ~strcmpi(sha256File(paths{k}), hashes{k})
        reason = sprintf('Input SHA changed: %s', paths{k});
        return;
    end
end
sagePath = fullfile(projectRoot, 'scripts', 'sage_pipeline', ...
    'run_nav_sage_pipeline.m');
if ~isfile(sagePath) || ~strcmpi(sha256File(sagePath), sageSha) ...
        || ~strcmpi(char(row.frozen_sage_sha256), sageSha)
    reason = 'Frozen SAGE source changed or no longer matches cohort pin.';
    return;
end
okay = true;
end

function yes = isPerRunDataError(identifier)
allowed = {'GNSS:SAGE:Stage2FitsMissing', ...
    'GNSS:SAGE:SelectedPathSchemaMismatch', ...
    'GNSS:SAGE:SelectedPathTableEmpty', ...
    'GNSS:SAGE:SelectedPathIdentityInvalid', ...
    'GNSS:SAGE:DuplicateSelectedPathIdentity', ...
    'GNSS:SAGE:SelectedPathSequenceInvalid', ...
    'GNSS:SAGE:Stage2FitWindowMissing', ...
    'GNSS:SAGE:SelectedModelMissing'};
yes = any(strcmp(identifier, allowed));
end

function writeAudit(path, audit)
tableValue = table(string({audit.run_id}).', string({audit.status}).', ...
    string({audit.preflight_reason}).', ...
    string({audit.error_identifier}).', string({audit.error_message}).', ...
    string({audit.started_utc}).', string({audit.finished_utc}).', ...
    [audit.elapsed_seconds].', [audit.stage2_path_rows].', ...
    [audit.stage2_window_count].', [audit.stage2_mpc_count].', ...
    [audit.stage2_direct_count].', [audit.alpha_available_count].', ...
    [audit.alpha_missing_count].', [audit.relative_power_pass_count].', ...
    [audit.relative_power_mismatch_count].', ...
    string({audit.alpha_output_path}).', ...
    string({audit.modeling_ledger_path}).', ...
    'VariableNames', {'run_id', 'status', 'preflight_reason', ...
    'error_identifier', 'error_message', 'started_utc', 'finished_utc', ...
    'elapsed_seconds', 'stage2_path_rows', 'stage2_window_count', ...
    'stage2_mpc_count', 'stage2_direct_count', 'alpha_available_count', ...
    'alpha_missing_count', 'relative_power_pass_count', ...
    'relative_power_mismatch_count', 'alpha_output_path', ...
    'modeling_ledger_path'});
temporary = [tempname(fileparts(path)), '.csv'];
cleanup = onCleanup(@() deleteIfPresent(temporary)); %#ok<NASGU>
writetable(tableValue, temporary);
if isfile(path)
    [okay, message] = movefile(temporary, path, 'f');
else
    [okay, message] = movefile(temporary, path);
end
assert(okay, 'GNSS:WP5:AuditWriteFailed', ...
    'Could not update run audit: %s', message);
end

function writeTableNew(tableValue, path)
assert(~isfile(path), 'GNSS:WP5:BatchOutputCollision', ...
    'Refusing to overwrite combined output: %s', path);
temporary = [tempname(fileparts(path)), '.csv'];
cleanup = onCleanup(@() deleteIfPresent(temporary)); %#ok<NASGU>
writetable(tableValue, temporary);
[okay, message] = movefile(temporary, path);
assert(okay, 'GNSS:WP5:CombinedPublishFailed', ...
    'Could not publish combined table: %s', message);
end

function writeJsonReplace(path, value)
temporary = [tempname(fileparts(path)), '.json'];
cleanup = onCleanup(@() deleteIfPresent(temporary)); %#ok<NASGU>
fid = fopen(temporary, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'GNSS:WP5:SummaryWriteFailed', ...
    'Could not create batch summary temporary file.');
fwrite(fid, jsonencode(value, 'PrettyPrint', true), 'char');
fwrite(fid, newline, 'char');
fclose(fid);
[okay, message] = movefile(temporary, path, 'f');
assert(okay, 'GNSS:WP5:SummaryPublishFailed', ...
    'Could not publish batch summary: %s', message);
end

function sha = sha256File(path)
fid = fopen(path, 'rb');
assert(fid >= 0, 'GNSS:WP5:HashReadFailed', ...
    'Could not open file for SHA-256: %s', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
digest = java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes = fread(fid, 1024 * 1024, '*uint8');
    if isempty(bytes), break; end
    digest.update(typecast(bytes(:), 'int8'));
end
raw = typecast(digest.digest(), 'uint8');
sha = lower(reshape(dec2hex(raw, 2).', 1, []));
end

function text = utcNow()
text = char(datetime('now', 'TimeZone', 'UTC', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end

function value = pathOrEmpty(path, present)
if present, value = path; else, value = ''; end
end

function deleteIfPresent(path)
if isfile(path), delete(path); end
end
