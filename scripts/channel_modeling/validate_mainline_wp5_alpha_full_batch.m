function report = validate_mainline_wp5_alpha_full_batch( ...
    projectRoot, outputRoot, task6LedgerPath, expectedLedgerSha256)
%VALIDATE_MAINLINE_WP5_ALPHA_FULL_BATCH Independently audit alpha exports.
% Reconstructs coefficients directly from stage2Fits; it does not call the
% exporter. It verifies Stage2 row conservation and the frozen Task6 ledger.

projectRoot = char(string(projectRoot));
outputRoot = char(string(outputRoot));
task6LedgerPath = char(string(task6LedgerPath));
if nargin < 4, expectedLedgerSha256 = ''; end
manifestPath = fullfile(outputRoot, 'input_manifest.csv');
preflightPath = fullfile(outputRoot, 'source_preflight.json');
batchSummaryPath = fullfile(outputRoot, 'batch_export_summary.json');
runAuditPath = fullfile(outputRoot, 'run_export_audit.csv');
alphaCombinedPath = fullfile(outputRoot, 'stage2_alpha_all_paths.csv');
ledgerCombinedPath = fullfile(outputRoot, ...
    'stage2_modeling_ledger_all_paths.csv');
assert(isfile(manifestPath) && isfile(preflightPath) ...
    && isfile(batchSummaryPath) && isfile(runAuditPath) ...
    && isfile(alphaCombinedPath) && isfile(ledgerCombinedPath) ...
    && isfile(task6LedgerPath), ...
    'GNSS:WP5:ValidationInputMissing', ...
    'A required batch, combined or frozen-ledger input is missing.');
manifestSha = sha256File(manifestPath);
preflight = jsondecode(fileread(preflightPath));
batch = jsondecode(fileread(batchSummaryPath));
assert(strcmpi(char(preflight.input_manifest_sha256), manifestSha) ...
    && strcmpi(char(batch.input_manifest_sha256), manifestSha), ...
    'GNSS:WP5:ValidationManifestShaMismatch', ...
    'Batch or preflight evidence is not bound to the current manifest.');
ledgerSha = sha256File(task6LedgerPath);
if ~isempty(expectedLedgerSha256)
    assert(strcmpi(ledgerSha, char(expectedLedgerSha256)), ...
        'GNSS:WP5:ValidationTask6LedgerShaMismatch', ...
        'Frozen Task6 ledger differs from the expected SHA pin.');
end

manifest = readtable(manifestPath, 'Delimiter', ',', 'TextType', 'string');
runAudit = readtable(runAuditPath, 'Delimiter', ',', 'TextType', 'string');
frozenLedger = readtable(task6LedgerPath, 'Delimiter', ',', 'TextType', 'string');
alphaCombined = readtable(alphaCombinedPath, 'Delimiter', ',', 'TextType', 'string');
ledgerCombined = readtable(ledgerCombinedPath, 'Delimiter', ',', 'TextType', 'string');
assert(height(manifest) == double(preflight.run_count) ...
    && height(runAudit) == height(manifest), ...
    'GNSS:WP5:ValidationRunCountMismatch', ...
    'Manifest, preflight and run audit counts disagree.');

sourceFields = {'window_id', 'path_id', 'selected_L', 'is_multipath', ...
    'recording_time_s', 'delay_samples', 'excess_delay_samples', ...
    'excess_delay_chips', 'excess_path_length_m', 'doppler_hz', ...
    'doppler_offset_hz', 'relative_power_db'};
ledgerFields = {'run_id', 'scene_id', 'prn', 'tracking_channel', ...
    'window_id', 'path_id', 'selected_L', 'is_multipath', ...
    'recording_time_s', 'delay_samples', 'excess_delay_samples', ...
    'excess_delay_chips', 'excess_path_length_m', 'doppler_hz', ...
    'doppler_offset_hz', 'relative_power_db'};
alphaFields = {'run_id','window_id','path_id','alpha_real','alpha_imag', ...
    'alpha_magnitude','alpha_phase_rad','alpha_status', ...
    'alpha_missing_reason','relative_power_check_status', ...
    'stage2_mat_sha256','selected_paths_csv_sha256', ...
    'SAGE_ALPHA_IS_FROM_WINDOW_NORMALIZED_IQ'};
assert(all(ismember(sourceFields, alphaCombined.Properties.VariableNames)) ...
    && all(ismember(ledgerFields, frozenLedger.Properties.VariableNames)) ...
    && all(ismember(alphaFields, alphaCombined.Properties.VariableNames)), ...
    'GNSS:WP5:ValidationSchemaMismatch', ...
    'Combined alpha or frozen ledger schema is incomplete.');

runResult = struct('run_id', {}, 'status', {}, 'path_count', {}, ...
    'window_count', {}, 'mpc_count', {}, 'direct_count', {}, ...
    'alpha_available_count', {}, 'alpha_missing_count', {}, ...
    'alpha_nonfinite_count', {}, 'power_pass_count', {}, ...
    'power_mismatch_count', {}, 'identity_error_count', {}, ...
    'numeric_error_count', {}, 'source_sha_error_count', {}, ...
    'max_stage2_attribute_abs_diff', {}, 'max_alpha_component_abs_diff', {}, ...
    'errors', {});
expectedAlphaKeys = strings(0, 1);
expectedLedgerKeys = strings(0, 1);
maxStage2Diff = 0;
maxAlphaDiff = 0;
combinedOffset = 0;

for r = 1:height(manifest)
    row = manifest(r, :);
    runId = char(row.run_id);
    item = runResultTemplate(runId);
    try
        auditRow = find(runAudit.run_id == string(runId));
        assert(numel(auditRow) == 1 && runAudit.status(auditRow) == "EXPORTED", ...
            'Run audit lacks exactly one EXPORTED record.');
        runFolder = fullfile(outputRoot, runId);
        alphaPath = fullfile(runFolder, 'stage2_alpha.csv');
        integratedPath = fullfile(runFolder, 'stage2_modeling_ledger.csv');
        sourceMat = char(row.stage2_mat_path);
        sourceCsv = char(row.stage2_selected_paths_csv_path);
        sourcePaths = {sourceMat, sourceCsv, ...
            char(row.stage3_persistence_csv_path), ...
            char(row.stage3_reliable_centers_csv_path), ...
            char(row.stage4_joint_summary_csv_path), ...
            char(row.stage4_joint_paths_csv_path)};
        sourceShas = {char(row.stage2_mat_sha256), ...
            char(row.stage2_selected_paths_csv_sha256), ...
            char(row.stage3_persistence_csv_sha256), ...
            char(row.stage3_reliable_centers_csv_sha256), ...
            char(row.stage4_joint_summary_csv_sha256), ...
            char(row.stage4_joint_paths_csv_sha256)};
        for p = 1:numel(sourcePaths)
            assert(isfile(sourcePaths{p}) ...
                && strcmpi(sha256File(sourcePaths{p}), sourceShas{p}), ...
                'A source file is absent or its SHA differs from manifest.');
        end
        source = readtable(sourceCsv, 'Delimiter', ',', 'TextType', 'string');
        alpha = readtable(alphaPath, 'Delimiter', ',', 'TextType', 'string');
        integrated = readtable(integratedPath, 'Delimiter', ',', 'TextType', 'string');
        assert(all(ismember(sourceFields, source.Properties.VariableNames)), ...
            'Stage2 source CSV lacks comparison fields.');
        assert(height(source) == height(alpha) ...
            && height(source) == height(integrated) ...
            && height(source) == double(row.stage2_path_rows), ...
            'Source, alpha and integrated-ledger row counts differ.');

        sourceKey = makeKeys(repmat(string(runId), height(source), 1), ...
            source.window_id, source.path_id);
        alphaKey = makeKeys(alpha.run_id, alpha.window_id, alpha.path_id);
        integratedKey = makeKeys(integrated.run_id, ...
            integrated.window_id, integrated.path_id);
        assert(numel(unique(sourceKey)) == numel(sourceKey) ...
            && isequal(sourceKey, alphaKey) ...
            && isequal(sourceKey, integratedKey), ...
            'Duplicate, missing, extra, reordered or cross-run path identity.');
        combinedRows = combinedOffset + (1:height(source));
        assert(isequal(combinedAlphaKeysFor(alphaCombined, combinedRows), alphaKey) ...
            && isequal(combinedAlphaKeysFor(ledgerCombined, combinedRows), integratedKey), ...
            'Combined path tables do not preserve per-run identity order.');
        assert_wp5_ledger_rows_equal(integrated, ledgerCombined, ...
            combinedRows, sprintf('run %s', runId));
        for fieldIndex = 1:numel(sourceFields)
            field = sourceFields{fieldIndex};
            sourceValues = double(source.(field));
            integratedValues = double(integrated.(field));
            alphaColumn = alphaCombined.(field);
            ledgerColumn = ledgerCombined.(field);
            combinedAlphaValues = double(alphaColumn(combinedRows));
            combinedLedgerValues = double(ledgerColumn(combinedRows));
            assert(all(abs(sourceValues(:) - integratedValues(:)) <= 1e-12) ...
                && all(abs(sourceValues(:) - combinedAlphaValues(:)) <= 1e-12) ...
                && all(abs(sourceValues(:) - combinedLedgerValues(:)) <= 1e-12), ...
                sprintf('Integrated or combined Stage2 field %s differs from source.', field));
        end
        for fieldName = {'alpha_real','alpha_imag','alpha_magnitude','alpha_phase_rad'}
            field = fieldName{1};
            perRunValues = double(alpha.(field));
            integratedValues = double(integrated.(field));
            alphaColumn = alphaCombined.(field);
            ledgerColumn = ledgerCombined.(field);
            combinedValues = double(alphaColumn(combinedRows));
            combinedLedgerValues = double(ledgerColumn(combinedRows));
            assert(all((isnan(perRunValues) & isnan(integratedValues)) ...
                | abs(perRunValues - integratedValues) <= 1e-12) ...
                && all((isnan(perRunValues) & isnan(combinedValues)) ...
                | abs(perRunValues - combinedValues) <= 1e-12) ...
                && all((isnan(perRunValues) & isnan(combinedLedgerValues)) ...
                | abs(perRunValues - combinedLedgerValues) <= 1e-12), ...
                sprintf('Integrated/combined %s differs from per-run alpha.', field));
        end
        for fieldName = {'alpha_status','alpha_missing_reason', ...
                'relative_power_check_status'}
            field = fieldName{1};
            alphaColumn = alphaCombined.(field);
            ledgerColumn = ledgerCombined.(field);
            assert(isequal(string(alpha.(field)), string(integrated.(field))) ...
                && isequal(string(alpha.(field)), string(alphaColumn(combinedRows))) ...
                && isequal(string(alpha.(field)), string(ledgerColumn(combinedRows))), ...
                sprintf('Integrated/combined %s differs from per-run alpha.', field));
        end
        combinedOffset = combinedOffset + height(source);
        item.path_count = height(source);
        item.window_count = numel(unique(double(source.window_id)));
        item.mpc_count = sum(double(source.is_multipath) == 1);
        item.direct_count = sum(double(source.is_multipath) == 0);
        item.identity_error_count = 0;
        expectedAlphaKeys = [expectedAlphaKeys; alphaKey]; %#ok<AGROW>
        expectedLedgerKeys = [expectedLedgerKeys; integratedKey]; %#ok<AGROW>

        frozenRows = mapFrozenRows(frozenLedger, runId, ...
            source.window_id, source.path_id);
        for f = 1:numel(sourceFields)
            field = sourceFields{f};
            left = double(source.(field));
            right = double(alpha.(field));
            diffValue = max([0; abs(left(:) - right(:))]);
            item.max_stage2_attribute_abs_diff = max( ...
                item.max_stage2_attribute_abs_diff, diffValue);
            maxStage2Diff = max(maxStage2Diff, diffValue);
            assert(all((isnan(left(:)) & isnan(right(:))) ...
                | abs(left(:) - right(:)) <= 1e-12), ...
                sprintf('Stage2 source attribute %s changed in export.', field));
            frozenColumn = frozenLedger.(field);
            frozenValues = double(frozenColumn(frozenRows));
            assert(all(abs(left(:) - frozenValues(:)) <= 1e-12), ...
                sprintf('Stage2 attribute %s differs from frozen Task6 ledger.', field));
        end
        assert(all(string(frozenLedger.scene_id(frozenRows)) == string(row.scene_id)) ...
            && all(normalizePrn(frozenLedger.prn(frozenRows)) == normalizePrn(row.prn)) ...
            && all(double(frozenLedger.tracking_channel(frozenRows)) == ...
                double(row.tracking_channel)), ...
            'Frozen Task6 ledger run metadata differs from manifest.');
        assert(all(lower(string(frozenLedger.source_stage2_csv_sha256(frozenRows))) ...
                == lower(string(row.stage2_selected_paths_csv_sha256))) ...
            && all(double(frozenLedger.stage2_source_row_number(frozenRows)) ...
                == (2:height(source)+1).'), ...
            'Frozen Task6 source CSV SHA or row-order provenance differs.');

        fits = load(sourceMat, 'stage2Fits');
        assert(isfield(fits, 'stage2Fits') && iscell(fits.stage2Fits), ...
            'Stage2 MAT lacks stage2Fits cell array.');
        expectedAlpha = complex(nan(height(source), 1), nan(height(source), 1));
        expectedStatus = repmat("MISSING", height(source), 1);
        expectedReason = strings(height(source), 1);
        for q = 1:height(source)
            [available, value, reason] = deriveAlphaIndependently( ...
                fits.stage2Fits, double(source.window_id(q)), ...
                double(source.selected_L(q)), double(source.path_id(q)));
            expectedReason(q) = reason;
            if available
                expectedAlpha(q) = value;
                expectedStatus(q) = "AVAILABLE";
            end
        end
        item.alpha_available_count = sum(expectedStatus == "AVAILABLE");
        item.alpha_missing_count = sum(expectedStatus == "MISSING");
        observedStatus = string(alpha.alpha_status);
        observedReason = string(alpha.alpha_missing_reason);
        assert(isequal(observedStatus, expectedStatus) ...
            && isequal(observedReason, expectedReason), ...
            'Alpha availability or missing reason differs from source MAT.');
        observedAlpha = complex(double(alpha.alpha_real), double(alpha.alpha_imag));
        availableRows = expectedStatus == "AVAILABLE";
        missingRows = ~availableRows;
        item.alpha_nonfinite_count = sum(~isfinite(real(observedAlpha(availableRows))) ...
            | ~isfinite(imag(observedAlpha(availableRows))));
        assert(~any(missingRows & (isfinite(real(observedAlpha)) ...
            | isfinite(imag(observedAlpha)))) ...
            && item.alpha_nonfinite_count == 0, ...
            'Missing alpha must remain NaN; available alpha must be finite.');
        componentDiff = [abs(real(observedAlpha(availableRows)) ...
            - real(expectedAlpha(availableRows))); ...
            abs(imag(observedAlpha(availableRows)) ...
            - imag(expectedAlpha(availableRows)))];
        if ~isempty(componentDiff)
            item.max_alpha_component_abs_diff = max(componentDiff);
            maxAlphaDiff = max(maxAlphaDiff, item.max_alpha_component_abs_diff);
        end
        assert(all(componentDiff <= 1e-12), ...
            'Exported alpha differs from independent MAT reconstruction.');
        magnitudeDiff = abs(double(alpha.alpha_magnitude(availableRows)) ...
            - abs(expectedAlpha(availableRows)));
        phaseDiff = abs(angle(exp(1i * (double(alpha.alpha_phase_rad(availableRows)) ...
            - angle(expectedAlpha(availableRows))))));
        assert(all(magnitudeDiff <= 1e-12) && all(phaseDiff <= 1e-12) ...
            && all(string(alpha.SAGE_ALPHA_IS_FROM_WINDOW_NORMALIZED_IQ) == "YES"), ...
            'Magnitude, phase or normalized-IQ provenance is inconsistent.');
        expectedPowerStatus = independentPowerStatus( ...
            source, expectedAlpha, expectedStatus);
        observedPowerStatus = string(alpha.relative_power_check_status);
        assert(isequal(observedPowerStatus, expectedPowerStatus), ...
            'Relative-power status differs from independent recomputation.');
        item.power_pass_count = sum(observedPowerStatus == "PASS");
        item.power_mismatch_count = sum(observedPowerStatus == "MISMATCH");
        assert(all(string(alpha.run_id) == string(runId)) ...
            && all(string(alpha.scene_id) == string(row.scene_id)) ...
            && all(normalizePrn(alpha.prn) == normalizePrn(row.prn)) ...
            && all(double(alpha.tracking_channel) == double(row.tracking_channel)) ...
            && all(lower(string(alpha.frozen_sage_sha256)) == ...
                lower(string(row.frozen_sage_sha256))) ...
            && all(lower(string(alpha.stage2_mat_sha256)) == ...
                lower(string(row.stage2_mat_sha256))) ...
            && all(lower(string(alpha.selected_paths_csv_sha256)) == ...
                lower(string(row.stage2_selected_paths_csv_sha256))), ...
            'Exported run or source provenance differs from manifest.');
        item.source_sha_error_count = 0;
        item.status = 'PASS';
    catch exception
        item.status = 'FAIL';
        errorLocation = strings(numel(exception.stack), 1);
        for stackIndex = 1:numel(exception.stack)
            errorLocation(stackIndex) = sprintf('%s:%d', ...
                exception.stack(stackIndex).name, ...
                exception.stack(stackIndex).line);
        end
        item.errors = sprintf('%s: %s%s', exception.identifier, ...
            exception.message, [' [' char(strjoin(errorLocation, ' <- ')) ']']);
        if contains(exception.message, 'identity') || contains(exception.message, 'path')
            item.identity_error_count = max(1, item.identity_error_count);
        elseif contains(exception.message, 'alpha') || contains(exception.message, 'power')
            item.numeric_error_count = max(1, item.numeric_error_count);
        else
            item.source_sha_error_count = max(1, item.source_sha_error_count);
        end
    end
    runResult(end + 1) = item; %#ok<AGROW>
end

combinedAlphaKeys = makeKeys(alphaCombined.run_id, ...
    alphaCombined.window_id, alphaCombined.path_id);
combinedLedgerKeys = makeKeys(ledgerCombined.run_id, ...
    ledgerCombined.window_id, ledgerCombined.path_id);
frozenKeys = makeKeys(frozenLedger.run_id, frozenLedger.window_id, ...
    frozenLedger.path_id);
globalIdentityErrors = 0;
if numel(unique(expectedAlphaKeys)) ~= numel(expectedAlphaKeys) ...
        || ~isequal(expectedAlphaKeys, combinedAlphaKeys) ...
        || ~isequal(expectedLedgerKeys, combinedLedgerKeys) ...
        || numel(unique(frozenKeys)) ~= numel(frozenKeys) ...
        || ~isequal(sort(expectedAlphaKeys), sort(frozenKeys))
    globalIdentityErrors = 1;
end
totalPaths = height(alphaCombined);
totalWindows = numel(unique(string(alphaCombined.run_id) + ":" + ...
    string(alphaCombined.window_id)));
totalMpc = sum(double(alphaCombined.is_multipath) == 1);
totalDirect = sum(double(alphaCombined.is_multipath) == 0);
availableCount = sum(string(alphaCombined.alpha_status) == "AVAILABLE");
missingCount = sum(string(alphaCombined.alpha_status) == "MISSING");
available = string(alphaCombined.alpha_status) == "AVAILABLE";
nonfiniteCount = sum(available & (~isfinite(double(alphaCombined.alpha_real)) ...
    | ~isfinite(double(alphaCombined.alpha_imag))));
powerMismatchCount = sum(string(alphaCombined.relative_power_check_status) == "MISMATCH");
allRunsPass = all(string({runResult.status}) == "PASS");
if allRunsPass && globalIdentityErrors == 0 ...
        && totalPaths == height(frozenLedger) ...
        && totalPaths == double(batch.stage2_path_count) ...
        && totalWindows == double(batch.stage2_window_count) ...
        && totalMpc == double(batch.stage2_mpc_count) ...
        && totalDirect == double(batch.stage2_direct_count) ...
        && string(batch.status) == "COMPLETE" && nonfiniteCount == 0 ...
        && powerMismatchCount == 0
    status = "PASS";
elseif allRunsPass && globalIdentityErrors == 0 ...
        && totalPaths == height(frozenLedger)
    status = "PASS_WITH_DIAGNOSTICS";
else
    status = "FAIL";
end

report = struct('status', status, 'validated_utc', utcNow(), ...
    'project_root', projectRoot, 'output_root', outputRoot, ...
    'input_manifest_sha256', manifestSha, ...
    'task6_ledger_path', task6LedgerPath, 'task6_ledger_sha256', ledgerSha, ...
    'run_count_expected', height(manifest), ...
    'run_count_pass', sum(string({runResult.status}) == "PASS"), ...
    'stage2_path_count', totalPaths, 'stage2_window_count', totalWindows, ...
    'stage2_mpc_count', totalMpc, 'stage2_direct_count', totalDirect, ...
    'alpha_available_count', availableCount, 'alpha_missing_count', missingCount, ...
    'alpha_nonfinite_available_count', nonfiniteCount, ...
    'relative_power_mismatch_count', powerMismatchCount, ...
    'path_identity_error_count', globalIdentityErrors + ...
        sum([runResult.identity_error_count]), ...
    'numeric_error_count', sum([runResult.numeric_error_count]), ...
    'source_sha_error_count', sum([runResult.source_sha_error_count]), ...
    'max_stage2_attribute_abs_diff', maxStage2Diff, ...
    'max_alpha_component_abs_diff', maxAlphaDiff, ...
    'independent_per_run_report', ...
        fullfile(outputRoot, 'independent_validation_per_run.csv'), ...
    'independent_summary_report', ...
        fullfile(outputRoot, 'independent_validation_summary.json'));
assert(~isfile(report.independent_per_run_report) ...
    && ~isfile(report.independent_summary_report), ...
    'GNSS:WP5:ValidationReportCollision', ...
    'Independent validation report already exists; refusing overwrite.');
perRunTable = table(string({runResult.run_id}).', ...
    string({runResult.status}).', [runResult.path_count].', ...
    [runResult.window_count].', [runResult.mpc_count].', ...
    [runResult.direct_count].', [runResult.alpha_available_count].', ...
    [runResult.alpha_missing_count].', [runResult.alpha_nonfinite_count].', ...
    [runResult.power_pass_count].', [runResult.power_mismatch_count].', ...
    [runResult.identity_error_count].', [runResult.numeric_error_count].', ...
    [runResult.source_sha_error_count].', ...
    [runResult.max_stage2_attribute_abs_diff].', ...
    [runResult.max_alpha_component_abs_diff].', string({runResult.errors}).', ...
    'VariableNames', {'run_id', 'status', 'path_count', 'window_count', ...
    'mpc_count', 'direct_count', 'alpha_available_count', ...
    'alpha_missing_count', 'alpha_nonfinite_count', 'power_pass_count', ...
    'power_mismatch_count', 'identity_error_count', 'numeric_error_count', ...
    'source_sha_error_count', 'max_stage2_attribute_abs_diff', ...
    'max_alpha_component_abs_diff', 'errors'});
writetable(perRunTable, report.independent_per_run_report);
writeJsonNew(report.independent_summary_report, report);
end

function item = runResultTemplate(runId)
item = struct('run_id', runId, 'status', 'NOT_VALIDATED', ...
    'path_count', 0, 'window_count', 0, 'mpc_count', 0, ...
    'direct_count', 0, 'alpha_available_count', 0, ...
    'alpha_missing_count', 0, 'alpha_nonfinite_count', 0, ...
    'power_pass_count', 0, 'power_mismatch_count', 0, ...
    'identity_error_count', 0, 'numeric_error_count', 0, ...
    'source_sha_error_count', 0, 'max_stage2_attribute_abs_diff', 0, ...
    'max_alpha_component_abs_diff', 0, 'errors', '');
end

function keys = makeKeys(runId, windowId, pathId)
keys = string(runId) + "|" + string(windowId) + "|" + string(pathId);
keys = keys(:);
end

function keys = combinedAlphaKeysFor(value, rows)
keys = makeKeys(value.run_id(rows), value.window_id(rows), value.path_id(rows));
end

function rows = mapFrozenRows(ledger, runId, windowId, pathId)
keys = makeKeys(ledger.run_id, ledger.window_id, ledger.path_id);
target = makeKeys(repmat(string(runId), numel(windowId), 1), ...
    windowId, pathId);
[present, rows] = ismember(target, keys);
assert(all(present) && numel(unique(rows)) == numel(rows), ...
    'Frozen Task6 ledger lacks or duplicates a Stage2 path identity.');
end

function normalized = normalizePrn(value)
normalized = upper(regexprep(string(value), '^G', ''));
end

function [available, alpha, reason] = deriveAlphaIndependently(fits, windowId, order, pathId)
available = false;
alpha = complex(NaN, NaN);
matches = [];
for k = 1:numel(fits)
    fit = fits{k};
    if isstruct(fit) && isfield(fit, 'windowId') ...
            && isnumeric(fit.windowId) && isscalar(fit.windowId) ...
            && isfinite(double(fit.windowId)) ...
            && double(fit.windowId) == windowId
        matches(end + 1) = k; %#ok<AGROW>
    end
end
if isempty(matches)
    reason = "NO_STAGE2_FIT_FOR_WINDOW";
    return;
elseif numel(matches) > 1
    reason = "AMBIGUOUS_STAGE2_FIT_FOR_WINDOW";
    return;
end
fit = fits{matches(1)};
if ~isfield(fit, 'selectedOrder') || ~isscalar(fit.selectedOrder) ...
        || ~isnumeric(fit.selectedOrder) || ~isfinite(double(fit.selectedOrder))
    reason = "SELECTED_ORDER_MISSING_OR_INVALID";
    return;
elseif double(fit.selectedOrder) ~= order
    reason = "SELECTED_ORDER_MISMATCH";
    return;
elseif ~isfield(fit, 'models') || ~iscell(fit.models) ...
        || numel(fit.models) < order || isempty(fit.models{order})
    reason = "SELECTED_MODEL_MISSING";
    return;
end
model = fit.models{order};
if ~isstruct(model) || ~isfield(model, 'paths')
    reason = "SELECTED_MODEL_PATHS_MISSING";
    return;
elseif numel(model.paths) < pathId
    reason = "STAGE2_PATH_ID_MISSING";
    return;
end
path = model.paths(pathId);
if ~isstruct(path) || ~isfield(path, 'alpha')
    reason = "ALPHA_FIELD_MISSING";
    return;
end
candidate = path.alpha;
if ~isnumeric(candidate) || ~isscalar(candidate) ...
        || ~isfinite(real(candidate)) || ~isfinite(imag(candidate))
    reason = "ALPHA_NONFINITE_OR_INVALID";
    return;
end
available = true;
alpha = candidate;
reason = "NONE";
end

function status = independentPowerStatus(source, alpha, alphaStatus)
status = repmat("NOT_CHECKED_ALPHA_MISSING", height(source), 1);
windows = unique(double(source.window_id), 'stable');
for w = 1:numel(windows)
    rows = find(double(source.window_id) == windows(w));
    reference = rows(double(source.path_id(rows)) == 1);
    assert(numel(reference) == 1, ...
        'Stage2 window lacks exactly one direct reference path.');
    for k = 1:numel(rows)
        row = rows(k);
        if alphaStatus(row) ~= "AVAILABLE"
            status(row) = "NOT_CHECKED_ALPHA_MISSING";
        elseif alphaStatus(reference) ~= "AVAILABLE"
            status(row) = "NOT_CHECKED_REFERENCE_ALPHA_MISSING";
        elseif ~isfinite(double(source.relative_power_db(row)))
            status(row) = "NOT_CHECKED_RELATIVE_POWER_INVALID";
        else
            expected = 10 * log10(max(abs(alpha(row))^2, realmin) ...
                / max(abs(alpha(reference))^2, realmin));
            if abs(expected - double(source.relative_power_db(row))) <= 1e-6
                status(row) = "PASS";
            else
                status(row) = "MISMATCH";
            end
        end
    end
end
end

function sha = sha256File(path)
fid = fopen(path, 'rb');
assert(fid >= 0, 'Could not open file for SHA-256: %s', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
digest = java.security.MessageDigest.getInstance('SHA-256');
while true
    bytes = fread(fid, 1024 * 1024, '*uint8');
    if isempty(bytes), break; end
    digest.update(typecast(bytes(:), 'int8'));
end
raw = typecast(digest.digest(), 'uint8');
sha = lower(reshape(dec2hex(raw, 2).', 1, []));
end

function writeJsonNew(path, value)
fid = fopen(path, 'w', 'n', 'UTF-8');
assert(fid >= 0, 'Could not create validation JSON: %s', path);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fwrite(fid, jsonencode(value, 'PrettyPrint', true), 'char');
fwrite(fid, newline, 'char');
end

function text = utcNow()
text = char(datetime('now', 'TimeZone', 'UTC', ...
    'Format', 'yyyy-MM-dd''T''HH:mm:ss.SSS''Z'''));
end
