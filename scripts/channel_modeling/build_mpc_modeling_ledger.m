function result = build_mpc_modeling_ledger( ...
    stage2PathsCsvPath, stage3PersistenceCsvPath, ...
    stage3ReliableCentersCsvPath, stage4SummaryCsvPath, ...
    stage4PathsCsvPath, alphaCsvPath, outputCsvPath, provenance)
%BUILD_MPC_MODELING_LEDGER Preserve all Stage2 paths with exact stage keys.

requiredProvenance = {'run_id', 'scene_id', 'prn', ...
    'tracking_channel', 'sample_rate_hz', 'frozen_sage_sha256', ...
    'stage2_mat_sha256', 'selected_paths_csv_sha256'};
assert(all(isfield(provenance, requiredProvenance)), ...
    'GNSS:SAGE:LedgerProvenanceMissing', ...
    'Required run provenance is incomplete.');
inputPaths = {stage2PathsCsvPath, stage3PersistenceCsvPath, ...
    stage3ReliableCentersCsvPath, stage4SummaryCsvPath, ...
    stage4PathsCsvPath, alphaCsvPath};
assert(all(cellfun(@isfile, inputPaths)), ...
    'GNSS:SAGE:LedgerInputMissing', ...
    'One or more Stage2/Stage3/Stage4/alpha input files are missing.');
assert(~isfile(outputCsvPath), ...
    'GNSS:SAGE:LedgerOutputCollision', ...
    'Refusing to overwrite modeling ledger: %s', outputCsvPath);

stage2 = readtable(stage2PathsCsvPath);
stage3 = readtable(stage3PersistenceCsvPath);
reliable = readtable(stage3ReliableCentersCsvPath);
stage4Summary = readtable(stage4SummaryCsvPath);
stage4Paths = readtable(stage4PathsCsvPath);
alpha = readtable(alphaCsvPath, 'TextType', 'string');
assert(hasColumns(stage2, {'window_id', 'path_id', 'is_multipath'}), ...
    'GNSS:SAGE:LedgerStage2SchemaMismatch', ...
    'Stage2 selected-path table lacks exact identity columns.');
assert(hasColumns(stage3, {'center_window_id', 'multipath_id', ...
    'persistence_pass', 'matched_window_count', ...
    'longest_consecutive_count'}), ...
    'GNSS:SAGE:LedgerStage3SchemaMismatch', ...
    'Stage3 persistence table lacks exact identity/status columns.');
assert(hasColumns(reliable, {'center_window_id'}) ...
    && hasColumns(stage4Summary, {'center_window_id', ...
    'joint_valid', 'joint_selected_L'}) ...
    && hasColumns(stage4Paths, {'center_window_id', 'path_id', ...
    'is_multipath'}), ...
    'GNSS:SAGE:LedgerStage4SchemaMismatch', ...
    'Stage3 reliable-center or Stage4 table lacks required identity fields.');
assert(hasColumns(alpha, {'window_id', 'path_id', 'alpha_real', ...
    'alpha_imag', 'alpha_magnitude', 'alpha_phase_rad', ...
    'alpha_status', 'alpha_missing_reason', ...
    'relative_power_check_status', ...
    'run_id', 'scene_id', 'prn', 'tracking_channel', ...
    'sample_rate_hz', 'frozen_sage_sha256', 'stage2_mat_sha256', ...
    'selected_paths_csv_sha256', ...
    'source_stage2_mat_path', 'source_selected_paths_csv_path', ...
    'SAGE_ALPHA_IS_FROM_WINDOW_NORMALIZED_IQ'}), ...
    'GNSS:SAGE:LedgerAlphaSchemaMismatch', ...
    'Complex-alpha export lacks required identity/provenance fields.');
expectedSha = normalizeSha256(provenance.frozen_sage_sha256, ...
    'frozen_sage_sha256');
expectedMatSha = normalizeSha256(provenance.stage2_mat_sha256, ...
    'stage2_mat_sha256');
expectedPathsSha = normalizeSha256( ...
    provenance.selected_paths_csv_sha256, 'selected_paths_csv_sha256');
assert(all(string(alpha.run_id) == string(provenance.run_id)) ...
    && all(string(alpha.scene_id) == string(provenance.scene_id)) ...
    && all(string(alpha.prn) == string(provenance.prn)) ...
    && all(double(alpha.tracking_channel) == ...
        double(provenance.tracking_channel)) ...
    && all(double(alpha.sample_rate_hz) == ...
        double(provenance.sample_rate_hz)) ...
    && all(lower(string(alpha.frozen_sage_sha256)) == expectedSha) ...
    && all(lower(string(alpha.stage2_mat_sha256)) == expectedMatSha) ...
    && all(lower(string(alpha.selected_paths_csv_sha256)) ...
        == expectedPathsSha) ...
    && all(strlength(string(alpha.source_stage2_mat_path)) > 0) ...
    && all(strlength(string(alpha.source_selected_paths_csv_path)) > 0) ...
    && numel(unique(string(alpha.source_stage2_mat_path))) == 1 ...
    && numel(unique(string(alpha.source_selected_paths_csv_path))) == 1, ...
    'GNSS:SAGE:AlphaProvenanceMismatch', ...
    'Alpha identity or source provenance does not match this run.');
for columnName = {'run_id', 'scene_id', 'prn', ...
        'tracking_channel', 'sample_rate_hz'}
    name = columnName{1};
    if ismember(name, stage2.Properties.VariableNames)
        assert(all(string(stage2.(name)) == ...
            string(provenance.(name))), ...
            'GNSS:SAGE:Stage2ProvenanceMismatch', ...
            'Stage2 input %s does not match run provenance.', name);
    end
end
assert(height(stage2) > 0, 'GNSS:SAGE:LedgerStage2Empty', ...
    'Stage2 selected-path table is empty.');

stage2Keys = [double(stage2.window_id), double(stage2.path_id)];
assert(size(unique(stage2Keys, 'rows'), 1) == height(stage2), ...
    'GNSS:SAGE:DuplicateStage2Identity', ...
    'Stage2 contains duplicate (window_id,path_id) identities.');
alphaKeys = [double(alpha.window_id), double(alpha.path_id)];
assert(size(unique(alphaKeys, 'rows'), 1) == height(alpha), ...
    'GNSS:SAGE:DuplicateAlphaIdentity', ...
    'Alpha export contains duplicate (window_id,path_id) identities.');
stage2InAlpha = ismember(stage2Keys, alphaKeys, 'rows');
alphaIsDirectReference = alphaKeys(:, 2) == 1;
assert(all(stage2InAlpha) ...
    && all(alphaIsDirectReference(~ismember(alphaKeys, ...
        stage2Keys, 'rows'))), ...
    'GNSS:SAGE:AlphaStage2IdentitySetMismatch', ...
    ['Every Stage2 path must have exactly one alpha identity. Additional ' ...
    'alpha rows are allowed only for path_id=1 direct-path references.']);
stage2Windows = unique(stage2Keys(:, 1));
for windowIndex = 1:numel(stage2Windows)
    directKey = [stage2Windows(windowIndex), 1];
    assert(ismember(directKey, alphaKeys, 'rows'), ...
        'GNSS:SAGE:AlphaDirectReferenceMissing', ...
        'Alpha export lacks the direct-path reference for window_id=%g.', ...
        stage2Windows(windowIndex));
end

alphaStatuses = string(alpha.alpha_status);
alphaMissingReasons = string(alpha.alpha_missing_reason);
relativePowerStatuses = string(alpha.relative_power_check_status);
allowedPowerStatuses = ["PASS", "MISMATCH", ...
    "NOT_CHECKED_ALPHA_MISSING", ...
    "NOT_CHECKED_REFERENCE_ALPHA_MISSING", ...
    "NOT_CHECKED_RELATIVE_POWER_INVALID"];
assert(all(ismember(alphaStatuses, ["AVAILABLE", "MISSING"])) ...
    && all(ismember(relativePowerStatuses, allowedPowerStatuses)), ...
    'GNSS:SAGE:AlphaStatusInvalid', ...
    'Alpha availability or relative-power check status is invalid.');
for alphaIndex = 1:height(alpha)
    alphaValues = double([alpha.alpha_real(alphaIndex), ...
        alpha.alpha_imag(alphaIndex), alpha.alpha_magnitude(alphaIndex), ...
        alpha.alpha_phase_rad(alphaIndex)]);
    if alphaStatuses(alphaIndex) == "AVAILABLE"
        assert(alphaMissingReasons(alphaIndex) == "NONE" ...
            && all(isfinite(alphaValues)) ...
            && abs(alphaValues(3) - hypot(alphaValues(1), ...
                alphaValues(2))) <= 1e-12 ...
            && abs(angle(exp(1i * (alphaValues(4) ...
                - atan2(alphaValues(2), alphaValues(1)))))) <= 1e-12, ...
            'GNSS:SAGE:AlphaValueInconsistent', ...
            'Available alpha components are inconsistent at row %d.', ...
            alphaIndex);
    else
        assert(strlength(alphaMissingReasons(alphaIndex)) > 0 ...
            && all(isnan(alphaValues)), ...
            'GNSS:SAGE:AlphaMissingReasonRequired', ...
            ['Missing alpha must retain NaN numeric fields and a reason ' ...
            'at row %d.'], alphaIndex);
    end
end
if ismember('relative_power_db', stage2.Properties.VariableNames)
    for rowIndex = 1:height(stage2)
        windowId = stage2Keys(rowIndex, 1);
        pathId = stage2Keys(rowIndex, 2);
        targetAlphaRow = find(ismember(alphaKeys, ...
            [windowId, pathId], 'rows'));
        directAlphaRow = find(ismember(alphaKeys, [windowId, 1], 'rows'));
        expectedStatus = relativePowerStatusForValues( ...
            alpha, alphaStatuses, targetAlphaRow, directAlphaRow, ...
            double(stage2.relative_power_db(rowIndex)));
        assert(relativePowerStatuses(targetAlphaRow) == expectedStatus, ...
            'GNSS:SAGE:RelativePowerCheckStatusMismatch', ...
            ['Alpha export relative-power status disagrees with the ' ...
            'Stage2 value at window=%g path=%g.'], windowId, pathId);
    end
end

rowCount = height(stage2);
stage3Persistent = strings(rowCount, 1);
stage3MatchStatus = strings(rowCount, 1);
stage3ReliableCenter = strings(rowCount, 1);
stage3MatchedCount = nan(rowCount, 1);
stage3LongestRun = nan(rowCount, 1);
stage3MatchPattern = strings(rowCount, 1);
stage4Confirmed = strings(rowCount, 1);
stage4MappingStatus = strings(rowCount, 1);
stage4JointValid = strings(rowCount, 1);
stage4SelectedOrder = nan(rowCount, 1);
modelingClass = strings(rowCount, 1);
primaryPool = strings(rowCount, 1);
alphaReal = nan(rowCount, 1);
alphaImag = nan(rowCount, 1);
alphaMagnitude = nan(rowCount, 1);
alphaPhase = nan(rowCount, 1);
alphaWindowNormalized = strings(rowCount, 1);
alphaStatus = strings(rowCount, 1);
alphaMissingReason = strings(rowCount, 1);
relativePowerCheckStatus = strings(rowCount, 1);
sourceStage2MatPath = strings(rowCount, 1);
sourceSelectedPathsCsvPath = strings(rowCount, 1);

for rowIndex = 1:rowCount
    windowId = double(stage2.window_id(rowIndex));
    pathId = double(stage2.path_id(rowIndex));
    isMultipath = asLogical(stage2.is_multipath(rowIndex));
    matchingAlpha = find(double(alpha.window_id) == windowId ...
        & double(alpha.path_id) == pathId);
    assert(numel(matchingAlpha) == 1, ...
        'GNSS:SAGE:AlphaIdentityMismatch', ...
        'Expected one alpha row for Stage2 window=%g path=%g; found %d.', ...
        windowId, pathId, numel(matchingAlpha));
    alphaRow = matchingAlpha(1);
    alphaStatus(rowIndex) = alphaStatuses(alphaRow);
    alphaMissingReason(rowIndex) = alphaMissingReasons(alphaRow);
    relativePowerCheckStatus(rowIndex) = ...
        relativePowerStatuses(alphaRow);
    sourceStage2MatPath(rowIndex) = ...
        string(alpha.source_stage2_mat_path(alphaRow));
    sourceSelectedPathsCsvPath(rowIndex) = ...
        string(alpha.source_selected_paths_csv_path(alphaRow));
    alphaReal(rowIndex) = double(alpha.alpha_real(alphaRow));
    alphaImag(rowIndex) = double(alpha.alpha_imag(alphaRow));
    alphaMagnitude(rowIndex) = double(alpha.alpha_magnitude(alphaRow));
    alphaPhase(rowIndex) = double(alpha.alpha_phase_rad(alphaRow));
    alphaWindowNormalized(rowIndex) = string( ...
        alpha.SAGE_ALPHA_IS_FROM_WINDOW_NORMALIZED_IQ(alphaRow));
    assert(alphaWindowNormalized(rowIndex) == "YES", ...
        'GNSS:SAGE:AlphaProvenanceInvalid', ...
        'Alpha provenance is invalid at window=%g path=%g.', ...
        windowId, pathId);
    if alphaStatus(rowIndex) == "MISSING"
        assert(all(isnan([alphaReal(rowIndex), alphaImag(rowIndex), ...
            alphaMagnitude(rowIndex), alphaPhase(rowIndex)])) ...
            && strlength(alphaMissingReason(rowIndex)) > 0, ...
            'GNSS:SAGE:AlphaMissingReasonRequired', ...
            'Missing alpha has no valid reason at window=%g path=%g.', ...
            windowId, pathId);
    else
        assert(all(isfinite([alphaReal(rowIndex), alphaImag(rowIndex), ...
            alphaMagnitude(rowIndex), alphaPhase(rowIndex)])), ...
            'GNSS:SAGE:AlphaProvenanceInvalid', ...
            'Available alpha is nonfinite at window=%g path=%g.', ...
            windowId, pathId);
    end

    if ~isMultipath
        stage3Persistent(rowIndex) = "NA";
        stage3MatchStatus(rowIndex) = "NOT_APPLICABLE_DIRECT_PATH";
        stage3ReliableCenter(rowIndex) = "NA";
        stage4Confirmed(rowIndex) = "NA";
        stage4MappingStatus(rowIndex) = "NOT_APPLICABLE_DIRECT_PATH";
        stage4JointValid(rowIndex) = "NA";
        modelingClass(rowIndex) = "DIRECT_PATH";
        primaryPool(rowIndex) = "NO";
        continue;
    end

    stage3AtCenter = find(double(stage3.center_window_id) == windowId);
    stage3Matches = stage3AtCenter( ...
        double(stage3.multipath_id(stage3AtCenter)) == pathId - 1);
    if numel(stage3Matches) > 1
        error('GNSS:SAGE:AmbiguousStage3Mapping', ...
            ['Multiple Stage3 rows map to Stage2 window=%g path=%g; ' ...
            'classification stopped.'], windowId, pathId);
    elseif isempty(stage3Matches)
        assert(isempty(stage3AtCenter), ...
            'GNSS:SAGE:AmbiguousStage3Mapping', ...
            ['Stage3 evaluated center window=%g but has no exact ' ...
            'multipath_id=%g row for Stage2 path_id=%g.'], ...
            windowId, pathId - 1, pathId);
        stage3Persistent(rowIndex) = "NO";
        stage3MatchStatus(rowIndex) = "NOT_ASSESSED_STAGE2_ONLY";
        stage3ReliableCenter(rowIndex) = "NO";
        stage4Confirmed(rowIndex) = "UNMAPPED";
        stage4MappingStatus(rowIndex) = ...
            "NOT_EVALUATED_NOT_STAGE3_PERSISTENT";
        stage4JointValid(rowIndex) = "UNMAPPED";
        modelingClass(rowIndex) = "TRANSIENT_MPC";
        primaryPool(rowIndex) = "NO";
    else
        persistenceRow = stage3Matches(1);
        isPersistent = asLogical(stage3.persistence_pass(persistenceRow));
        stage3MatchedCount(rowIndex) = ...
            double(stage3.matched_window_count(persistenceRow));
        stage3LongestRun(rowIndex) = ...
            double(stage3.longest_consecutive_count(persistenceRow));
        if ismember('match_pattern', stage3.Properties.VariableNames)
            stage3MatchPattern(rowIndex) = string( ...
                stage3.match_pattern(persistenceRow));
        end
        if isPersistent
            stage3Persistent(rowIndex) = "YES";
            stage3MatchStatus(rowIndex) = "EXACT_STAGE3_PATH_MATCH";
            modelingClass(rowIndex) = "PERSISTENT_MPC";
            primaryPool(rowIndex) = "YES";
        else
            stage3Persistent(rowIndex) = "NO";
            stage3MatchStatus(rowIndex) = "EXACT_STAGE3_PATH_MATCH";
            stage4Confirmed(rowIndex) = "UNMAPPED";
            stage4MappingStatus(rowIndex) = ...
                "NOT_EVALUATED_NOT_STAGE3_PERSISTENT";
            stage4JointValid(rowIndex) = "UNMAPPED";
            modelingClass(rowIndex) = "TRANSIENT_MPC";
            primaryPool(rowIndex) = "NO";
        end
        reliableMatches = find(double(reliable.center_window_id) == windowId);
        assert(numel(reliableMatches) <= 1, ...
            'GNSS:SAGE:AmbiguousStage3Mapping', ...
            'Stage3 reliable-center identity is duplicated for window=%g.', ...
            windowId);
        if isempty(reliableMatches)
            stage3ReliableCenter(rowIndex) = "NO";
        else
            stage3ReliableCenter(rowIndex) = "YES";
        end

        if isPersistent
            summaryMatches = find( ...
                double(stage4Summary.center_window_id) == windowId);
            if numel(summaryMatches) == 1
                summaryRow = summaryMatches(1);
                validJoint = asLogical(stage4Summary.joint_valid(summaryRow));
                selectedOrder = ...
                    double(stage4Summary.joint_selected_L(summaryRow));
                stage4SelectedOrder(rowIndex) = selectedOrder;
                stage4JointValid(rowIndex) = string(validJoint);
                if validJoint && selectedOrder == 1
                    stage4Confirmed(rowIndex) = "NO";
                    stage4MappingStatus(rowIndex) = ...
                        "VALID_STAGE4_SELECTED_L1_NO_MPC";
                elseif validJoint && selectedOrder >= pathId
                    pathMatches = find( ...
                        double(stage4Paths.center_window_id) == windowId ...
                        & double(stage4Paths.path_id) == pathId);
                    pathMatches = pathMatches(arrayfun(@(idx) ...
                        asLogical(stage4Paths.is_multipath(idx)), ...
                        pathMatches));
                    if numel(pathMatches) == 1
                        stage4Confirmed(rowIndex) = "YES";
                        stage4MappingStatus(rowIndex) = ...
                            "EXACT_STAGE4_PATH_MATCH";
                    else
                        stage4Confirmed(rowIndex) = "UNMAPPED";
                        stage4MappingStatus(rowIndex) = ...
                            "NO_UNIQUE_EXACT_STAGE4_PATH_MATCH";
                    end
                elseif ~validJoint
                    stage4Confirmed(rowIndex) = "UNMAPPED";
                    stage4MappingStatus(rowIndex) = ...
                        "STAGE4_JOINT_RESULT_INVALID";
                else
                    stage4Confirmed(rowIndex) = "UNMAPPED";
                    stage4MappingStatus(rowIndex) = ...
                        "STAGE4_SELECTED_MODEL_CANNOT_MAP_PATH_ID";
                end
            else
                stage4Confirmed(rowIndex) = "UNMAPPED";
                stage4JointValid(rowIndex) = "UNMAPPED";
                stage4MappingStatus(rowIndex) = ...
                    "NO_UNIQUE_STAGE4_CENTER_RESULT";
            end
            if stage4Confirmed(rowIndex) == "YES"
                modelingClass(rowIndex) = "HIGH_CONFIDENCE_MPC";
                primaryPool(rowIndex) = "YES";
            end
        end
    end
end

stage3Persistent(stage3Persistent == "") = "UNMAPPED";
stage3MatchStatus(stage3MatchStatus == "") = "UNMAPPED";
stage3ReliableCenter(stage3ReliableCenter == "") = "UNMAPPED";
stage4Confirmed(stage4Confirmed == "") = "UNMAPPED";
stage4MappingStatus(stage4MappingStatus == "") = "UNMAPPED";
stage4JointValid(stage4JointValid == "") = "UNMAPPED";
assert(all(modelingClass ~= "") && all(primaryPool ~= ""), ...
    'GNSS:SAGE:LedgerClassificationIncomplete', ...
    'At least one Stage2 row could not be classified without guessing.');

ledger = table();
ledger.run_id = repmat(string(provenance.run_id), rowCount, 1);
ledger.scene_id = repmat(string(provenance.scene_id), rowCount, 1);
ledger.prn = repmat(string(provenance.prn), rowCount, 1);
ledger.tracking_channel = repmat( ...
    double(provenance.tracking_channel), rowCount, 1);
ledger.sample_rate_hz = repmat( ...
    double(provenance.sample_rate_hz), rowCount, 1);
ledger.frozen_sage_sha256 = repmat(expectedSha, rowCount, 1);
ledger.window_id = double(stage2.window_id);
ledger.recording_time_s = getNumericColumn(stage2, ...
    'recording_time_s', rowCount);
ledger.selected_L = getNumericColumn(stage2, 'selected_L', rowCount);
ledger.path_id = double(stage2.path_id);
ledger.is_multipath = arrayfun(@(idx) ...
    double(asLogical(stage2.is_multipath(idx))), (1:rowCount).');
ledger.delay_samples = getNumericColumn(stage2, 'delay_samples', rowCount);
ledger.excess_delay_samples = getNumericColumn(stage2, ...
    'excess_delay_samples', rowCount);
ledger.excess_delay_chips = getNumericColumn(stage2, ...
    'excess_delay_chips', rowCount);
ledger.excess_path_length_m = getNumericColumn(stage2, ...
    'excess_path_length_m', rowCount);
ledger.doppler_hz = getNumericColumn(stage2, 'doppler_hz', rowCount);
ledger.doppler_offset_hz = getNumericColumn(stage2, ...
    'doppler_offset_hz', rowCount);
ledger.relative_power_db = getNumericColumn(stage2, ...
    'relative_power_db', rowCount);
ledger.alpha_real = alphaReal;
ledger.alpha_imag = alphaImag;
ledger.alpha_magnitude = alphaMagnitude;
ledger.alpha_phase_rad = alphaPhase;
ledger.alpha_status = alphaStatus;
ledger.alpha_missing_reason = alphaMissingReason;
ledger.relative_power_check_status = relativePowerCheckStatus;
ledger.source_stage2_mat_path = sourceStage2MatPath;
ledger.source_selected_paths_csv_path = sourceSelectedPathsCsvPath;
ledger.stage2_mat_sha256 = repmat(expectedMatSha, rowCount, 1);
ledger.selected_paths_csv_sha256 = repmat(expectedPathsSha, rowCount, 1);
ledger.SAGE_ALPHA_IS_FROM_WINDOW_NORMALIZED_IQ = alphaWindowNormalized;
ledger.stage3_persistent = stage3Persistent;
ledger.stage3_match_status = stage3MatchStatus;
ledger.stage3_matched_window_count = stage3MatchedCount;
ledger.stage3_longest_consecutive_count = stage3LongestRun;
ledger.stage3_match_pattern = stage3MatchPattern;
ledger.stage3_reliable_center = stage3ReliableCenter;
ledger.stage4_confirmed = stage4Confirmed;
ledger.stage4_mapping_status = stage4MappingStatus;
ledger.stage4_joint_valid = stage4JointValid;
ledger.stage4_joint_selected_L = stage4SelectedOrder;
ledger.modeling_class = modelingClass;
ledger.mpc_member = repmat("YES", rowCount, 1);
ledger.mpc_member(ledger.is_multipath == 0) = "NO";
ledger.primary_modeling_pool = primaryPool;

assert(height(ledger) == height(stage2) ...
    && sum(ledger.is_multipath == 0) ...
    + sum(ledger.is_multipath == 1) == height(stage2), ...
    'GNSS:SAGE:LedgerRowConservationFailed', ...
    'Ledger rows do not exactly conserve Stage2 selected-path rows.');
assert(all(ledger.modeling_class(ledger.is_multipath == 0) ...
    == "DIRECT_PATH") ...
    && all(ledger.primary_modeling_pool(ledger.is_multipath == 0) ...
    == "NO"), ...
    'GNSS:SAGE:DirectPathClassificationFailed', ...
    'Direct paths must be retained and excluded from MPC modeling.');

temporaryCsvPath = [tempname(fileparts(outputCsvPath)), '.csv'];
writetable(ledger, temporaryCsvPath);
assert(~isfile(outputCsvPath), ...
    'GNSS:SAGE:LedgerOutputCollision', ...
    'Refusing to overwrite modeling ledger: %s', outputCsvPath);
[moved, message] = movefile(temporaryCsvPath, outputCsvPath);
assert(moved, 'GNSS:SAGE:LedgerPublishFailed', ...
    'Could not publish modeling ledger: %s', message);

result = struct();
result.ledger_stage2_selected_path_rows = rowCount;
result.direct_path_rows = sum(ledger.is_multipath == 0);
result.multipath_rows = sum(ledger.is_multipath == 1);
result.primary_modeling_pool_count = ...
    sum(ledger.primary_modeling_pool == "YES");
result.direct_path_class_count = sum( ...
    ledger.modeling_class == "DIRECT_PATH");
result.transient_mpc_count = sum( ...
    ledger.modeling_class == "TRANSIENT_MPC");
result.persistent_mpc_count = sum( ...
    ledger.modeling_class == "PERSISTENT_MPC");
result.high_confidence_mpc_count = sum( ...
    ledger.modeling_class == "HIGH_CONFIDENCE_MPC");
result.alpha_available_count = sum(ledger.alpha_status == "AVAILABLE");
result.alpha_missing_count = sum(ledger.alpha_status == "MISSING");
result.alpha_relative_power_mismatch_count = sum( ...
    ledger.relative_power_check_status == "MISMATCH");
result.ledger_path = outputCsvPath;
end

function present = hasColumns(inputTable, names)
present = all(ismember(names, inputTable.Properties.VariableNames));
end

function value = asLogical(inputValue)
if islogical(inputValue)
    value = inputValue;
elseif isnumeric(inputValue)
    value = inputValue ~= 0;
else
    text = lower(strtrim(string(inputValue)));
    value = any(text == ["true", "1", "yes"]);
end
end

function values = getNumericColumn(inputTable, name, rowCount)
if ismember(name, inputTable.Properties.VariableNames)
    values = double(inputTable.(name));
else
    values = nan(rowCount, 1);
end
end

function status = relativePowerStatusForValues( ...
    alpha, alphaStatuses, targetRow, directRow, relativePowerDb)
if alphaStatuses(targetRow) ~= "AVAILABLE"
    status = "NOT_CHECKED_ALPHA_MISSING";
elseif alphaStatuses(directRow) ~= "AVAILABLE"
    status = "NOT_CHECKED_REFERENCE_ALPHA_MISSING";
elseif ~isfinite(relativePowerDb)
    status = "NOT_CHECKED_RELATIVE_POWER_INVALID";
else
    target = complex(double(alpha.alpha_real(targetRow)), ...
        double(alpha.alpha_imag(targetRow)));
    direct = complex(double(alpha.alpha_real(directRow)), ...
        double(alpha.alpha_imag(directRow)));
    expectedDb = 10 * log10(max(abs(target)^2, realmin) ...
        / max(abs(direct)^2, realmin));
    if abs(expectedDb - relativePowerDb) <= 1e-6
        status = "PASS";
    else
        status = "MISMATCH";
    end
end
end

function sha = normalizeSha256(value, fieldName)
if isstring(value) && isscalar(value)
    shaText = char(value);
elseif ischar(value) && isrow(value)
    shaText = value;
else
    shaText = '';
end
assert(~isempty(regexp(lower(shaText), '^[0-9a-f]{64}$', 'once')), ...
    'GNSS:SAGE:LedgerProvenanceInvalid', ...
    '%s must contain exactly 64 hexadecimal characters.', fieldName);
sha = string(lower(shaText));
end
