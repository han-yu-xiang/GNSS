function result = audit_gnss_code_domain_cir_pdp(hdf5Path, stage0Table, options)
%AUDIT_GNSS_CODE_DOMAIN_CIR_PDP Independently audit CIR/PDP and window axes.
% This auditor does not call the production CIR validator. CIR matrices are
% read in bounded row chunks; PDP is independently recomputed as the mean
% power of each window's 40 one-ms complex CIR snapshots.

if nargin < 3 || isempty(options)
    options = struct();
end
options = applyDefaults(options, struct( ...
    'chunk_rows', 64, ...
    'snapshots_per_window', 40, ...
    'sample_rate_hz', 10230000, ...
    'pdp_absolute_tolerance', 0, ...
    'pdp_relative_tolerance', 64 * eps(1), ...
    'time_tolerance_s', 1e-12));

assert(isfile(hdf5Path), 'GNSS:SAGE:GateFInputMissing', ...
    'CIR HDF5 does not exist: %s.', hdf5Path);
assert(istable(stage0Table) && all(ismember( ...
    {'window_id', 'sample_start_zero_based', 'recording_time_s'}, ...
    stage0Table.Properties.VariableNames)), ...
    'GNSS:SAGE:GateFStage0SchemaMismatch', ...
    'Stage0 table must contain window_id, sample_start_zero_based, and recording_time_s.');
assert(isscalar(options.chunk_rows) && options.chunk_rows >= 1 ...
    && options.chunk_rows == floor(options.chunk_rows) ...
    && isscalar(options.snapshots_per_window) ...
    && options.snapshots_per_window == 40, ...
    'GNSS:SAGE:GateFOptionsInvalid', ...
    'Chunk size must be a positive integer and frozen PDP window size is 40.');

try
    h5 = h5info(hdf5Path);
catch exception
    error('GNSS:SAGE:GateFHdf5ReadFailed', ...
        'Unable to read HDF5 metadata: %s.', exception.message);
end
datasetNames = {h5.Datasets.Name};
requiredNames = {'cir_real', 'cir_imag', 'time_s', 'delay_samples', ...
    'raw_iq_rms', 'tracking_doppler_hz', 'code_frequency_hz', ...
    'cn0_db_hz', 'nav_symbol', 'window_id', ...
    'snapshot_index_in_window', 'sample_start_zero_based', ...
    'nav_symbol_transition_offset_samples', 'pdp_window_id', ...
    'pdp_time_s', 'pdp_start_sample_zero_based', ...
    'pdp_interval_count', 'pdp_power'};
assert(all(ismember(requiredNames, datasetNames)), ...
    'GNSS:SAGE:GateFHdf5SchemaMismatch', ...
    'HDF5 is missing one or more frozen CIR/PDP datasets.');

cirRealSize = datasetDimensions(h5, 'cir_real');
cirImagSize = datasetDimensions(h5, 'cir_imag');
pdpSize = datasetDimensions(h5, 'pdp_power');
assert(numel(cirRealSize) == 2 && isequal(cirRealSize, cirImagSize) ...
    && numel(pdpSize) == 2 && cirRealSize(2) == 451 ...
    && pdpSize(2) == 451, ...
    'GNSS:SAGE:GateFDimensionsMismatch', ...
    'CIR/PDP dimensions are inconsistent with the frozen 451-bin grid.');

expectedIds = double(stage0Table.window_id(:));
expectedStarts = double(stage0Table.sample_start_zero_based(:));
expectedTimes = double(stage0Table.recording_time_s(:));
nWindows = height(stage0Table);
nSnapshots = cirRealSize(1);
nDelays = cirRealSize(2);
assert(nWindows > 0 && numel(unique(expectedIds)) == nWindows ...
    && all(isfinite(expectedIds)) && all(expectedIds > 0) ...
    && all(expectedIds == floor(expectedIds)) ...
    && all(isfinite(expectedStarts)) && all(expectedStarts >= 0) ...
    && all(expectedStarts == floor(expectedStarts)) ...
    && all(isfinite(expectedTimes)) ...
    && nSnapshots == options.snapshots_per_window * nWindows ...
    && isequal(pdpSize, [nWindows, nDelays]), ...
    'GNSS:SAGE:GateFWindowIdentityMismatch', ...
    'Stage0 identities, CIR snapshots, and PDP rows do not have a one-to-one shape.');

delay = double(h5read(hdf5Path, '/delay_samples'));
delay = delay(:);
expectedDelay = (-5:0.1:40).';
assert(isequal(delay, expectedDelay), ...
    'GNSS:SAGE:GateFDelayGridMismatch', ...
    'Delay grid differs from the frozen -5:0.1:40 sample grid.');

time = double(readVector(hdf5Path, '/time_s', nSnapshots));
sampleStart = double(readVector( ...
    hdf5Path, '/sample_start_zero_based', nSnapshots));
windowId = double(readVector(hdf5Path, '/window_id', nSnapshots));
snapshotIndex = double(readVector( ...
    hdf5Path, '/snapshot_index_in_window', nSnapshots));
rawIqRms = double(readVector(hdf5Path, '/raw_iq_rms', nSnapshots));
trackingDoppler = double(readVector( ...
    hdf5Path, '/tracking_doppler_hz', nSnapshots));
codeFrequency = double(readVector( ...
    hdf5Path, '/code_frequency_hz', nSnapshots));
cn0 = double(readVector(hdf5Path, '/cn0_db_hz', nSnapshots));
navSymbol = double(readVector(hdf5Path, '/nav_symbol', nSnapshots));
navTransition = double(readVector( ...
    hdf5Path, '/nav_symbol_transition_offset_samples', nSnapshots));
pdpIds = double(readVector(hdf5Path, '/pdp_window_id', nWindows));
pdpTimes = double(readVector(hdf5Path, '/pdp_time_s', nWindows));
pdpStarts = double(readVector( ...
    hdf5Path, '/pdp_start_sample_zero_based', nWindows));
pdpIntervals = double(readVector( ...
    hdf5Path, '/pdp_interval_count', nWindows));
pdpStored = double(h5read(hdf5Path, '/pdp_power'));

assert(isequal(pdpIds, expectedIds) ...
    && isequal(pdpStarts, expectedStarts) ...
    && all(abs(pdpTimes - expectedStarts ./ options.sample_rate_hz) ...
    <= options.time_tolerance_s) ...
    && all(abs(expectedTimes - expectedStarts ./ options.sample_rate_hz) ...
    <= 1e-8), ...
    'GNSS:SAGE:GateFWindowIdentityMismatch', ...
    'PDP rows do not preserve Stage0 window order, sample starts, and times.');
assert(all(isfinite(time)) && all(diff(time) >= 0) ...
    && all(isfinite(sampleStart)) && all(sampleStart >= 0) ...
    && all(sampleStart == floor(sampleStart)) ...
    && all(isfinite(rawIqRms)) && all(rawIqRms > 0) ...
    && all(isfinite(trackingDoppler)) && all(isfinite(codeFrequency)) ...
    && all(codeFrequency > 0) && all(isfinite(cn0)) ...
    && all(ismember(navSymbol, [-1, 1])) ...
    && all(isfinite(navTransition)) && all(navTransition >= 0) ...
    && all(navTransition < 10230) ...
    && all(navTransition == floor(navTransition)) ...
    && all(isfinite(pdpStored(:))) && all(pdpStored(:) >= 0) ...
    && all(pdpIntervals == options.snapshots_per_window), ...
    'GNSS:SAGE:GateFNonfiniteValue', ...
    'HDF5 contains nonfinite or invalid CIR/PDP axis values.');
assert(all(abs(time - sampleStart ./ options.sample_rate_hz) ...
    <= options.time_tolerance_s) ...
    && all(diff(sampleStart) >= 0), ...
    'GNSS:SAGE:GateFTimeAxisMismatch', ...
    'CIR time and sample axes are not aligned and monotone.');

% Map the interleaved, overlapping-window snapshots without loading the full
% complex CIR cube. Only 64x451 row blocks and one accumulated PDP per window
% are held in memory.
rowById = containers.Map('KeyType', 'double', 'ValueType', 'double');
for k = 1:nWindows
    rowById(expectedIds(k)) = k;
end
counts = zeros(nWindows, 1);
firstStart = nan(nWindows, 1);
firstTime = nan(nWindows, 1);
powerSum = zeros(nWindows, nDelays);
maxPdpRelativeDifference = 0;

for chunkStart = 1:options.chunk_rows:nSnapshots
    chunkCount = min(options.chunk_rows, nSnapshots - chunkStart + 1);
    cirReal = double(h5read(hdf5Path, '/cir_real', ...
        [chunkStart, 1], [chunkCount, nDelays]));
    cirImag = double(h5read(hdf5Path, '/cir_imag', ...
        [chunkStart, 1], [chunkCount, nDelays]));
    assert(all(isfinite(cirReal(:))) && all(isfinite(cirImag(:))), ...
        'GNSS:SAGE:GateFNonfiniteValue', ...
        'CIR real or imaginary component contains NaN/Inf.');
    % Match the frozen production per-snapshot operation. The independent
    % streaming sum can still differ from MATLAB mean() by roundoff.
    powerBlock = abs(complex(cirReal, cirImag)) .^ 2;
    for localRow = 1:chunkCount
        globalRow = chunkStart + localRow - 1;
        id = windowId(globalRow);
        assert(isKey(rowById, id), ...
            'GNSS:SAGE:GateFWindowIdentityMismatch', ...
            'A CIR snapshot references a window absent from Stage0.');
        windowRow = rowById(id);
        nextIndex = counts(windowRow) + 1;
        assert(snapshotIndex(globalRow) == nextIndex ...
            && nextIndex <= options.snapshots_per_window, ...
            'GNSS:SAGE:GateFSnapshotOrderMismatch', ...
            'A Stage0 window does not contain ordered snapshots 1 through 40.');
        if nextIndex == 1
            firstStart(windowRow) = sampleStart(globalRow);
            firstTime(windowRow) = time(globalRow);
        end
        assert(sampleStart(globalRow) == firstStart(windowRow) ...
            + (nextIndex - 1) * (options.sample_rate_hz / 1000) ...
            && abs(time(globalRow) - firstTime(windowRow) ...
            - (nextIndex - 1) / 1000) <= options.time_tolerance_s, ...
            'GNSS:SAGE:GateFTimeAxisMismatch', ...
            'Snapshots within a Stage0 window do not advance by one millisecond.');
        powerSum(windowRow, :) = powerSum(windowRow, :) ...
            + powerBlock(localRow, :);
        counts(windowRow) = nextIndex;
    end
end

assert(all(counts == options.snapshots_per_window), ...
    'GNSS:SAGE:GateFSnapshotOrderMismatch', ...
    'At least one Stage0 window lacks 40 CIR snapshots.');
assert(isequal(firstStart, expectedStarts) ...
    && all(abs(firstTime - expectedTimes) <= options.time_tolerance_s), ...
    'GNSS:SAGE:GateFWindowIdentityMismatch', ...
    'The first CIR snapshot start/time for a window does not match Stage0.');
recomputedPdp = powerSum ./ options.snapshots_per_window;
difference = abs(recomputedPdp - pdpStored);
tolerance = options.pdp_absolute_tolerance ...
    + options.pdp_relative_tolerance .* abs(pdpStored);
assert(all(difference(:) <= tolerance(:)), ...
    'GNSS:SAGE:GateFPdpMismatch', ...
    'Stored PDP differs from independent mean(|CIR|^2) recomputation.');
maxPdpDifference = max(difference(:));
windowMaxPdpDifference = max(difference, [], 2);
relativeMask = pdpStored > 0;
if any(relativeMask(:))
    maxPdpRelativeDifference = max( ...
        difference(relativeMask) ./ pdpStored(relativeMask));
end

totalPower = sum(recomputedPdp, 2);
peakPower = max(recomputedPdp, [], 2);
[~, peakIndex] = max(recomputedPdp, [], 2);
peakDelay = delay(peakIndex);
centroid = nan(nWindows, 1);
rmsWidth = nan(nWindows, 1);
negativeFraction = nan(nWindows, 1);
positivePower = totalPower > 0;
for k = find(positivePower).'
    centroid(k) = sum(recomputedPdp(k, :) .* delay.') / totalPower(k);
    rmsWidth(k) = sqrt(sum(recomputedPdp(k, :) ...
        .* (delay.' - centroid(k)).^2) / totalPower(k));
    negativeFraction(k) = sum(recomputedPdp(k, delay < 0)) / totalPower(k);
end

windowFeatures = table(expectedIds, (1:nWindows).', expectedStarts, ...
    expectedTimes, counts, firstStart, firstTime, ...
    windowMaxPdpDifference, totalPower, peakPower, ...
    peakDelay, centroid, rmsWidth, negativeFraction, ...
    peakIndex == 1 | peakIndex == nDelays, ...
    'VariableNames', {'window_id', 'pdp_row', ...
    'stage0_sample_start_zero_based', 'stage0_recording_time_s', ...
    'cir_snapshot_count', 'cir_first_sample_start_zero_based', ...
    'cir_first_time_s', 'pdp_abs_difference_max_by_window', ...
    'pdp_total_power_relative_units', 'pdp_peak_power_relative_units', ...
    'pdp_peak_code_delay_samples', 'pdp_centroid_code_delay_samples', ...
    'pdp_rms_width_code_delay_samples', ...
    'pdp_negative_delay_power_fraction', ...
    'pdp_peak_at_grid_boundary'});

result = struct();
result.status = 'PASS';
result.hdf5_path = char(hdf5Path);
result.snapshot_count = nSnapshots;
result.delay_count = nDelays;
result.window_count = nWindows;
result.delay_min_samples = min(delay);
result.delay_max_samples = max(delay);
result.snapshots_per_window = options.snapshots_per_window;
result.pdp_recomputation_pass = true;
result.max_abs_pdp_difference = maxPdpDifference;
result.max_relative_pdp_difference = maxPdpRelativeDifference;
result.pdp_absolute_tolerance = options.pdp_absolute_tolerance;
result.pdp_relative_tolerance = options.pdp_relative_tolerance;
result.time_monotone = all(diff(time) >= 0);
result.window_features = windowFeatures;
result.dataset_names = datasetNames;
result.chunk_rows = options.chunk_rows;
result.amplitude_reference_status = readOptionalAttribute( ...
    hdf5Path, 'amplitude_reference_status', 'NOT_RECORDED');
end

function options = applyDefaults(options, defaults)
names = fieldnames(defaults);
for k = 1:numel(names)
    if ~isfield(options, names{k}) || isempty(options.(names{k}))
        options.(names{k}) = defaults.(names{k});
    end
end
end

function dimensions = datasetDimensions(info, datasetName)
index = find(strcmp({info.Datasets.Name}, datasetName), 1);
assert(~isempty(index), 'GNSS:SAGE:GateFHdf5SchemaMismatch', ...
    'HDF5 dataset is missing: %s.', datasetName);
dimensions = double(info.Datasets(index).Dataspace.Size(:).');
end

function values = readVector(filename, datasetName, expectedCount)
values = h5read(filename, ['/', datasetName]);
values = values(:);
assert(numel(values) == expectedCount, ...
    'GNSS:SAGE:GateFDimensionsMismatch', ...
    'HDF5 vector %s has %d elements; expected %d.', ...
    datasetName, numel(values), expectedCount);
end

function value = readOptionalAttribute(filename, attributeName, fallback)
try
    value = h5readatt(filename, '/', attributeName);
catch
    value = fallback;
end
if isstring(value)
    value = char(value);
end
end
