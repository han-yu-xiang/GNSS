function outputTable = export_stage2_complex_alpha( ...
    stage2MatPath, selectedPathsCsvPath, outputCsvPath, provenance)
%EXPORT_STAGE2_COMPLEX_ALPHA Export selected Stage2 complex coefficients.
% One output row is retained for every Stage2 selected-path row. Missing or
% invalid alpha values are represented as NaN with an explicit reason; no
% Stage2 MPC row is silently dropped. This function reads the Stage2 MAT and
% should only be run after the source attempt is complete and immutable.

requiredProvenance = {'run_id', 'scene_id', 'prn', ...
    'tracking_channel', 'sample_rate_hz', 'frozen_sage_sha256', ...
    'stage2_mat_sha256', 'selected_paths_csv_sha256'};
assert(isstruct(provenance) && all(isfield(provenance, requiredProvenance)), ...
    'GNSS:SAGE:AlphaProvenanceMissing', ...
    'Required run provenance is incomplete.');
assert(strlength(string(provenance.run_id)) > 0 ...
    && strlength(string(provenance.scene_id)) > 0 ...
    && strlength(string(provenance.prn)) > 0 ...
    && isscalar(provenance.tracking_channel) ...
    && isfinite(double(provenance.tracking_channel)) ...
    && isscalar(provenance.sample_rate_hz) ...
    && isfinite(double(provenance.sample_rate_hz)) ...
    && double(provenance.sample_rate_hz) > 0, ...
    'GNSS:SAGE:AlphaProvenanceInvalid', ...
    'Run identity, channel, or sample-rate provenance is invalid.');
frozenSha = requiredSha256(provenance.frozen_sage_sha256, ...
    'frozen_sage_sha256');
stage2MatSha = requiredSha256(provenance.stage2_mat_sha256, ...
    'stage2_mat_sha256');
selectedPathsSha = requiredSha256( ...
    provenance.selected_paths_csv_sha256, 'selected_paths_csv_sha256');
assert(isfile(stage2MatPath) && isfile(selectedPathsCsvPath), ...
    'GNSS:SAGE:AlphaInputMissing', ...
    'Stage2 MAT and selected-path CSV inputs must exist.');
assert(~isfile(outputCsvPath), ...
    'GNSS:SAGE:AlphaOutputCollision', ...
    'Refusing to overwrite alpha output: %s', outputCsvPath);
outputFolder = fileparts(outputCsvPath);
if isempty(outputFolder)
    outputFolder = pwd;
end
assert(isfolder(outputFolder), 'GNSS:SAGE:AlphaOutputFolderMissing', ...
    'Alpha output directory does not exist: %s', outputFolder);

loaded = load(stage2MatPath, 'stage2Fits');
assert(isfield(loaded, 'stage2Fits') && iscell(loaded.stage2Fits), ...
    'GNSS:SAGE:Stage2FitsMissing', ...
    'The Stage2 MAT file does not contain a stage2Fits cell array.');
selectedPaths = readtable(selectedPathsCsvPath);
requiredColumns = {'window_id', 'selected_L', 'path_id', ...
    'relative_power_db'};
assert(all(ismember(requiredColumns, ...
    selectedPaths.Properties.VariableNames)), ...
    'GNSS:SAGE:SelectedPathSchemaMismatch', ...
    'Selected-path CSV lacks an identity or relative-power column.');
assert(height(selectedPaths) > 0, ...
    'GNSS:SAGE:SelectedPathTableEmpty', ...
    'Selected-path CSV contains no rows.');

windowId = double(selectedPaths.window_id);
selectedOrder = double(selectedPaths.selected_L);
pathId = double(selectedPaths.path_id);
assert(all(isfinite(windowId)) && all(windowId >= 0) ...
    && all(windowId == fix(windowId)) ...
    && all(isfinite(selectedOrder)) && all(selectedOrder >= 1) ...
    && all(selectedOrder == fix(selectedOrder)) ...
    && all(isfinite(pathId)) && all(pathId >= 1) ...
    && all(pathId == fix(pathId)) && all(pathId <= selectedOrder), ...
    'GNSS:SAGE:SelectedPathIdentityInvalid', ...
    'window_id, selected_L, and path_id must be valid integer identities.');
selectedKeys = [windowId, pathId];
assert(size(unique(selectedKeys, 'rows'), 1) == height(selectedPaths), ...
    'GNSS:SAGE:DuplicateSelectedPathIdentity', ...
    'Selected-path CSV contains duplicate (window_id,path_id) identities.');
uniqueWindowIds = unique(windowId, 'stable');
for groupIndex = 1:numel(uniqueWindowIds)
    rows = find(windowId == uniqueWindowIds(groupIndex));
    groupOrders = unique(selectedOrder(rows));
    groupPaths = sort(pathId(rows));
    assert(numel(groupOrders) == 1 ...
        && isequal(groupPaths(:), (1:groupOrders(1)).'), ...
        'GNSS:SAGE:SelectedPathSequenceInvalid', ...
        ['Selected-path rows for window_id=%g must contain exactly ' ...
        'path_id 1:selected_L with one selected_L value.'], ...
        uniqueWindowIds(groupIndex));
end

optionalIdentityColumns = {'run_id', 'scene_id', 'prn', ...
    'tracking_channel'};
expectedIdentity = {string(provenance.run_id), ...
    string(provenance.scene_id), string(provenance.prn), ...
    double(provenance.tracking_channel)};
for columnIndex = 1:numel(optionalIdentityColumns)
    columnName = optionalIdentityColumns{columnIndex};
    if ismember(columnName, selectedPaths.Properties.VariableNames)
        actual = string(selectedPaths.(columnName));
        assert(all(actual == expectedIdentity{columnIndex}), ...
            'GNSS:SAGE:SelectedPathProvenanceMismatch', ...
            'Selected-path CSV %s does not match supplied run provenance.', ...
            columnName);
    end
end

% Index fits by window once; a duplicate fit remains explicitly ambiguous.
fitIndicesByWindow = containers.Map('KeyType', 'char', ...
    'ValueType', 'any');
for fitIndex = 1:numel(loaded.stage2Fits)
    fit = loaded.stage2Fits{fitIndex};
    if ~isstruct(fit) || ~isfield(fit, 'windowId') ...
            || ~isscalar(fit.windowId) || ~isnumeric(fit.windowId) ...
            || ~isfinite(double(fit.windowId)) ...
            || double(fit.windowId) < 0 ...
            || double(fit.windowId) ~= fix(double(fit.windowId))
        continue;
    end
    key = windowKey(double(fit.windowId));
    if isKey(fitIndicesByWindow, key)
        fitIndicesByWindow(key) = [fitIndicesByWindow(key), fitIndex];
    else
        fitIndicesByWindow(key) = fitIndex;
    end
end

alpha = complex(nan(height(selectedPaths), 1), ...
    nan(height(selectedPaths), 1));
alphaStatus = repmat("MISSING", height(selectedPaths), 1);
alphaMissingReason = repmat("", height(selectedPaths), 1);
for rowIndex = 1:height(selectedPaths)
    key = windowKey(windowId(rowIndex));
    if ~isKey(fitIndicesByWindow, key)
        alphaMissingReason(rowIndex) = "NO_STAGE2_FIT_FOR_WINDOW";
        continue;
    end
    matchingFits = fitIndicesByWindow(key);
    if numel(matchingFits) ~= 1
        alphaMissingReason(rowIndex) = "AMBIGUOUS_STAGE2_FIT_FOR_WINDOW";
        continue;
    end
    fit = loaded.stage2Fits{matchingFits(1)};
    if ~isfield(fit, 'selectedOrder') || ~isscalar(fit.selectedOrder) ...
            || ~isnumeric(fit.selectedOrder) ...
            || ~isfinite(double(fit.selectedOrder))
        alphaMissingReason(rowIndex) = "SELECTED_ORDER_MISSING_OR_INVALID";
        continue;
    end
    if double(fit.selectedOrder) ~= selectedOrder(rowIndex)
        alphaMissingReason(rowIndex) = "SELECTED_ORDER_MISMATCH";
        continue;
    end
    order = selectedOrder(rowIndex);
    if ~isfield(fit, 'models') || ~iscell(fit.models) ...
            || numel(fit.models) < order || isempty(fit.models{order})
        alphaMissingReason(rowIndex) = "SELECTED_MODEL_MISSING";
        continue;
    end
    model = fit.models{order};
    if ~isstruct(model) || ~isfield(model, 'paths')
        alphaMissingReason(rowIndex) = "SELECTED_MODEL_PATHS_MISSING";
        continue;
    end
    if numel(model.paths) < pathId(rowIndex)
        alphaMissingReason(rowIndex) = "STAGE2_PATH_ID_MISSING";
        continue;
    end
    selectedPath = model.paths(pathId(rowIndex));
    if ~isstruct(selectedPath) || ~isfield(selectedPath, 'alpha')
        alphaMissingReason(rowIndex) = "ALPHA_FIELD_MISSING";
        continue;
    end
    candidate = selectedPath.alpha;
    if ~isnumeric(candidate) || ~isscalar(candidate) ...
            || ~isfinite(real(candidate)) || ~isfinite(imag(candidate))
        alphaMissingReason(rowIndex) = "ALPHA_NONFINITE_OR_INVALID";
        continue;
    end
    alpha(rowIndex) = candidate;
    alphaStatus(rowIndex) = "AVAILABLE";
    alphaMissingReason(rowIndex) = "NONE";
end

relativePowerCheckStatus = repmat( ...
    "NOT_CHECKED_ALPHA_MISSING", height(selectedPaths), 1);
for groupIndex = 1:numel(uniqueWindowIds)
    rows = find(windowId == uniqueWindowIds(groupIndex));
    directRow = rows(pathId(rows) == 1);
    assert(numel(directRow) == 1, ...
        'GNSS:SAGE:SelectedPathSequenceInvalid', ...
        'Each selected Stage2 window must contain exactly one direct path.');
    for rowPosition = 1:numel(rows)
        row = rows(rowPosition);
        if alphaStatus(row) ~= "AVAILABLE"
            relativePowerCheckStatus(row) = "NOT_CHECKED_ALPHA_MISSING";
        elseif alphaStatus(directRow) ~= "AVAILABLE"
            relativePowerCheckStatus(row) = ...
                "NOT_CHECKED_REFERENCE_ALPHA_MISSING";
        elseif ~isfinite(double(selectedPaths.relative_power_db(row)))
            relativePowerCheckStatus(row) = ...
                "NOT_CHECKED_RELATIVE_POWER_INVALID";
        else
            expectedDb = 10 * log10(max(abs(alpha(row))^2, realmin) ...
                / max(abs(alpha(directRow))^2, realmin));
            if abs(expectedDb - ...
                    double(selectedPaths.relative_power_db(row))) <= 1e-6
                relativePowerCheckStatus(row) = "PASS";
            else
                relativePowerCheckStatus(row) = "MISMATCH";
            end
        end
    end
end

outputTable = selectedPaths;
outputTable.run_id = repmat(string(provenance.run_id), ...
    height(outputTable), 1);
outputTable.scene_id = repmat(string(provenance.scene_id), ...
    height(outputTable), 1);
outputTable.prn = repmat(string(provenance.prn), height(outputTable), 1);
outputTable.tracking_channel = repmat(double(provenance.tracking_channel), ...
    height(outputTable), 1);
outputTable.sample_rate_hz = repmat(double(provenance.sample_rate_hz), ...
    height(outputTable), 1);
outputTable.frozen_sage_sha256 = repmat(frozenSha, ...
    height(outputTable), 1);
outputTable.stage2_mat_sha256 = repmat(stage2MatSha, ...
    height(outputTable), 1);
outputTable.selected_paths_csv_sha256 = repmat(selectedPathsSha, ...
    height(outputTable), 1);
outputTable.source_stage2_mat_path = repmat(string(stage2MatPath), ...
    height(outputTable), 1);
outputTable.source_selected_paths_csv_path = ...
    repmat(string(selectedPathsCsvPath), height(outputTable), 1);
outputTable.alpha_real = real(alpha);
outputTable.alpha_imag = imag(alpha);
outputTable.alpha_magnitude = abs(alpha);
outputTable.alpha_phase_rad = angle(alpha);
outputTable.alpha_status = alphaStatus;
outputTable.alpha_missing_reason = alphaMissingReason;
outputTable.relative_power_check_status = relativePowerCheckStatus;
outputTable.alpha_source = repmat(string( ...
    'stage2Fits.models{selectedOrder}.paths(path_id).alpha'), ...
    height(outputTable), 1);
outputTable.SAGE_ALPHA_IS_FROM_WINDOW_NORMALIZED_IQ = ...
    repmat("YES", height(outputTable), 1);

temporaryCsvPath = [tempname(outputFolder), '.csv'];
temporaryCleanup = onCleanup(@() deleteIfPresent(temporaryCsvPath)); %#ok<NASGU>
writetable(outputTable, temporaryCsvPath);
assert(~isfile(outputCsvPath), ...
    'GNSS:SAGE:AlphaOutputCollision', ...
    'Refusing to overwrite alpha output: %s', outputCsvPath);
[moved, message] = movefile(temporaryCsvPath, outputCsvPath);
assert(moved, 'GNSS:SAGE:AlphaPublishFailed', ...
    'Could not publish alpha CSV: %s', message);
end

function key = windowKey(windowId)
key = sprintf('%.0f', windowId);
end

function sha = requiredSha256(value, fieldName)
if isstring(value) && isscalar(value)
    shaText = char(value);
elseif ischar(value) && isrow(value)
    shaText = value;
else
    shaText = '';
end
assert(~isempty(regexp(lower(shaText), '^[0-9a-f]{64}$', 'once')), ...
    'GNSS:SAGE:AlphaProvenanceInvalid', ...
    '%s must contain exactly 64 hexadecimal characters.', fieldName);
sha = string(lower(shaText));
end

function deleteIfPresent(filePath)
if isfile(filePath)
    delete(filePath);
end
end
