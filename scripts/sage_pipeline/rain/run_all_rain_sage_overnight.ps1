function Assert-PreflightRow {
    param(
        [Parameter(Mandatory = $true)][object]$Task,
        [Parameter(Mandatory = $true)][object[]]$Rows
    )
    $matches = @($Rows | Where-Object {
        $_.scene -eq $Task.Scene -and $_.prn -eq $Task.PRN -and
        [int]$_.channel -eq [int]$Task.Channel
    })
    if ($matches.Count -ne 1) {
        throw "Expected exactly one static preflight row for $($Task.Scene)/$($Task.PRN)/ch$($Task.Channel); found $($matches.Count)."
    }
    $row = $matches[0]
    if ($row.preflight_pass -ne "PASS_STATIC_INPUT_GATE") {
        throw "Static preflight is not PASS_STATIC_INPUT_GATE for $($Task.Scene)/$($Task.PRN)."
    }
    foreach ($field in @("raw_ready", "tracking_ready", "telemetry_ready", "mapping_ready", "sample_rate_ready", "stage0_input_ready", "output_safe")) {
        if ([string]$row.$field -notin @("True", "true", "1")) {
            throw "Static preflight field $field is not true for $($Task.Scene)/$($Task.PRN)."
        }
    }
    return $row
}

