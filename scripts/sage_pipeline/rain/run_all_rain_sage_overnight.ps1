        [Parameter(Mandatory = $true)][object]$ProcessResult,
        [Parameter(Mandatory = $true)][string]$OutputDir,
        [Parameter(Mandatory = $true)][string]$Expression,
        [Parameter(Mandatory = $true)][string]$StdoutPath,
        [Parameter(Mandatory = $true)][string]$StderrPath,
        [Parameter(Mandatory = $true)][string]$Path
    )
    $record = [ordered]@{
        sequence = $Task.Sequence
        weather = $Task.Weather
        scene = $Task.Scene
        prn = $Task.PRN
        channel = $Task.Channel
        output_dir = $OutputDir
        matlab_exit_code = $ProcessResult.ExitCode
        start_utc = $ProcessResult.StartUtc
        end_utc = $ProcessResult.EndUtc
        stdout_path = $StdoutPath
        stderr_path = $StderrPath
        launch_error = $ProcessResult.LaunchError
        failure_reason = if ($ProcessResult.LaunchError) { $ProcessResult.LaunchError } else { "" }
        matlab_expression = $Expression
        production_sha256 = $script:ProductionHashBefore
        preflight_sha256 = $script:PreflightHashBefore
        raw_iq_opened_by_runner = $false
        gold_labels_used = $false
    }
    Write-NewJson -Path $Path -Value $record
    return $record
}

$globalStop = $false
$runResult = $null
$summaryResult = $null
try {
    if (-not (Test-Path -LiteralPath $ProjectRoot -PathType Container)) {
        throw "Project root is missing: $ProjectRoot"
    }
    if (-not (Test-Path -LiteralPath $MonitorRoot -PathType Container)) {
        New-Item -ItemType Directory -Path $MonitorRoot | Out-Null
    }
    $script:ProductionHashBefore = Assert-ProductionFrozen
    Assert-RainInterface
    if (-not (Test-Path -LiteralPath $PreflightCsv -PathType Leaf)) {
        throw "Static preflight CSV is missing: $PreflightCsv"
    }
    $script:PreflightHashBefore = Get-FileSha256 -Path $PreflightCsv
    $preflightRows = @(Import-Csv -LiteralPath $PreflightCsv)
    if ($preflightRows.Count -ne 9) {
        throw "Expected 9 static preflight rows, found $($preflightRows.Count)."
    }
    if (-not (Test-Path -LiteralPath $QaHelper -PathType Leaf)) {
        throw "QA helper is missing: $QaHelper"
    }
    $pythonCommand = Get-Command python.exe -ErrorAction Stop
    $script:PythonExecutable = if ($pythonCommand.Path) { $pythonCommand.Path } else { $pythonCommand.Source }
    if (-not (Test-Path -LiteralPath $script:PythonExecutable -PathType Leaf)) {
        throw "Resolved Python executable is not a file: $script:PythonExecutable"
    }
    & $script:PythonExecutable --version
    if ($LASTEXITCODE -ne 0) {
        throw "Python version check failed."
    }
    Acquire-GlobalRunnerMutex
    # Formal and dry-run modes share the complete pre-MATLAB initialization
    # path.  Dry-run stops only after this block and before Invoke-MatlabBatch.
    $script:RunDir = New-UniqueRunDirectory
    $script:MasterLog = Join-Path $script:RunDir "master.log"
    $summaryDirectory = Join-Path $script:RunDir "summary"
    New-Item -ItemType Directory -Path $summaryDirectory | Out-Null
    $script:QaCsvPath = Join-Path $summaryDirectory "rain_sage_execution_qa_20260818.csv"
    $script:ParametersCsvPath = Join-Path $summaryDirectory "rain_sage_darkroom_parameters_v1.csv"
    $script:QaReportPath = Join-Path $summaryDirectory "RAIN_SAGE_QA_REPORT_20260818.md"
    $script:MeetingReportPath = Join-Path $summaryDirectory "TOMORROW_MEETING_RAIN_SAGE_RESULTS.md"
    Write-NewTextFile -Path $script:MasterLog -Text ("Rain overnight runner started $(Get-Date -Format o)" + [Environment]::NewLine)
    New-Item -ItemType Directory -Path (Join-Path $script:RunDir "receipts") | Out-Null
    New-Item -ItemType Directory -Path (Join-Path $script:RunDir "task_logs") | Out-Null
    Write-NewJson -Path (Join-Path $script:RunDir "task_schedule.json") -Value $Tasks
    Test-ErrorDiagnosticsSafe
    Test-ProcessCaptureSafe
    $script:FormalInitializationComplete = $true
    Write-Log "FORMAL_INITIALIZATION_PATH=PASS"
    Write-Log "ERROR_DIAGNOSTICS_NEVER_THROWS=PASS"
    Write-Log "PRODUCTION_SHA_BEFORE=$script:ProductionHashBefore"
    Write-Log "PREFLIGHT_SHA256=$script:PreflightHashBefore"
    Write-Log "SUMMARY_NAMESPACE=$summaryDirectory"
    Write-Log "LEGACY_SUMMARY_ROOT_FILES_PRESERVED=YES"
    Write-Log "RAIN_MATLAB_SYNTAX_SMOKE=PASS (normal-user evidence; not rerun)"
    Write-Log "TASK_COUNT=$($Tasks.Count); EXECUTION_POLICY=SERIAL; RESUME=false; NEW_ONLY=true"
    if ($DryRun) {
        $plannedTasks = @()
        foreach ($task in $Tasks) {
            $currentHash = Assert-ProductionFrozen
            if ($currentHash -ne $script:ProductionHashBefore) {
                throw "Production SHA changed during dry-run."
            }
            if ((Get-FileSha256 -Path $PreflightCsv) -ne $script:PreflightHashBefore) {
                throw "Static preflight CSV changed during dry-run."
            }
            $row = Assert-PreflightRow -Task $task -Rows $preflightRows
            $outputDir = Assert-ExpectedOutputNamespace -Task $task -OutputDir ([string]$row.output_dir)
            if (Test-Path -LiteralPath $outputDir) {
                throw "Dry-run rejected: output namespace already exists: $outputDir"
            }
            $expression = New-MatlabExpression -Task $task
            $plannedTasks += [pscustomobject]@{
                Sequence = $task.Sequence
                Task = "$($task.Scene)/$($task.PRN)/ch$($task.Channel)"
                Output = $outputDir
                MatlabExpression = $expression
            }
        }
        $script:DryRunPlan = $plannedTasks
        Write-NewJson -Path (Join-Path $script:RunDir "dry_run_plan.json") -Value ([ordered]@{
                mode = "DRY_RUN_FORMAL_INITIALIZATION"
                formal_initialization_path = "PASS"
                matlab_started = $false
                raw_iq_opened = $false
                sage_executed = $false
                production_sha256 = $script:ProductionHashBefore
                preflight_sha256 = $script:PreflightHashBefore
                tasks = $plannedTasks
            })
        $afterDryRunHash = Assert-ProductionFrozen
        if ($afterDryRunHash -ne $script:ProductionHashBefore) {
            throw "Production SHA changed at dry-run completion."
        }
        Write-Output "OVERNIGHT_RUNNER_DRY_RUN=PASS"
        Write-Output "FORMAL_INITIALIZATION_PATH=PASS"
        Write-Output "FORMAL_PATH_RUNTIME_CHECK=PASS"
        Write-Output "ERROR_DIAGNOSTICS_NEVER_THROWS=PASS"
        Write-Output "TASK_OUTPUT_CAPTURE_NEVER_THROWS=PASS"
        Write-Output "MATLAB_STARTED=NO"
        Write-Output "RAW_IQ_OPENED=NO"
        Write-Output "SAGE_EXECUTED=NO"
        Write-Output "OUTPUT_SAGE_CREATED=NO"
        Write-Output "TASK_COUNT=$($plannedTasks.Count)"
        foreach ($planned in $plannedTasks) {
            Write-Output ("DRY_RUN_TASK={0} {1} OUTPUT={2}" -f $planned.Sequence, $planned.Task, $planned.Output)
            Write-Output ("DRY_RUN_MATLAB_EXPRESSION={0}" -f $planned.MatlabExpression)
        }
        exit 0
    }
    $executionIdentity = Assert-NormalUserExecutionIdentity
    Write-Log "EXECUTION_IDENTITY=$executionIdentity"

    foreach ($task in $Tasks) {
        if ($globalStop) { break }
        try {
            $currentHash = Assert-ProductionFrozen
            if ($currentHash -ne $script:ProductionHashBefore) {
                throw "Production SHA changed during overnight run."
            }
            if ((Get-FileSha256 -Path $PreflightCsv) -ne $script:PreflightHashBefore) {
                throw "Static preflight CSV changed during overnight run."
            }
            $row = Assert-PreflightRow -Task $task -Rows $preflightRows
            $outputDir = Assert-ExpectedOutputNamespace -Task $task -OutputDir ([string]$row.output_dir)
            $receiptPath = Join-Path $script:RunDir ("receipts\task_{0:D2}.json" -f $task.Sequence)
            if (Test-Path -LiteralPath $outputDir) {
                $blocked = New-FallbackReceipt -Task $task -OutputDir $outputDir -Status "INPUT_BLOCKED" -Reason "output_namespace_already_exists_new_only" -ReceiptPath $receiptPath
                Write-Log "TASK=$($task.Sequence) $($task.Scene)/$($task.PRN) INPUT_BLOCKED output exists; no MATLAB call."
                if ($task.Sequence -eq 1) { $globalStop = $true }
                continue
            }
            $expression = New-MatlabExpression -Task $task
            $stdoutPath = Join-Path $script:RunDir ("task_logs\{0}_{1}_stdout.log" -f $task.Weather, $task.PRN)
            $stderrPath = Join-Path $script:RunDir ("task_logs\{0}_{1}_stderr.log" -f $task.Weather, $task.PRN)
            Write-Log "TASK=$($task.Sequence) START $($task.Scene)/$($task.PRN)/ch$($task.Channel) output=$outputDir"
            Write-Log "TASK=$($task.Sequence) MATLAB_EXPRESSION=$expression"
            $processResult = Invoke-MatlabBatch -Expression $expression -StdoutPath $stdoutPath -StderrPath $stderrPath
            $taskRecordPath = Join-Path $script:RunDir ("task_logs\{0}_{1}_record.json" -f $task.Weather, $task.PRN)
            Write-TaskRecord -Task $task -ProcessResult $processResult -OutputDir $outputDir -Expression $expression -StdoutPath $stdoutPath -StderrPath $stderrPath -Path $taskRecordPath | Out-Null
            try {
                $qaReceipt = Invoke-QaHelper -TaskRecordPath $taskRecordPath -ReceiptPath $receiptPath
                Write-Log "TASK=$($task.Sequence) END status=$($qaReceipt.overall_status) exit=$($qaReceipt.matlab_exit_code) events=$($qaReceipt.confirmed_events) paths=$($qaReceipt.confirmed_multipath_paths)"
                if ($qaReceipt.overall_status -in @("SOFTWARE_FAIL", "INPUT_BLOCKED")) {
                    $script:ExitCode = 1
                }
                if ($task.Sequence -eq 1 -and $qaReceipt.overall_status -notin @("PASS_WITH_CONFIRMED_MULTIPATH", "PASS_NO_CONFIRMED_MULTIPATH")) {
                    Write-Log "GLOBAL_STOP: Clear G24 did not complete a valid Stage0-Stage4 run."
                    $globalStop = $true
                }
            }
            catch {
                Write-Log "TASK=$($task.Sequence) QA_HELPER_FAILURE=$($_.Exception.Message)"
                $script:ExitCode = 1
                if (-not (Test-Path -LiteralPath $receiptPath)) {
                    New-FallbackReceipt -Task $task -OutputDir $outputDir -Status "SOFTWARE_FAIL" -Reason "qa_helper_failure" -ReceiptPath $receiptPath -ExitCode $processResult.ExitCode | Out-Null
                }
                if ($task.Sequence -eq 1) { $globalStop = $true }
            }
            $afterTaskHash = Assert-ProductionFrozen
            if ($afterTaskHash -ne $script:ProductionHashBefore) {
                throw "Production SHA changed after task $($task.Sequence)."
            }
        }
        catch {
            Write-Log "TASK=$($task.Sequence) FAILURE=$($_.Exception.Message)"
            $script:ExitCode = 1
            $receiptPath = Join-Path $script:RunDir ("receipts\task_{0:D2}.json" -f $task.Sequence)
            $outputDir = Join-Path $ProjectRoot ("scenes\{0}\sage_results\rain_sage_v1\{1}" -f $task.Scene, $task.PRN)
            if (-not (Test-Path -LiteralPath $receiptPath)) {
                New-FallbackReceipt -Task $task -OutputDir $outputDir -Status "SOFTWARE_FAIL" -Reason $_.Exception.Message -ReceiptPath $receiptPath | Out-Null
            }
            if ($task.Sequence -eq 1) {
                $globalStop = $true
            }
        }
    }
}
catch {
    $globalStop = $true
    $script:ExitCode = 1
    Write-ErrorDiagnostics -ErrorRecord $_
    if ($null -ne $script:MasterLog) {
        Write-Log "RUNNER_FATAL=$($_.Exception.Message)"
    }
}
finally {
    if ($null -ne $script:RunDir) {
        $qaReport = $script:QaReportPath
        $meetingReport = $script:MeetingReportPath
        if ($DryRun) {
            Write-Log "DRY_RUN_SUMMARY_HELPER=NOT_RUN"
            Write-Log "DRY_RUN_OUTPUT_NAMESPACE=NO_SAGE_OUTPUT_CREATED"
        }
        else {
            try {
                $summaryOutput = @(& $script:PythonExecutable $QaHelper --summarize --run-dir $script:RunDir --qa-csv $script:QaCsvPath --parameters-csv $script:ParametersCsvPath --report $qaReport --meeting-report $meetingReport 2>&1)
                foreach ($line in $summaryOutput) { Write-Log ("SUMMARY_HELPER " + [string]$line) }
                if ($LASTEXITCODE -ne 0) { Write-Log "SUMMARY_HELPER_EXIT=$LASTEXITCODE" }
            }
            catch {
                Write-Log "SUMMARY_FAILURE=$($_.Exception.Message)"
                $script:ExitCode = 1
            }
        }
        $productionAfter = "UNAVAILABLE"
        $productionDiff = "UNAVAILABLE"
        try {
            $productionAfter = Get-FileSha256 -Path $ProductionEntry
            $productionDiff = (@(& git -C $ProjectRoot diff -- $ProductionEntry) -join [Environment]::NewLine)
        }
        catch {
            Write-Log "PRODUCTION_POSTCHECK_FAILURE=$($_.Exception.Message)"
        }
        $unchanged = ($productionAfter -eq $script:ProductionHashBefore -and [string]::IsNullOrWhiteSpace($productionDiff))
        $unchangedText = if ($unchanged) { "YES" } else { "NO" }
        $terminalStatus = if ($globalStop) { "GLOBAL_SOFTWARE_FAILURE_OR_STOP" } else { "SEQUENTIAL_RUN_FINISHED" }
        Write-Log "PRODUCTION_SHA_AFTER=$productionAfter"
        Write-Log "PRODUCTION_UNCHANGED=$unchangedText"
        Write-Log "FILES_DELETED_COUNT=0"
        Write-Log "FILES_MOVED_TO_TRASH=0"
        Write-Log "TRASH_DIRECTORY_PRESERVED=YES"
        Write-Log "NO_DELETE_POLICY_VIOLATION=YES"
        Write-Log "RUN_STATUS=$terminalStatus"
        Write-Output "RUNNER_PATH=$PSCommandPath"
        Write-Output "RUNNER_LOG_DIRECTORY=$script:RunDir"
        Write-Output "QA_REPORT_PATH=$qaReport"
        Write-Output "MEETING_REPORT_PATH=$meetingReport"
        Write-Output "PRODUCTION_SHA_BEFORE=$script:ProductionHashBefore"
        Write-Output "PRODUCTION_SHA_AFTER=$productionAfter"
        Write-Output "PRODUCTION_UNCHANGED=$unchangedText"
        if ($DryRun) {
            Write-Output "FORMAL_INITIALIZATION_PATH=PASS"
            Write-Output "FORMAL_PATH_RUNTIME_CHECK=PASS"
            Write-Output "TASK_OUTPUT_CAPTURE_NEVER_THROWS=PASS"
            Write-Output "MATLAB_STARTED=NO"
            Write-Output "RAW_IQ_OPENED=NO"
            Write-Output "SAGE_EXECUTED=NO"
        }
        Write-Output "FILES_DELETED_COUNT=0"
        Write-Output "FILES_MOVED_TO_TRASH=0"
        Write-Output "TRASH_DIRECTORY_PRESERVED=YES"
        Write-Output "NO_DELETE_POLICY_VIOLATION=YES"
    }
    if ($script:MutexAcquired) {
        $script:GlobalMutex.ReleaseMutex()
        $script:GlobalMutex.Dispose()
        $script:MutexAcquired = $false
        Write-Output "GLOBAL_MUTEX_RELEASED=YES"
    }
}

if ($script:ExitCode -ne 0) {
    exit $script:ExitCode
}
