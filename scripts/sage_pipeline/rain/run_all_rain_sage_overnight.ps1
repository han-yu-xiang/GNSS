function ConvertTo-SafeDiagnosticText {
    param([Parameter(Mandatory = $false)][AllowNull()][object]$Value)
    try {
        if ($null -eq $Value) {
            return ""
        }
        $text = [string]$Value
        return ($text -replace "[\r\n]+", " | ")
    }
    catch {
        return "<unprintable>"
    }
}

function Get-ErrorDiagnosticLines {
    param([Parameter(Mandatory = $false)][AllowNull()][object]$ErrorRecord)
    try {
        $invocation = $null
        $message = ""
        $stack = ""
        $errorId = ""
        $command = ""
        $lineNumber = ""
        $lineText = ""
        $position = ""
        if ($null -ne $ErrorRecord) {
            $invocation = $ErrorRecord.InvocationInfo
            if ($null -ne $ErrorRecord.Exception) {
                $message = ConvertTo-SafeDiagnosticText -Value $ErrorRecord.Exception.Message
            }
            $stack = ConvertTo-SafeDiagnosticText -Value $ErrorRecord.ScriptStackTrace
            $errorId = ConvertTo-SafeDiagnosticText -Value $ErrorRecord.FullyQualifiedErrorId
            if ($null -ne $invocation) {
                if ($null -ne $invocation.MyCommand) {
                    $command = ConvertTo-SafeDiagnosticText -Value $invocation.MyCommand.Name
                }
                $lineNumber = ConvertTo-SafeDiagnosticText -Value $invocation.ScriptLineNumber
                $lineText = ConvertTo-SafeDiagnosticText -Value $invocation.Line
                $position = ConvertTo-SafeDiagnosticText -Value $invocation.PositionMessage
            }
            if ([string]::IsNullOrWhiteSpace($command)) {
                $command = ConvertTo-SafeDiagnosticText -Value $ErrorRecord.CategoryInfo.Activity
            }
        }
        return @(
            "ERROR_MESSAGE=$message",
            "ERROR_COMMAND=$command",
            "ERROR_LINE=$lineText",
            "ERROR_LINE_NUMBER=$lineNumber",
            "ERROR_POSITION=$position",
            "ERROR_SCRIPT_STACK_TRACE=$stack",
            "FULLY_QUALIFIED_ERROR_ID=$errorId",
            "POWERSHELL_VERSION=$(ConvertTo-SafeDiagnosticText -Value $PSVersionTable.PSVersion)"
        )
    }
    catch {
        $fallback = "ERROR_DIAGNOSTICS_INTERNAL_FAILURE=$(ConvertTo-SafeDiagnosticText -Value $_.Exception.Message)"
        return @($fallback)
    }
}

function Write-ErrorDiagnostics {
    param(
        [Parameter(Mandatory = $false)][AllowNull()][object]$ErrorRecord,
        [Parameter(Mandatory = $false)][AllowNull()][System.IO.TextWriter]$Writer
    )
    try {
        $diagnosticLines = @(Get-ErrorDiagnosticLines -ErrorRecord $ErrorRecord)
    }
    catch {
        $diagnosticLines = @("ERROR_DIAGNOSTICS_INTERNAL_FAILURE=diagnostic line construction failed")
    }
    foreach ($diagnosticLine in $diagnosticLines) {
        $safeLine = ConvertTo-SafeDiagnosticText -Value $diagnosticLine
        try {
            if ($null -ne $Writer) {
                # Pass one completed string so braces, percent signs, and
                # quotes in error text can never become a format string.
                $Writer.WriteLine([string]$safeLine)
            }
            else {
                [Console]::Error.WriteLine([string]$safeLine)
            }
        }
        catch {
            try {
                [Console]::Error.WriteLine([string]("ERROR_DIAGNOSTICS_FALLBACK=" + $safeLine))
            }
            catch {
                try { Write-Host ([string]("ERROR_DIAGNOSTICS_FALLBACK=" + $safeLine)) } catch { }
            }
        }
    }
}

function Test-ErrorDiagnosticsSafe {
    $messages = @(
        "ordinary exception",
        "format token {0} and empty braces {}",
        "中文错误文本",
        "multi-line`nerror",
        'percent 100% and quoted ''text'' "text"'
    )
    foreach ($message in $messages) {
        $writer = New-Object System.IO.StringWriter
        try {
            $exception = [System.Exception]::new($message)
            $record = [System.Management.Automation.ErrorRecord]::new(
                $exception,
                "SyntheticDiagnostics",
                [System.Management.Automation.ErrorCategory]::NotSpecified,
                $null)
            Write-ErrorDiagnostics -ErrorRecord $record -Writer $writer
            if ([string]::IsNullOrWhiteSpace($writer.ToString())) {
                throw "Diagnostics writer produced no output."
            }
        }
        finally {
            $writer.Dispose()
        }
    }
    $nullWriter = New-Object System.IO.StringWriter
    try {
        Write-ErrorDiagnostics -ErrorRecord $null -Writer $nullWriter
        if ([string]::IsNullOrWhiteSpace($nullWriter.ToString())) {
            throw "Null ErrorRecord diagnostics produced no output."
        }
    }
    finally {
        $nullWriter.Dispose()
    }
}

function Invoke-CapturedProcess {
    param(
        [Parameter(Mandatory = $true)][string]$FilePath,
        [Parameter(Mandatory = $true)][AllowEmptyString()][AllowNull()][string]$Arguments,
        [Parameter(Mandatory = $true)][string]$StdoutPath,
        [Parameter(Mandatory = $true)][string]$StderrPath,
        [Parameter(Mandatory = $true)][string]$WorkingDirectory
    )
    $start = (Get-Date).ToUniversalTime()
    $stdout = ""
    $stderr = ""
    $exitCode = $null
    $launchError = ""
    $process = $null
    try {
        $info = [System.Diagnostics.ProcessStartInfo]::new()
        $info.FileName = $FilePath
        $info.Arguments = if ($null -eq $Arguments) { "" } else { [string]$Arguments }
        $info.WorkingDirectory = $WorkingDirectory
        $info.UseShellExecute = $false
        $info.CreateNoWindow = $true
        $info.RedirectStandardOutput = $true
        $info.RedirectStandardError = $true
        Write-Log "PROCESS_START file=$FilePath"
        $process = [System.Diagnostics.Process]::new()
        $process.StartInfo = $info
        if (-not $process.Start()) {
            throw "External process did not start: $FilePath"
        }
        $stdoutTask = $process.StandardOutput.ReadToEndAsync()
        $stderrTask = $process.StandardError.ReadToEndAsync()
        $process.WaitForExit()
        $stdout = $stdoutTask.GetAwaiter().GetResult()
        $stderr = $stderrTask.GetAwaiter().GetResult()
        $exitCode = $process.ExitCode
        Write-Log "PROCESS_EXIT file=$FilePath exit=$exitCode"
    }
    catch {
        $launchError = [string]$_.Exception.Message
        $stderr = $launchError
        Write-Log "PROCESS_CAPTURE_FAILURE file=$FilePath error=$launchError"
    }
    finally {
        if ($null -ne $process) {
            $process.Dispose()
        }
    }
    if ($null -eq $stdout) { $stdout = "" }
    if ($null -eq $stderr) { $stderr = "" }
    Write-NewTextFile -Path $StdoutPath -Text $stdout
    Write-NewTextFile -Path $StderrPath -Text $stderr
    return [pscustomobject]@{
        StartUtc = $start.ToString("o")
        EndUtc = (Get-Date).ToUniversalTime().ToString("o")
        ExitCode = $exitCode
        LaunchError = $launchError
    }
}

function Test-ProcessCaptureSafe {
    $captureDirectory = Join-Path $script:RunDir "capture_self_test"
    New-Item -ItemType Directory -Path $captureDirectory | Out-Null
    $powershellCommand = Get-Command powershell.exe -ErrorAction Stop
    $powershellPath = if ($powershellCommand.Path) { $powershellCommand.Path } else { $powershellCommand.Source }
    if (-not (Test-Path -LiteralPath $powershellPath -PathType Leaf)) {
        throw "PowerShell test executable is missing: $powershellPath"
    }
    $richStdout = Join-Path $captureDirectory "rich_stdout.log"
    $richStderr = Join-Path $captureDirectory "rich_stderr.log"
    $richCommand = "& { Write-Output 'capture normal {0} % 中文'; Write-Output 'capture line 2'; [Console]::Error.Write('capture stderr {} 100% 中文') }"
    $richArguments = '-NoProfile -NonInteractive -Command "' + $richCommand + '"'
    $richResult = Invoke-CapturedProcess -FilePath $powershellPath -Arguments $richArguments -StdoutPath $richStdout -StderrPath $richStderr -WorkingDirectory $ProjectRoot
    if ($richResult.ExitCode -ne 0) {
        throw "Capture self-test rich process failed with exit code $($richResult.ExitCode): $($richResult.LaunchError)"
    }
    $richOutText = [System.IO.File]::ReadAllText($richStdout)
    $richErrText = [System.IO.File]::ReadAllText($richStderr)
    if ($richOutText -notmatch "capture normal" -or $richOutText -notmatch "capture line 2") {
        throw "Capture self-test did not preserve normal/multiline stdout."
    }
    if ($richErrText -notmatch "capture stderr") {
        throw "Capture self-test did not preserve stderr."
    }
    $emptyStdout = Join-Path $captureDirectory "empty_stdout.log"
    $emptyStderr = Join-Path $captureDirectory "empty_stderr.log"
    $emptyResult = Invoke-CapturedProcess -FilePath $powershellPath -Arguments '-NoProfile -NonInteractive -Command "exit 0"' -StdoutPath $emptyStdout -StderrPath $emptyStderr -WorkingDirectory $ProjectRoot
    if ($emptyResult.ExitCode -ne 0) {
        throw "Capture self-test empty process failed with exit code $($emptyResult.ExitCode): $($emptyResult.LaunchError)"
    }
    if ([System.IO.File]::ReadAllText($emptyStdout) -ne "" -or [System.IO.File]::ReadAllText($emptyStderr) -ne "") {
        throw "Capture self-test empty process produced unexpected output."
    }
    Write-Log "TASK_OUTPUT_CAPTURE_NEVER_THROWS=PASS"
}

