function Assert-NormalUserExecutionIdentity {
    $windowsIdentity = [System.Security.Principal.WindowsIdentity]::GetCurrent()
    $identity = $windowsIdentity.Name
    if ($identity -match "(?i)codexsandboxoffline") {
        throw "Formal Rain execution is blocked under Codex sandbox identity: $identity. Run from TJ-CHANNEL\Jing_ non-administrator PowerShell."
    }
    if ($identity -notmatch "(?i)^TJ-CHANNEL\\Jing_$") {
        throw "Formal Rain execution requires TJ-CHANNEL\Jing_; actual identity is $identity"
    }
    $principal = [System.Security.Principal.WindowsPrincipal]::new($windowsIdentity)
    if ($principal.IsInRole([System.Security.Principal.WindowsBuiltInRole]::Administrator)) {
        throw "Formal Rain execution must not run from an elevated Administrator shell."
    }
    return $identity
}

function Assert-ProductionFrozen {
    if (-not (Test-Path -LiteralPath $ProductionEntry -PathType Leaf)) {
        throw "Production entry is missing: $ProductionEntry"
    }
    if (-not (Test-Path -LiteralPath $ProductionFreeze -PathType Leaf)) {
        throw "Production freeze record is missing: $ProductionFreeze"
    }
    $hash = Get-FileSha256 -Path $ProductionEntry
    if ($hash -ne $ExpectedProductionHash) {
        throw "Production SHA mismatch: expected $ExpectedProductionHash, actual $hash"
    }
    $freezeText = [System.IO.File]::ReadAllText($ProductionFreeze)
    if ($freezeText -notmatch "PRODUCTION_PIPELINE_FROZEN\s*[:=]\s*YES" -and
        $freezeText -notmatch "PRODUCTION_PIPELINE_FROZEN=YES") {
        throw "Production freeze record does not assert PRODUCTION_PIPELINE_FROZEN=YES"
    }
    $tags = @(& git -C $ProjectRoot tag --list $ExpectedFreezeTag)
    if ($tags -notcontains $ExpectedFreezeTag) {
        throw "Required production freeze tag is missing: $ExpectedFreezeTag"
    }
    $diff = @(& git -C $ProjectRoot diff -- $ProductionEntry)
    if ($diff.Count -ne 0) {
        throw "Production entry has an uncommitted diff."
    }
    return $hash
}

