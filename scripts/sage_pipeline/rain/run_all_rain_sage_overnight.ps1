function Write-NewTextFile {
    param(
        [Parameter(Mandatory = $true)][string]$Path,
        [Parameter(Mandatory = $true)][AllowEmptyString()][AllowNull()][string]$Text
    )
    if ($null -eq $Text) {
        $Text = ""
    }
    $parent = Split-Path -Parent $Path
    if (-not (Test-Path -LiteralPath $parent -PathType Container)) {
        # Windows PowerShell 5.1 New-Item has -Path but not -LiteralPath.
        # These parents are generated by the runner and contain no wildcard
        # characters; all untrusted/input path checks remain LiteralPath-based.
        New-Item -ItemType Directory -Path $parent | Out-Null
    }
    $stream = [System.IO.File]::Open(
        $Path,
        [System.IO.FileMode]::CreateNew,
        [System.IO.FileAccess]::Write,
        [System.IO.FileShare]::None)
    $writer = $null
    try {
        $writer = [System.IO.StreamWriter]::new(
            $stream,
            [System.Text.UTF8Encoding]::new($false))
        $writer.Write($Text)
        $writer.Flush()
    }
    finally {
        if ($null -ne $writer) {
            $writer.Dispose()
        }
        else {
            $stream.Dispose()
        }
    }
}

