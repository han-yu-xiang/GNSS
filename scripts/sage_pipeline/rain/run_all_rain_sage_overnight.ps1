function Get-FileSha256 {
    param([Parameter(Mandatory = $true)][string]$Path)
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToUpperInvariant()
}

function Get-CanonicalPath {
    param([Parameter(Mandatory = $true)][string]$Path)
    $full = [System.IO.Path]::GetFullPath($Path)
    return $full.TrimEnd([char[]]@('\', '/'))
}

function Test-PathWithin {
    param(
        [Parameter(Mandatory = $true)][string]$Candidate,
        [Parameter(Mandatory = $true)][string]$Root
    )
    $candidateFull = Get-CanonicalPath -Path $Candidate
    $rootFull = Get-CanonicalPath -Path $Root
    if ($candidateFull.Equals($rootFull, [System.StringComparison]::OrdinalIgnoreCase)) {
        return $true
    }
    return $candidateFull.StartsWith(
        $rootFull + [System.IO.Path]::DirectorySeparatorChar,
        [System.StringComparison]::OrdinalIgnoreCase)
}

function New-UniqueRunDirectory {
    $stamp = (Get-Date).ToUniversalTime().ToString("yyyyMMddTHHmmssZ")
    for ($index = 0; $index -lt 100; $index++) {
        $suffix = if ($index -eq 0) { "" } else { "_" + $index.ToString("D2") }
        $candidate = Join-Path $MonitorRoot ("rain_sage_overnight_{0}{1}" -f $stamp, $suffix)
        if (Test-Path -LiteralPath $candidate) {
            continue
        }
        try {
            # New-Item -LiteralPath is not available in Windows PowerShell 5.1.
            New-Item -ItemType Directory -Path $candidate | Out-Null
            return $candidate
        }
        catch {
            if (Test-Path -LiteralPath $candidate) {
                continue
            }
            throw
        }
    }
    throw "Unable to create a unique Rain overnight log namespace."
}

