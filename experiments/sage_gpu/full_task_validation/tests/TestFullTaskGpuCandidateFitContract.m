function tests = TestFullTaskGpuCandidateFitContract
tests = functiontests(localfunctions);
end

function testCompleteCpuOnlyFrozenFitIsAccepted(testCase)
fit = makeSyntheticCpuFit();
valid = assertCpuResidentFrozenFit(fit);
verifyTrue(testCase, valid);
verifyEqual(testCase, fieldnames(fit), ...
    {'windowId'; 'catalogIndex'; 'recordingTimeS'; 'towS'; 'models'; 'selectedOrder'; 'errorMessage'});
verifyEqual(testCase, numel(fit.models), 4);
end

function testNestedGpuArrayIsRejectedBeforeCheckpoint(testCase)
fit = makeSyntheticCpuFit();
fit.models{2}.paths(1).alpha = gpuArray(complex(1.25, -0.75));
verifyError(testCase, @() assertCpuResidentFrozenFit(fit), ...
    'FullTaskGpuCandidate:NO_GPUARRAY_IN_RETURNED_FIT');
end

function testMissingFrozenFitFieldIsRejected(testCase)
fit = makeSyntheticCpuFit();
fit = rmfield(fit, 'catalogIndex');
verifyError(testCase, @() assertCpuResidentFrozenFit(fit), ...
    'FullTaskGpuCandidate:INVALID_FROZEN_FIT_CONTRACT');
end

function fit = makeSyntheticCpuFit()
models = cell(4, 1);
for order = 1:4
    paths = repmat(struct( ...
        'delaySamples', 0.0, ...
        'dopplerHz', 0.0, ...
        'alpha', complex(0.0, 0.0), ...
        'score', 0.0), 1, order);
    for pathIndex = 1:order
        paths(pathIndex).delaySamples = double(5 + 2 * pathIndex);
        paths(pathIndex).dopplerHz = double(-13.5 + 3 * pathIndex);
        paths(pathIndex).alpha = complex(double(0.8 / pathIndex), double(-0.1 * pathIndex));
        paths(pathIndex).score = double(2.0 / pathIndex);
    end

    models{order} = struct( ...
        'order', double(order), ...
        'paths', paths, ...
        'rss', double(10 / order), ...
        'bic', double(100 - order), ...
        'valid', logical(true), ...
        'relativePowerDb', double(-3 * (0:order - 1)), ...
        'minimumSeparationSamples', double(2), ...
        'minimumMultipathPowerDb', double(-12), ...
        'maximumRelativeDopplerHz', double(20), ...
        'maximumCoherence', double(0.1), ...
        'rssHistory', double([10 / order, 5 / order]));
end

fit = struct( ...
    'windowId', double(17), ...
    'catalogIndex', double(17), ...
    'recordingTimeS', double(600.232764516129), ...
    'towS', double(345600.2327645161), ...
    'models', {models}, ...
    'selectedOrder', double(3), ...
    'errorMessage', "");
end
