function replay = replayFrozenSequentialModelSelection( ...
    models, maximumModelOrder, minimumSequentialBicGain, ...
    minimumIncrementalRssPercent)
% Replay the Frozen Stage2 order-by-order decision for comparison evidence.

if ~iscell(models) || numel(models) ~= 4
    error('FullTaskGpuCandidate:INVALID_MODEL_COLLECTION', ...
        'Expected the complete L=1..4 model cell array.');
end
if ~isnumeric(maximumModelOrder) || ~isscalar(maximumModelOrder) || ...
        ~isfinite(maximumModelOrder) || maximumModelOrder < 1 || ...
        maximumModelOrder > 4 || fix(maximumModelOrder) ~= maximumModelOrder
    error('FullTaskGpuCandidate:INVALID_MAXIMUM_MODEL_ORDER', ...
        'maximumModelOrder must be an integer from 1 through 4.');
end
if ~isnumeric(minimumSequentialBicGain) || ...
        ~isscalar(minimumSequentialBicGain) || ...
        ~isfinite(minimumSequentialBicGain) || ...
        ~isnumeric(minimumIncrementalRssPercent) || ...
        ~isscalar(minimumIncrementalRssPercent) || ...
        ~isfinite(minimumIncrementalRssPercent)
    error('FullTaskGpuCandidate:INVALID_SEQUENTIAL_THRESHOLD', ...
        'Frozen sequential-selection thresholds must be finite numeric scalars.');
end

transitionTemplate = struct( ...
    'FromL', NaN, ...
    'ToL', NaN, ...
    'Checked', false, ...
    'CurrentModelValid', false, ...
    'BicGain', NaN, ...
    'BicThreshold', NaN, ...
    'BicSurplus', NaN, ...
    'RssGainPercent', NaN, ...
    'RssThreshold', NaN, ...
    'RssSurplus', NaN, ...
    'Accepted', false);
transitions = repmat(transitionTemplate, 1, 3);

selectedOrder = 1;
for order = 2:double(maximumModelOrder)
    previous = models{selectedOrder};
    current = models{order};
    requiredModelFields = {'valid', 'bic', 'rss'};
    if ~isstruct(previous) || ~isscalar(previous) || ...
            ~all(isfield(previous, requiredModelFields)) || ...
            ~isstruct(current) || ~isscalar(current) || ...
            ~all(isfield(current, requiredModelFields)) || ...
            ~islogical(current.valid) || ~isscalar(current.valid) || ...
            ~isnumeric(previous.bic) || ~isscalar(previous.bic) || ...
            ~isnumeric(current.bic) || ~isscalar(current.bic) || ...
            ~isnumeric(previous.rss) || ~isscalar(previous.rss) || ...
            ~isnumeric(current.rss) || ~isscalar(current.rss)
        error('FullTaskGpuCandidate:INVALID_SEQUENTIAL_MODEL', ...
            'Model data are incomplete or have invalid scalar types.');
    end

    bicGain = double(previous.bic) - double(current.bic);
    rssGainPercent = 100 * (double(previous.rss) - double(current.rss)) ...
        / max(double(previous.rss), eps);
    bicThreshold = double(minimumSequentialBicGain);
    rssThreshold = double(minimumIncrementalRssPercent);
    accepted = current.valid ...
        && bicGain >= bicThreshold ...
        && rssGainPercent >= rssThreshold;

    transitions(order - 1) = struct( ...
        'FromL', selectedOrder, ...
        'ToL', order, ...
        'Checked', true, ...
        'CurrentModelValid', current.valid, ...
        'BicGain', bicGain, ...
        'BicThreshold', bicThreshold, ...
        'BicSurplus', bicGain - bicThreshold, ...
        'RssGainPercent', rssGainPercent, ...
        'RssThreshold', rssThreshold, ...
        'RssSurplus', rssGainPercent - rssThreshold, ...
        'Accepted', accepted);
    if accepted
        selectedOrder = order;
    else
        break;
    end
end

replay = struct('SelectedOrder', selectedOrder, ...
    'Transitions', transitions);
end
