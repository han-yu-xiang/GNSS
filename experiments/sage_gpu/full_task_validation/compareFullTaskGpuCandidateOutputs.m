function [rows, aggregate] = compareStage2FitCollections( ...
    referenceFits, candidateFits, aggregate, referenceCfg, candidateCfg)
if ~iscell(referenceFits) || ~iscell(candidateFits) || ...
        numel(referenceFits) ~= numel(candidateFits)
    comparisonFailure('STAGE2_FIT_COLLECTION_SHAPE_MISMATCH');
end
selectionCfgFields = {'maximumModelOrder', ...
    'minimumSequentialBicGain', 'minimumIncrementalRssPercent'};
validateFields(referenceCfg, selectionCfgFields, 'STAGE2_REFERENCE_SELECTION_CFG');
validateFields(candidateCfg, selectionCfgFields, 'STAGE2_CANDIDATE_SELECTION_CFG');
rows = {};
for fitIndex = 1:numel(referenceFits)
    referenceFit = referenceFits{fitIndex};
    candidateFit = candidateFits{fitIndex};
    if isempty(referenceFit) || isempty(candidateFit)
        if ~isempty(referenceFit) || ~isempty(candidateFit)
            comparisonFailure('STAGE2_FIT_PRESENCE_MISMATCH');
        end
        continue;
    end
    fitIdentityFields = {'windowId','catalogIndex','recordingTimeS','towS', ...
        'errorMessage'};
    validateFields(referenceFit, fitIdentityFields, 'STAGE2_REFERENCE_FIT');
    validateFields(candidateFit, fitIdentityFields, 'STAGE2_CANDIDATE_FIT');
    for fieldIndex = 1:numel(fitIdentityFields)
        field = fitIdentityFields{fieldIndex};
        if ~isequaln(referenceFit.(field), candidateFit.(field))
            comparisonFailure(['STAGE2_FIT_IDENTITY_MISMATCH_' upper(field)]);
        end
    end
    if ~isnumeric(referenceFit.selectedOrder) || ...
            ~isscalar(referenceFit.selectedOrder) || ...
            referenceFit.selectedOrder < 1 || referenceFit.selectedOrder > 4 || ...
            fix(referenceFit.selectedOrder) ~= referenceFit.selectedOrder || ...
            ~isnumeric(candidateFit.selectedOrder) || ...
            ~isscalar(candidateFit.selectedOrder) || ...
            candidateFit.selectedOrder < 1 || candidateFit.selectedOrder > 4 || ...
            fix(candidateFit.selectedOrder) ~= candidateFit.selectedOrder
        comparisonFailure('STAGE2_SELECTED_MODEL_ORDER_OUT_OF_RANGE');
    end
    if ~iscell(referenceFit.models) || ~iscell(candidateFit.models) || ...
            numel(referenceFit.models) ~= 4 || numel(candidateFit.models) ~= 4
        comparisonFailure('STAGE2_MODEL_ORDER_COLLECTION_MISMATCH');
    end
    cpuReplay = replayFrozenSequentialModelSelection( ...
        referenceFit.models, referenceCfg.maximumModelOrder, ...
        referenceCfg.minimumSequentialBicGain, ...
        referenceCfg.minimumIncrementalRssPercent);
    gpuReplay = replayFrozenSequentialModelSelection( ...
        candidateFit.models, candidateCfg.maximumModelOrder, ...
        candidateCfg.minimumSequentialBicGain, ...
        candidateCfg.minimumIncrementalRssPercent);
    if cpuReplay.SelectedOrder ~= referenceFit.selectedOrder
        comparisonFailure('CPU_SELECTION_REPLAY_MISMATCH');
    end
    if gpuReplay.SelectedOrder ~= candidateFit.selectedOrder
        comparisonFailure('GPU_SELECTION_REPLAY_MISMATCH');
    end
    if referenceFit.selectedOrder ~= candidateFit.selectedOrder
        comparisonFailure('STAGE2_SELECTED_MODEL_ORDER_MISMATCH');
    end
    oneWindow = emptyNumericDiffs();
    cpuValidity = false(1, 4);
    gpuValidity = false(1, 4);
    for order = 1:4
        referenceModel = referenceFit.models{order};
        candidateModel = candidateFit.models{order};
        validateFields(referenceModel, {'order','paths','rss','bic', ...
            'valid','relativePowerDb'}, 'STAGE2_REFERENCE_MODEL');
        validateFields(candidateModel, {'order','paths','rss','bic', ...
            'valid','relativePowerDb'}, 'STAGE2_CANDIDATE_MODEL');
        referencePathCount = numel(referenceModel.paths);
        candidatePathCount = numel(candidateModel.paths);
        if referencePathCount ~= candidatePathCount
            comparisonFailure(sprintf('STAGE2_PATH_COUNT_MISMATCH_L%d', order));
        end
        if referenceModel.order ~= order || candidateModel.order ~= order || ...
                ~isequaln(referenceModel.valid, candidateModel.valid)
            comparisonFailure(sprintf('STAGE2_MODEL_VALIDITY_OR_ORDER_MISMATCH_L%d', order));
        end
        cpuValidity(order) = logical(referenceModel.valid);
        gpuValidity(order) = logical(candidateModel.valid);
        emptyInvalidModel = referencePathCount == 0 && ...
            ~logical(referenceModel.valid);
        if referencePathCount ~= order && ~emptyInvalidModel
            comparisonFailure(sprintf( ...
                'STAGE2_MODEL_PATH_STRUCTURE_INVALID_L%d', order));
        end
        if numel(referenceModel.relativePowerDb) ~= order || ...
                numel(candidateModel.relativePowerDb) ~= order
            comparisonFailure(sprintf('STAGE2_RELATIVE_POWER_SHAPE_MISMATCH_L%d', order));
        end
        oneWindow = accumulateNumericDiff(oneWindow, 'Rss', ...
            referenceModel.rss, candidateModel.rss);
        oneWindow = accumulateNumericDiff(oneWindow, 'Bic', ...
            referenceModel.bic, candidateModel.bic);
        oneWindow = accumulateNumericDiff(oneWindow, 'RelativePower', ...
            referenceModel.relativePowerDb, candidateModel.relativePowerDb);
        oneWindow = accumulateNumericDiff(oneWindow, 'MinimumMultipathPower', ...
            referenceModel.minimumMultipathPowerDb, ...
            candidateModel.minimumMultipathPowerDb);
        oneWindow = accumulateNumericDiff(oneWindow, 'Doppler', ...
            referenceModel.maximumRelativeDopplerHz, ...
            candidateModel.maximumRelativeDopplerHz);
        oneWindow = accumulateNumericDiff(oneWindow, 'MaximumCoherence', ...
            referenceModel.maximumCoherence, candidateModel.maximumCoherence);
        for pathIndex = 1:referencePathCount
            referencePath = referenceModel.paths(pathIndex);
            candidatePath = candidateModel.paths(pathIndex);
            validateFields(referencePath, {'delaySamples','dopplerHz', ...
                'alpha','score'}, 'STAGE2_REFERENCE_PATH');
            validateFields(candidatePath, {'delaySamples','dopplerHz', ...
                'alpha','score'}, 'STAGE2_CANDIDATE_PATH');
            oneWindow = accumulateNumericDiff(oneWindow, 'Delay', ...
                referencePath.delaySamples, candidatePath.delaySamples);
