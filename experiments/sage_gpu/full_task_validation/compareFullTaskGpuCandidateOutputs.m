function [matched, aggregate] = compareJointFits(referenceFits, candidateFits)
if ~iscell(referenceFits) || ~iscell(candidateFits) || ...
        numel(referenceFits) ~= numel(candidateFits)
    comparisonFailure('STAGE4_JOINT_FIT_COLLECTION_MISMATCH');
end
aggregate = emptyNumericDiffs();
for index = 1:numel(referenceFits)
    left = referenceFits{index};
    right = candidateFits{index};
    if isempty(left) || isempty(right)
        if ~isempty(left) || ~isempty(right)
            comparisonFailure('STAGE4_JOINT_FIT_PRESENCE_MISMATCH');
        end
        continue;
    end
    if ~isequaln(left.centerWindowId, right.centerWindowId) || ...
            ~isequaln(left.selectedOrder, right.selectedOrder) || ...
            numel(left.models) ~= 4 || numel(right.models) ~= 4
        comparisonFailure('STAGE4_JOINT_FIT_IDENTITY_MISMATCH');
    end
    for order = 1:numel(left.models)
        leftModel = left.models{order};
        rightModel = right.models{order};
        modelFields = {'paths','rss','bic','valid','relativePowerDb', ...
            'minimumMultipathPowerDb','maximumRelativeDopplerHz', ...
            'maximumCoherence','snapshotRss','snapshotWins'};
        validateFields(leftModel, modelFields, 'STAGE4_REFERENCE_JOINT_MODEL');
        validateFields(rightModel, modelFields, 'STAGE4_CANDIDATE_JOINT_MODEL');
        if ~isequaln(leftModel.valid, rightModel.valid) || ...
                ~isequaln(leftModel.snapshotWins, rightModel.snapshotWins) || ...
                numel(leftModel.paths) ~= numel(rightModel.paths)
            comparisonFailure(sprintf('STAGE4_JOINT_MODEL_STRUCTURE_MISMATCH_L%d', order));
        end
        aggregate = accumulateNumericDiff(aggregate, 'Rss', ...
            leftModel.rss, rightModel.rss);
        aggregate = accumulateNumericDiff(aggregate, 'Bic', ...
            leftModel.bic, rightModel.bic);
        aggregate = accumulateNumericDiff(aggregate, 'RelativePower', ...
            leftModel.relativePowerDb, rightModel.relativePowerDb);
        aggregate = accumulateNumericDiff(aggregate, 'MinimumMultipathPower', ...
            leftModel.minimumMultipathPowerDb, ...
            rightModel.minimumMultipathPowerDb);
        aggregate = accumulateNumericDiff(aggregate, 'Doppler', ...
            leftModel.maximumRelativeDopplerHz, ...
            rightModel.maximumRelativeDopplerHz);
        aggregate = accumulateNumericDiff(aggregate, 'MaximumCoherence', ...
            leftModel.maximumCoherence, rightModel.maximumCoherence);
        aggregate = accumulateNumericDiff(aggregate, 'Rss', ...
            leftModel.snapshotRss, rightModel.snapshotRss);
        if numel(leftModel.paths) > 0 && ...
                ~isequal(fieldnames(leftModel.paths), fieldnames(rightModel.paths))
            comparisonFailure('STAGE4_JOINT_PATH_SCHEMA_MISMATCH');
        end
        for pathIndex = 1:numel(leftModel.paths)
            leftPath = leftModel.paths(pathIndex);
            rightPath = rightModel.paths(pathIndex);
            validateFields(leftPath, {'delaySamples','dopplerHz','alpha','score'}, ...
                'STAGE4_REFERENCE_JOINT_PATH');
            validateFields(rightPath, {'delaySamples','dopplerHz','alpha','score'}, ...
                'STAGE4_CANDIDATE_JOINT_PATH');
            aggregate = accumulateNumericDiff(aggregate, 'Delay', ...
                leftPath.delaySamples, rightPath.delaySamples);
            aggregate = accumulateNumericDiff(aggregate, 'Doppler', ...
                leftPath.dopplerHz, rightPath.dopplerHz);
            aggregate = accumulateNumericDiff(aggregate, 'Alpha', ...
                leftPath.alpha, rightPath.alpha);
            aggregate = accumulateNumericDiff(aggregate, 'PathScore', ...
                leftPath.score, rightPath.score);
        end
    end
end
matched = true;
end

function [confirmed, pathCounts] = strictConfirmedRows(summary, paths)
confirmed = false(height(summary), 1);
pathCounts = zeros(height(summary), 1);
for row = 1:height(summary)
    centerId = summary.center_window_id(row);
    rows = paths.center_window_id == centerId;
    mpcCount = sum(logical(paths.is_multipath(rows)));
    pathCounts(row) = mpcCount;
    declaredCount = double(summary.joint_multipath_count(row));
    if declaredCount ~= mpcCount
        comparisonFailure('STAGE4_SUMMARY_PATH_MULTIPATH_COUNT_MISMATCH');
    end
    confirmed(row) = logical(summary.joint_valid(row)) && ...
        declaredCount > 0 && mpcCount == declaredCount;
end
end

