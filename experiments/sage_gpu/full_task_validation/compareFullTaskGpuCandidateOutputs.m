function comparison = compareFullTaskGpuCandidateOutputs( ...
    formalDir, candidateDir, taskSceneId, taskPrn, taskChannel, evidenceDirectory)

if nargin < 6
    evidenceDirectory = '';
end

if ~isfolder(formalDir) || ~isfolder(candidateDir)
    comparisonFailure('OUTPUT_DIRECTORY_MISSING');
end
identity = validateComparisonIdentity( ...
    formalDir, candidateDir, taskSceneId, taskPrn, taskChannel);
validateRequiredArtifactSet(formalDir, false);
validateRequiredArtifactSet(candidateDir, true);

stage0 = compareStage0(formalDir, candidateDir);
stage1 = compareStage1(formalDir, candidateDir);
[stage2, numericDiffs] = compareStage2(formalDir, candidateDir);
stage3 = compareStage3(formalDir, candidateDir);
stage4 = compareStage4(formalDir, candidateDir);

comparison = struct( ...
    'Passed', true, ...
    'TaskIdentity', identity, ...
    'Stage0', stage0, ...
    'Stage1', stage1, ...
    'Stage2', stage2, ...
    'Stage3', stage3, ...
    'Stage4', stage4, ...
    'NumericDiffs', numericDiffs, ...
    'ComparisonTimestampUtc', char(datetime('now', ...
        'TimeZone', 'UTC', 'Format', "yyyy-MM-dd'T'HH:mm:ssXXX")));
if ~isempty(evidenceDirectory)
    persistFullTaskComparisonEvidence(comparison, char(evidenceDirectory));
end
end

function identity = validateComparisonIdentity( ...
    formalDir, candidateDir, taskSceneId, taskPrn, taskChannel)
formalContext = readJson(fullfile(formalDir, 'run_context.json'));
candidateContext = readJson(fullfile(candidateDir, 'run_context.json'));
provenance = readJson(fullfile(candidateDir, 'candidate_provenance.json'));
requiredContextFields = {'sceneId', 'prn', 'trackingChannel', ...
    'samplingRateHz', 'projectRoot', 'rawFile', ...
    'trackingFile', 'telemetryFile'};
validateFields(formalContext, requiredContextFields, 'FORMAL_RUN_CONTEXT');
validateFields(candidateContext, requiredContextFields, 'CANDIDATE_RUN_CONTEXT');

expected = taskNamespace(taskSceneId, taskPrn, taskChannel);
if ~strcmp(char(formalContext.sceneId), taskSceneId) || ...
        double(formalContext.prn) ~= taskPrn || ...
        double(formalContext.trackingChannel) ~= taskChannel || ...
        double(formalContext.samplingRateHz) ~= 10230000
    comparisonFailure('FORMAL_TASK_IDENTITY_MISMATCH');
end
if ~strcmp(char(candidateContext.sceneId), taskSceneId) || ...
        double(candidateContext.prn) ~= taskPrn || ...
        double(candidateContext.trackingChannel) ~= taskChannel || ...
        double(candidateContext.samplingRateHz) ~= 10230000
    comparisonFailure('CANDIDATE_TASK_IDENTITY_MISMATCH');
end
if ~strcmp(normalizePath(formalContext.projectRoot), ...
        normalizePath(candidateContext.projectRoot))
    comparisonFailure('PROJECT_ROOT_IDENTITY_MISMATCH');
end
if ~strcmp(normalizePath(formalDir), ...
        normalizePath(fullfile(formalContext.projectRoot, ...
        strrep(expected.ReferenceNamespace, '/', filesep))))
    comparisonFailure('FORMAL_REFERENCE_NAMESPACE_MISMATCH');
end
if ~strcmp(normalizePath(candidateDir), ...
        normalizePath(fullfile(candidateContext.projectRoot, ...
        strrep(expected.CandidateNamespace, '/', filesep))))
    comparisonFailure('CANDIDATE_NAMESPACE_MISMATCH');
end
if ~isfield(candidateContext, 'referenceOutputDir') || ...
        ~strcmp(normalizePath(candidateContext.referenceOutputDir), ...
        normalizePath(formalDir))
    comparisonFailure('CANDIDATE_REFERENCE_OUTPUT_PATH_MISMATCH');
end
if ~isfield(candidateContext, 'referenceOutputNamespace') || ...
        ~strcmp(normalizeNamespace(candidateContext.referenceOutputNamespace), ...
        expected.ReferenceNamespace) || ...
        ~isfield(candidateContext, 'candidateOutputNamespace') || ...
        ~strcmp(normalizeNamespace(candidateContext.candidateOutputNamespace), ...
        expected.CandidateNamespace)
    comparisonFailure('CANDIDATE_RUN_CONTEXT_NAMESPACE_MISMATCH');
end
compareInputPathFields(formalContext, candidateContext);

provenanceFields = {'frozen_source_sha256', ...
    'gpu_candidate_source_sha256', ...
    'qualified_gpu_stage2_source_identity', 'execution_timestamp', ...
    'scene_id', 'prn', 'tracking_channel', 'resume', ...
    'reference_output_namespace', 'candidate_output_namespace', ...
    'gpu_identity'};
validateFields(provenance, provenanceFields, 'CANDIDATE_PROVENANCE');
if ~strcmpi(char(provenance.frozen_source_sha256), ...
        'bffc123c97af77f0a797f417d3866e9a34feab7729c5c1575352f53bc3571b9c')
    comparisonFailure('CANDIDATE_PROVENANCE_FROZEN_SHA_MISMATCH');
end
if isempty(regexp(char(provenance.gpu_candidate_source_sha256), ...
        '^[0-9a-fA-F]{64}$', 'once'))
    comparisonFailure('CANDIDATE_PROVENANCE_CANDIDATE_SHA_INVALID');
end
candidateSourcePath = fullfile(fileparts(mfilename('fullpath')), ...
    '..', 'full_task_candidate', ...
    'run_nav_sage_pipeline_gpu_candidate.m');
if ~strcmpi(char(provenance.gpu_candidate_source_sha256), ...
        sha256File(candidateSourcePath))
    comparisonFailure('CANDIDATE_PROVENANCE_CANDIDATE_SHA_MISMATCH');
end
qualified = provenance.qualified_gpu_stage2_source_identity;
validateFields(qualified, {'probeSha256', 'selectorSha256'}, ...
    'QUALIFIED_GPU_SOURCE_IDENTITY');
if ~strcmpi(char(qualified.probeSha256), ...
        'bfe56ad02c99240257fddd212ba43ee5606a81740b3dda716c5947c433cbfa88') || ...
        ~strcmpi(char(qualified.selectorSha256), ...
        'a40c6459e66a384e85053589b270c5d2e112363872153fbf46da5c56fd4bb1f5')
    comparisonFailure('CANDIDATE_PROVENANCE_QUALIFIED_SOURCE_MISMATCH');
end
if ~strcmp(char(provenance.scene_id), taskSceneId) || ...
        double(provenance.prn) ~= taskPrn || ...
        double(provenance.tracking_channel) ~= taskChannel || ...
        logical(provenance.resume) || ...
        ~strcmp(normalizeNamespace(provenance.reference_output_namespace), ...
        expected.ReferenceNamespace) || ...
        ~strcmp(normalizeNamespace(provenance.candidate_output_namespace), ...
        expected.CandidateNamespace) || isempty(char(provenance.execution_timestamp)) || ...
        isempty(char(provenance.gpu_identity))
    comparisonFailure('CANDIDATE_PROVENANCE_IDENTITY_MISMATCH');
end

formalContextMat = load(fullfile(formalDir, 'run_context.mat'));
candidateContextMat = load(fullfile(candidateDir, 'run_context.mat'));
validateFields(formalContextMat, {'runContext', 'cfg'}, ...
    'FORMAL_RUN_CONTEXT_MAT');
validateFields(candidateContextMat, {'runContext', 'cfg'}, ...
    'CANDIDATE_RUN_CONTEXT_MAT');
compareContextIdentity(formalContextMat.runContext, formalContext, ...
    'FORMAL_RUN_CONTEXT_MAT_JSON_MISMATCH');
compareContextIdentity(candidateContextMat.runContext, candidateContext, ...
    'CANDIDATE_RUN_CONTEXT_MAT_JSON_MISMATCH');
compareCfg(formalContextMat.cfg, candidateContextMat.cfg, ...
    'RUN_CONTEXT_CFG_MISMATCH');

identity = struct('Task', expected.Task, 'SceneId', taskSceneId, 'Prn', taskPrn, ...
    'TrackingChannel', taskChannel, 'SampleRateHz', 10230000, ...
    'FormalOutputDir', formalDir, 'CandidateOutputDir', candidateDir, ...
    'ReferenceNamespace', expected.ReferenceNamespace, ...
    'CandidateNamespace', expected.CandidateNamespace, ...
    'FrozenSourceSha256', char(provenance.frozen_source_sha256), ...
    'CandidateSourceSha256', char(provenance.gpu_candidate_source_sha256), ...
    'GpuIdentity', char(provenance.gpu_identity));
end

function namespaces = taskNamespace(sceneId, prn, channel)
if strcmp(sceneId, 'F1023_V70_D0117_P2') && prn == 28 && channel == 1
    task = 'TaskA';
    satellite = 'G28';
elseif strcmp(sceneId, 'F1023_V120_D0121_P2') && prn == 3 && channel == 2
    task = 'TaskB';
    satellite = 'G03';
else
    comparisonFailure('UNSUPPORTED_COMPARISON_TASK_IDENTITY');
end
namespaces = struct('Task', task, ...
    'ReferenceNamespace', sprintf( ...
        'scenes/%s/sage_results/rerun_20261003_frozen_v3/%s_ch%d', ...
        sceneId, satellite, channel), ...
    'CandidateNamespace', sprintf( ...
        'scenes/%s/sage_results/gpu_candidate_fulltask_20261005/%s_ch%d', ...
        sceneId, satellite, channel));
end

function compareInputPathFields(formalContext, candidateContext)
fields = {'rawFile', 'trackingFile', 'telemetryFile'};
for index = 1:numel(fields)
    field = fields{index};
    if ~isfield(formalContext, field) || ~isfield(candidateContext, field) || ...
            ~strcmp(normalizePath(formalContext.(field)), ...
            normalizePath(candidateContext.(field)))
        comparisonFailure(['INPUT_PATH_IDENTITY_MISMATCH_' upper(field)]);
    end
end
end

function compareContextIdentity(left, right, failureId)
fields = {'sceneId', 'prn', 'trackingChannel', 'samplingRateHz', ...
    'projectRoot', 'rawFile', 'trackingFile', 'telemetryFile'};
for index = 1:numel(fields)
    field = fields{index};
    if ~isfield(left, field) || ~isfield(right, field)
        comparisonFailure(failureId);
    end
    if ischar(left.(field)) || isstring(left.(field))
        matches = strcmp(normalizePath(left.(field)), normalizePath(right.(field)));
    else
        matches = isequaln(left.(field), right.(field));
    end
    if ~matches
        comparisonFailure(failureId);
    end
end
end

function compareCfg(referenceCfg, candidateCfg, failureId)
forbidden = {'frozen_source_sha256', 'gpu_candidate_source_sha256', ...
    'qualified_gpu_stage2_source_identity', 'candidate_output_namespace', ...
    'gpu_identity', 'execution_timestamp', 'candidate_provenance'};
for index = 1:numel(forbidden)
    if isfield(candidateCfg, forbidden{index})
        comparisonFailure('CANDIDATE_PROVENANCE_IN_CFG');
    end
end
if ~isequaln(referenceCfg, candidateCfg)
    comparisonFailure(failureId);
end
end

