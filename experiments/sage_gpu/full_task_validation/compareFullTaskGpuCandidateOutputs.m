function validateExistingEvidenceKeys(results, windows)
resultKeys = evidenceTaskKey(results);
if numel(unique(resultKeys)) ~= numel(resultKeys)
    comparisonFailure('COMPARISON_EVIDENCE_DUPLICATE_RESULT_KEY');
end
windowKeys = evidenceTaskKey(windows);
windowRowKeys = windowKeys + "|" + string(windows.window_id);
if numel(unique(windowRowKeys)) ~= numel(windowRowKeys)
    comparisonFailure('COMPARISON_EVIDENCE_DUPLICATE_WINDOW_TASK_KEY');
end
expectedWindowRows = str2double(results.stage2_evaluated_windows) > 0;
expectedWindowKeys = unique(resultKeys(expectedWindowRows));
if ~isequal(sort(unique(windowKeys)), sort(expectedWindowKeys))
    comparisonFailure('COMPARISON_EVIDENCE_KEY_SET_MISMATCH');
end
end

function validateEvidenceKeyAlignment(results, windows)
validateExistingEvidenceKeys(results, windows);
end

function keys = evidenceTaskKey(rows)
if height(rows) == 0
    keys = strings(0, 1);
    return;
end
keys = string(rows.task) + "|" + string(rows.scene_id) + "|" + ...
    string(rows.prn) + "|" + string(rows.tracking_channel);
end

