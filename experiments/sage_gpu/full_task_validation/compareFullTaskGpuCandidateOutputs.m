end

function text = numberText(value)
if ~isnumeric(value) || ~isscalar(value)
    comparisonFailure('COMPARISON_EVIDENCE_NONSCALAR_NUMBER');
end
if isnan(value)
    text = "NaN";
elseif isinf(value)
    if value > 0, text = "Inf"; else, text = "-Inf"; end
else
    text = string(sprintf('%.17g', double(value)));
end
end

function text = logicalText(value)
if ~isscalar(value)
    comparisonFailure('COMPARISON_EVIDENCE_NONSCALAR_LOGICAL');
end
if logical(value)
    text = "true";
else
    text = "false";
end
end

