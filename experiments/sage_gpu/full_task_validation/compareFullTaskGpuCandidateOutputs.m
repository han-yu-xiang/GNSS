function metrics = accumulateNumericDiff(metrics, name, reference, candidate)
if ~isnumeric(reference) || ~isnumeric(candidate) || ...
        ~isequal(size(reference), size(candidate))
    comparisonFailure(['NUMERIC_SHAPE_MISMATCH_' upper(name)]);
end
reference = double(reference);
candidate = double(candidate);
finiteReference = isfinite(reference);
finiteCandidate = isfinite(candidate);
if ~isequal(finiteReference, finiteCandidate) || ...
        ~isequaln(reference(~finiteReference), candidate(~finiteCandidate))
    comparisonFailure(['NUMERIC_NONFINITE_STATE_MISMATCH_' upper(name)]);
end
if ~any(finiteReference(:))
    return;
end
absolute = abs(candidate(finiteReference) - reference(finiteReference));
relative = absolute ./ max(abs(reference(finiteReference)), eps);
absField = ['max' name 'Abs'];
relField = ['max' name 'Rel'];
metrics.(absField) = max(metrics.(absField), max(absolute(:)));
metrics.(relField) = max(metrics.(relField), max(relative(:)));
end

function result = mergeNumericDiffs(left, right)
fields = fieldnames(left);
result = left;
for index = 1:numel(fields)
    result.(fields{index}) = max(left.(fields{index}), right.(fields{index}));
end
end

