function summary = validate_wp5_alpha_G32ch11_pilot( ...
    stage2MatPath, selectedPathsCsvPath, alphaCsvPath, summaryJsonPath)
% Independent pilot check. This function does not call the exporter.
loaded = load(stage2MatPath, 'stage2Fits');
assert(isfield(loaded, 'stage2Fits') && iscell(loaded.stage2Fits), ...
    'WP5:Stage2FitsMissing', 'stage2Fits cell array is absent.');
fits = loaded.stage2Fits;
source = readtable(selectedPathsCsvPath, 'TextType', 'string');
exported = readtable(alphaCsvPath, 'TextType', 'string');
assert(height(source) == height(exported), ...
    'WP5:RowCountMismatch', 'Export row count differs from source.');
sourceKeys = [double(source.window_id), double(source.path_id)];
exportKeys = [double(exported.window_id), double(exported.path_id)];
assert(isequal(sourceKeys, exportKeys), ...
    'WP5:IdentityOrOrderMismatch', 'Path identity or order changed.');
assert(size(unique(sourceKeys, 'rows'), 1) == height(source), ...
    'WP5:DuplicateSourceKey', 'Duplicate source path identity.');

columns = {'selected_L','is_multipath','delay_samples', ...
    'excess_delay_samples','excess_delay_chips', ...
    'excess_path_length_m','doppler_hz','doppler_offset_hz', ...
    'relative_power_db'};
columnErrors = struct();
for c = 1:numel(columns)
    name = columns{c};
    assert(ismember(name, source.Properties.VariableNames) ...
        && ismember(name, exported.Properties.VariableNames), ...
        'WP5:ScienceColumnMissing', 'Missing required column %s.', name);
    a = double(source.(name)); b = double(exported.(name));
    assert(isequal(isnan(a), isnan(b)), ...
        'WP5:ScienceNaNChanged', 'NaN pattern changed in %s.', name);
    finite = isfinite(a) & isfinite(b);
    if any(finite), err = max(abs(a(finite)-b(finite))); else, err = 0; end
    columnErrors.(name) = err;
    assert(err <= 1e-12, 'WP5:ScienceValueChanged', ...
        'Stage2 values changed in %s.', name);
end
assert(all(exported.run_id == ...
    "run_20261003_F1023_V70_D0117_P2_G32_ch11") ...
    && all(exported.scene_id == "F1023_V70_D0117_P2") ...
    && all(string(exported.prn) == "32") ...
    && all(double(exported.tracking_channel) == 11) ...
    && all(double(exported.sample_rate_hz) == 10230000), ...
    'WP5:RunIdentityMismatch', 'Exported run context is inconsistent.');
assert(all(lower(string(exported.frozen_sage_sha256)) == ...
    "bffc123c97af77f0a797f417d3866e9a34feab7729c5c1575352f53bc3571b9c") ...
    && all(lower(string(exported.stage2_mat_sha256)) == ...
    "fac53e460ac6f89e55e03bed3bacdfc4932b7eb00c246f9df66572e5465419f3") ...
    && all(lower(string(exported.selected_paths_csv_sha256)) == ...
    "845ba8379c80596b1248441e8b9ceeb18207c1b60a20361f0b5d6a1f271dd6b3") ...
    && all(exported.SAGE_ALPHA_IS_FROM_WINDOW_NORMALIZED_IQ == "YES"), ...
    'WP5:SourceProvenanceMismatch', ...
    'Output source hashes or normalization marker do not match preflight.');

n = height(source);
expectedAlpha = complex(nan(n,1),nan(n,1));
reason = strings(n,1);
for r = 1:n
    wid = double(source.window_id(r)); order = double(source.selected_L(r));
    pid = double(source.path_id(r)); matches = [];
    for f = 1:numel(fits)
        x = fits{f};
        if isstruct(x) && isfield(x,'windowId') && isscalar(x.windowId) ...
                && double(x.windowId) == wid
            matches(end+1) = f; %#ok<AGROW>
        end
    end
    if isempty(matches), reason(r) = "NO_STAGE2_FIT_FOR_WINDOW"; continue; end
    if numel(matches) ~= 1, reason(r) = "AMBIGUOUS_STAGE2_FIT_FOR_WINDOW"; continue; end
    x = fits{matches(1)};
    if ~isfield(x,'selectedOrder') || ~isscalar(x.selectedOrder) ...
            || ~isfinite(double(x.selectedOrder))
        reason(r) = "SELECTED_ORDER_MISSING_OR_INVALID"; continue;
    end
    if double(x.selectedOrder) ~= order, reason(r) = "SELECTED_ORDER_MISMATCH"; continue; end
    if ~isfield(x,'models') || ~iscell(x.models) ...
            || numel(x.models) < order || isempty(x.models{order})
        reason(r) = "SELECTED_MODEL_MISSING"; continue;
    end
    m = x.models{order};
    if ~isstruct(m) || ~isfield(m,'paths'), reason(r) = "SELECTED_MODEL_PATHS_MISSING"; continue; end
    if numel(m.paths) < pid, reason(r) = "STAGE2_PATH_ID_MISSING"; continue; end
    p = m.paths(pid);
    if ~isstruct(p) || ~isfield(p,'alpha'), reason(r) = "ALPHA_FIELD_MISSING"; continue; end
    a = p.alpha;
    if ~isnumeric(a) || ~isscalar(a) || ~isfinite(real(a)) || ~isfinite(imag(a))
        reason(r) = "ALPHA_NONFINITE_OR_INVALID"; continue;
    end
    expectedAlpha(r) = a; reason(r) = "NONE";
end

available = reason == "NONE";
assert(all(exported.alpha_status(available) == "AVAILABLE") ...
    && all(exported.alpha_missing_reason(available) == "NONE"), ...
    'WP5:AvailableStatusMismatch', 'Available-alpha status mismatch.');
assert(all(exported.alpha_status(~available) == "MISSING") ...
    && all(exported.alpha_missing_reason(~available) == reason(~available)), ...
    'WP5:MissingStatusMismatch', 'Missing alpha/reason was dropped or changed.');
re = double(exported.alpha_real(available));
im = double(exported.alpha_imag(available));
mag = double(exported.alpha_magnitude(available));
phase = double(exported.alpha_phase_rad(available));
realErr = maxOrZero(abs(re-real(expectedAlpha(available))));
imagErr = maxOrZero(abs(im-imag(expectedAlpha(available))));
magErr = maxOrZero(abs(mag-abs(expectedAlpha(available))));
phaseErr = maxOrZero(abs(angle(exp(1i*(phase-angle(expectedAlpha(available)))))));
assert(max([realErr imagErr magErr phaseErr]) <= 1e-12, ...
    'WP5:ComplexComponentMismatch', 'Complex alpha components mismatch.');
assert(all(isnan(double(exported.alpha_real(~available)))) ...
    && all(isnan(double(exported.alpha_imag(~available)))) ...
    && all(isnan(double(exported.alpha_magnitude(~available)))) ...
    && all(isnan(double(exported.alpha_phase_rad(~available)))), ...
    'WP5:MissingAlphaNotRetained', 'Missing alpha numeric values are not NaN.');

mpc = logical(source.is_multipath); powerPass = 0; powerMismatch = 0; powerUnchecked = 0;
for r = 1:n
    if ~available(r), powerUnchecked = powerUnchecked+1; continue; end
    group = find(double(source.window_id) == double(source.window_id(r)));
    direct = group(double(source.path_id(group)) == 1);
    assert(numel(direct) == 1, 'WP5:DirectPathIdentity', ...
        'Each window must have exactly one path_id 1.');
    if ~available(direct), powerUnchecked = powerUnchecked+1; continue; end
    observed = double(source.relative_power_db(r));
    if ~isfinite(observed), powerUnchecked = powerUnchecked+1; continue; end
    predicted = 10*log10(max(abs(expectedAlpha(r))^2,realmin) ...
        / max(abs(expectedAlpha(direct))^2,realmin));
    if abs(predicted-observed) <= 1e-6
        powerPass = powerPass+1;
        assert(exported.relative_power_check_status(r) == "PASS", ...
            'WP5:PowerStatusMismatch', 'Expected relative-power PASS.');
    else
        powerMismatch = powerMismatch+1;
        assert(exported.relative_power_check_status(r) == "MISMATCH", ...
            'WP5:PowerStatusMismatch', 'Expected relative-power mismatch.');
    end
end

assert(n == 344 && numel(unique(double(source.window_id))) == 117 ...
    && nnz(mpc) == 227 && nnz(~mpc) == 117, ...
    'WP5:PilotCensusMismatch', 'Pilot counts differ from verified census.');
special = repmat(struct('window_id',0,'selected_L',0, ...
    'path_ids',[],'mpc_count',0),2,1);
candidateIds = [38 1007];
for j = 1:2
    rows = find(double(source.window_id) == candidateIds(j));
    assert(~isempty(rows), 'WP5:CandidateWindowAbsent', ...
        'Candidate window %d is absent.', candidateIds(j));
    special(j).window_id = candidateIds(j);
    special(j).selected_L = double(source.selected_L(rows(1)));
    special(j).path_ids = double(source.path_id(rows)).';
    special(j).mpc_count = nnz(mpc(rows));
end
summary = struct('run_id',"run_20261003_F1023_V70_D0117_P2_G32_ch11", ...
    'path_rows',n,'unique_windows',numel(unique(double(source.window_id))), ...
    'mpc_rows',nnz(mpc),'direct_reference_rows',nnz(~mpc), ...
    'valid_alpha_rows',nnz(available), ...
    'missing_or_invalid_alpha_rows',nnz(~available), ...
    'mpc_valid_alpha_rows',nnz(available & mpc), ...
    'mpc_missing_or_invalid_alpha_rows',nnz(~available & mpc), ...
    'relative_power_check_pass',powerPass, ...
    'relative_power_check_mismatch',powerMismatch, ...
    'relative_power_check_not_checked',powerUnchecked, ...
    'real_max_abs_error',realErr,'imag_max_abs_error',imagErr, ...
    'magnitude_max_abs_error',magErr, ...
    'phase_max_wrapped_error_rad',phaseErr, ...
    'stage2_parameter_max_abs_errors',columnErrors, ...
    'candidate_windows',special,'missing_reasons',unique(reason(~available)), ...
    'independent_validation',"PASS");
fid = fopen(summaryJsonPath,'w');
assert(fid >= 0, 'WP5:SummaryCreateFailed', 'Cannot create validation summary.');
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(summary,'PrettyPrint',true),'char');
fprintf('%s\n',jsonencode(summary,'PrettyPrint',true));
end

function value = maxOrZero(values)
if isempty(values), value = 0; else, value = max(values); end
end
